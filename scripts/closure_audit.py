#!/usr/bin/env python3
"""Family-by-family closure audit against the method children, the counterpart inventory and
the release-scope reconciliation.

The audit reads three generated inventories and the sources they rest on:

  parity/method_children/children.toml    every leaf, with the fixture and consumer it names
  parity/counterparts.toml                every method x {static, temporal} x {frequentist, bayesian}
  parity/release_scope/reconciliation.toml  every scope row matched to its owner, fixtures, consumer

and writes parity/release_scope/closure_audit.toml, a report listing

  missing_attempt     counterpart quadrants that still carry no executing attempt, with the
                      next attempt each one names
  missing_consumer    children whose fixture or artifact consumer does not resolve, per child
  adjusted_claim      narrowed promises: the reduced claim, the failed attempt and the next one
  unresolved_mandatory  mandatory scope rows with a missing owner, fixture or consumer
  audited_attempt     the shipped joint-response claims, the flagship rows and every pending or failed
                      attempt of the release scope

    python3 scripts/closure_audit.py              # rewrite the report
    python3 scripts/closure_audit.py --check      # fail when the report is stale
    python3 scripts/closure_audit.py --require-zero   # release: fail while anything is unresolved
    python3 scripts/closure_audit.py --self-test
"""

from __future__ import annotations

import json
import sys
import tomllib
from collections import Counter
from pathlib import Path

from _repo import REPO_ROOT as ROOT
from _repo import ensure_scripts_on_path

ensure_scripts_on_path()
import check_method_children as method_children  # noqa: E402
import generate_counterparts as counterparts  # noqa: E402
import reconcile_release_scope as reconciliation  # noqa: E402
from method_evidence import Evidence  # noqa: E402

OUTPUT = "parity/release_scope/closure_audit.toml"
ATTEMPT_SOURCES = ("attempt", "joint_response")
HEADER = (
    "# Generated by scripts/closure_audit.py; do not edit.\n"
    "# Family-by-family closure audit of the method children, the counterpart inventory and the\n"
    "# release-scope reconciliation. Zero unresolved rows is the release condition\n"
    "# (python3 scripts/closure_audit.py --require-zero).\n"
)


def family(identifier: str) -> str:
    return identifier.split(".")[0]


def audit(
    children: list[dict],
    evidence_findings: dict[str, list[str]],
    rows: list[dict],
    records: list[dict],
    audited: set[str] | None = None,
) -> dict:
    """The report as plain data; `evidence_findings` maps a child id to its unresolved evidence."""
    missing_attempt = []
    adjusted = []
    for row in rows:
        side = f"{row['design']}.{row['inference']}"
        if row["status"] == "closed_with_next_attempt":
            missing_attempt.append(
                {
                    "id": row["id"],
                    "method": row["method"],
                    "side": side,
                    "route": row["route"],
                    "next_attempt": row["next_attempt"] or "unnamed",
                }
            )
        if row["closure"] == "narrowed_promise":
            adjusted.append(
                {
                    "id": row["id"],
                    "method": row["method"],
                    "side": side,
                    "status": row["status"],
                    "reason": row["reason"],
                    "next_attempt": row["next_attempt"],
                }
            )
    parents = {child["id"]: child.get("parent", family(child["id"])) for child in children}
    missing_consumer = [
        {"id": cid, "family": parents.get(cid, family(cid)), "reasons": reasons}
        for cid, reasons in sorted(evidence_findings.items())
        if reasons
    ]
    unresolved = [
        {"id": r["id"], "list": r["list"], "missing": r["missing"]}
        for r in records
        if r["mandatory"] and r["status"] != "reconciled"
    ]
    attempts = [
        {"id": r["id"], "status": r["status"], "list": r["list"]}
        for r in records
        if audited is not None and r["id"] in audited
    ]
    by_family: dict[str, dict] = {}
    for child in children:
        entry = by_family.setdefault(
            child.get("parent", family(child["id"])),
            {"children": 0, "gaps": Counter(), "unresolved_evidence": 0},
        )
        entry["children"] += 1
        entry["gaps"][child["gap"]] += 1
        entry["unresolved_evidence"] += bool(evidence_findings.get(child["id"]))
    return {
        "families": by_family,
        "missing_attempt": missing_attempt,
        "missing_consumer": missing_consumer,
        "adjusted_claim": adjusted,
        "unresolved_mandatory": unresolved,
        "audited_attempt": sorted(attempts, key=lambda a: a["id"]),
    }


def quote(value: object) -> str:
    return json.dumps(value, ensure_ascii=False)


def render(report: dict) -> str:
    out = [HEADER, "schema = 1"]
    for key in ("missing_attempt", "missing_consumer", "adjusted_claim", "unresolved_mandatory"):
        out.append(f"{key}s = {len(report[key])}")
    out.append(f"families = {len(report['families'])}")
    out.append("")
    for name, entry in sorted(report["families"].items()):
        gaps = ", ".join(f"{gap} = {count}" for gap, count in sorted(entry["gaps"].items()))
        out += [
            "[[family]]",
            f"id = {quote(name)}",
            f"children = {entry['children']}",
            f"unresolved_evidence = {entry['unresolved_evidence']}",
            f"gaps = {quote(gaps)}",
            "",
        ]
    for row in report["missing_attempt"]:
        out += [
            "[[missing_attempt]]",
            f"id = {quote(row['id'])}",
            f"method = {quote(row['method'])}",
            f"side = {quote(row['side'])}",
            f"route = {quote(row['route'])}",
            f"next_attempt = {quote(row['next_attempt'])}",
            "",
        ]
    for row in report["missing_consumer"]:
        out += [
            "[[missing_consumer]]",
            f"id = {quote(row['id'])}",
            f"family = {quote(row['family'])}",
            f"reasons = {quote(row['reasons'])}",
            "",
        ]
    for row in report["adjusted_claim"]:
        out += [
            "[[adjusted_claim]]",
            f"id = {quote(row['id'])}",
            f"method = {quote(row['method'])}",
            f"side = {quote(row['side'])}",
            f"status = {quote(row['status'])}",
            f"reason = {quote(row['reason'])}",
            f"next_attempt = {quote(row['next_attempt'])}",
            "",
        ]
    for row in report["unresolved_mandatory"]:
        out += [
            "[[unresolved_mandatory]]",
            f"id = {quote(row['id'])}",
            f"list = {quote(row['list'])}",
            f"missing = {quote(row['missing'])}",
            "",
        ]
    for row in report["audited_attempt"]:
        out += [
            "[[audited_attempt]]",
            f"id = {quote(row['id'])}",
            f"status = {quote(row['status'])}",
            f"list = {quote(row['list'])}",
            "",
        ]
    return "\n".join(out)


def release_findings(report: dict) -> list[str]:
    """What stops a release: the audit's own unresolved rows."""
    out = [
        f"missing consumer: {r['id']}: {'; '.join(r['reasons'])}"
        for r in report["missing_consumer"]
    ]
    out += [
        f"unresolved mandatory row: {r['id']}: {'; '.join(r['missing'])}"
        for r in report["unresolved_mandatory"]
    ]
    out += [
        f"missing attempt: {r['id']} ({r['side']}) next attempt: {r['next_attempt']}"
        for r in report["missing_attempt"]
    ]
    out += [
        f"narrowed promise without a reason and a next attempt: {r['id']}"
        for r in report["adjusted_claim"]
        if not (r["reason"].strip() and r["next_attempt"].strip())
    ]
    return out


def audited_ids(scope: list[dict]) -> set[str]:
    """Scope rows the audit reports on by name: every attempt, its sibling rows and the flagship."""
    families = {e["id"].split(".")[0] for e in scope if e["source"] in ATTEMPT_SOURCES}
    return {
        e["id"]
        for e in scope
        if e["source"] in ATTEMPT_SOURCES
        or e["id"].split(".")[0] in families
        or e.get("obligation") == "flagship"
    }


def gather(root: Path = ROOT) -> dict:
    ev = Evidence(root)
    children = tomllib.loads(ev.text(method_children.CHILDREN))["child"]
    routes = method_children.manifest_ids(ev)
    per_child = {c["id"]: method_children.child_findings(ev, c, routes) for c in children}
    rows = counterparts.build()
    records = reconciliation.gather(ev.repo)
    scope = tomllib.loads(ev.text(reconciliation.SCOPE))["entry"]
    return audit(children, per_child, rows, records, audited_ids(scope))


def self_test() -> int:
    child = {"id": "FAM.method.static.bayesian", "gap": "none"}
    rows = [
        {
            "id": "r1",
            "method": "M",
            "design": "static",
            "inference": "bayesian",
            "route": "a",
            "status": "closed_with_next_attempt",
            "closure": "narrowed_promise",
            "reason": "no dependence law",
            "next_attempt": "derive the likelihood",
        },
        {
            "id": "r2",
            "method": "M",
            "design": "temporal",
            "inference": "bayesian",
            "route": "b",
            "status": "licensed",
            "closure": "delivered",
            "reason": "",
            "next_attempt": "",
        },
    ]
    records = [
        {
            "id": "ATT.static.bayesian",
            "list": "mandatory",
            "mandatory": True,
            "status": "reconciled",
            "missing": [],
        },
        {
            "id": "OTHER.static.bayesian",
            "list": "mandatory",
            "mandatory": True,
            "status": "open",
            "missing": ["no consumer is named"],
        },
    ]
    report = audit(
        [child],
        {child["id"]: ["consumer 'FAMILY' is not a path"]},
        rows,
        records,
        {"ATT.static.bayesian"},
    )
    assert [r["id"] for r in report["missing_attempt"]] == ["r1"]
    assert report["adjusted_claim"][0]["next_attempt"] == "derive the likelihood"
    assert report["missing_consumer"][0]["id"] == child["id"]
    assert report["unresolved_mandatory"][0]["missing"] == ["no consumer is named"]
    assert [a["id"] for a in report["audited_attempt"]] == ["ATT.static.bayesian"]
    assert len(release_findings(report)) == 3, release_findings(report)
    clean = audit([child], {}, rows[1:], records[:1])
    assert release_findings(clean) == []
    assert render(report) == render(report) and "[[missing_attempt]]" in render(report)
    print("closure_audit self-test passed")
    return 0


def main(argv: list[str]) -> int:
    if "--self-test" in argv:
        return self_test()
    report = gather()
    text = render(report)
    output = ROOT / OUTPUT
    if "--check" in argv or "--require-zero" in argv:
        stored = output.read_text(encoding="utf-8") if output.is_file() else None
        if stored != text:
            print(f"FAIL: {OUTPUT} is stale; run python3 scripts/closure_audit.py")
            return 1
        if "--require-zero" in argv:
            findings = release_findings(report)
            for line in findings:
                print(f"FAIL: {line}")
            print(f"closure audit: {len(findings)} unresolved row(s)")
            return 1 if findings else 0
        print(f"closure audit current: {len(report['families'])} families")
        return 0
    output.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}: {len(release_findings(report))} unresolved row(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
