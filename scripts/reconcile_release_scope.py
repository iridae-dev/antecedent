#!/usr/bin/env python3
"""Reconcile the release-scope registry with the code.

Every row of parity/release_scope/scope.toml is matched to evidence:

  route      the licensed route exists in the route manifest, its lowering is registered in
             parity/licensed_routes.toml, and a compiler source file reads that lowering
  owner      every owning path exists and, where a symbol is named, defines it
  fixture    every acceptance fixture exists (a `path::name` fixture also names a real
             function or test) and is run by a registered test: a Cargo test target or suite
             member, a python test, a gate script, a registered unit-test source, or a file
             that one of those reads
  consumer   a source file other than the owner reads the artifact (a named symbol is found
             there, or the route's lowering is read by the compiler)

A row takes its evidence from its own fields (`owner`, `acceptance_fixtures`, `consumer`), from
its method child in parity/method_children/children.toml, from its manifest route, and from
parity/release_scope/evidence.toml, which holds the evidence of rows that have neither.

Each row is `reconciled` or `open`; an open row names the exact missing element. The result is
written to parity/release_scope/reconciliation.toml. The check fails when

  stale      the generated reconciliation differs from the sources
  dangling   a row names an owner, fixture or consumer that does not exist or is not run
  open       a mandatory row has a missing fixture, owner or consumer

    python3 scripts/reconcile_release_scope.py            # regenerate the reconciliation
    python3 scripts/reconcile_release_scope.py --check
    python3 scripts/reconcile_release_scope.py --report   # open rows and counts
    python3 scripts/reconcile_release_scope.py --self-test
"""

from __future__ import annotations

import re
import subprocess
import sys
import tomllib
from collections import Counter, defaultdict
from pathlib import Path

from _repo import REPO_ROOT as ROOT

SCOPE = "parity/release_scope/scope.toml"
EVIDENCE = "parity/release_scope/evidence.toml"
OUTPUT = "parity/release_scope/reconciliation.toml"
MANIFEST = "parity/capabilities/route_manifest.toml"
CHILDREN = "parity/method_children/children.toml"
LICENSED = "parity/licensed_routes.toml"
REGISTRY = "parity/v3_test_registry.toml"
UNLISTED = {"", "unlisted", "none"}
ROOTS = "crates|python|parity|scripts|docs|examples|conformance|provenance|tests"
PATH_TOKEN = re.compile(rf"\b(?:{ROOTS})(?:/[A-Za-z0-9_.\-]+)+/?(?:::[A-Za-z0-9_]+)*")
# A row that is a reviewed record rather than a route needs an owner and a consumer only when it
# is mandatory; the research list is reported but never fails.
HEADER = (
    "# Generated by scripts/reconcile_release_scope.py; do not edit.\n"
    "# Each row of parity/release_scope/scope.toml matched to the code. `open` rows name the exact\n"
    "# missing element. Regenerate with: python3 scripts/reconcile_release_scope.py\n"
)


class Repo:
    """Read-only view of the files the reconciliation matches against."""

    def __init__(self, root: Path) -> None:
        self.root = root
        self._text: dict[str, str | None] = {}
        self._grep: dict[str, list[str]] = {}
        self._corpus: dict[str, str] | None = None
        self._cargo: dict[str, dict] = {}
        self._registry: set[str] | None = None
        self._registered: dict[str, bool] = {}

    def load(self, rel: str) -> dict:
        return tomllib.loads((self.root / rel).read_text(encoding="utf-8"))

    def exists(self, rel: str) -> bool:
        return (self.root / rel).exists()

    def text(self, rel: str) -> str | None:
        if rel not in self._text:
            path = self.root / rel
            self._text[rel] = (
                path.read_text(encoding="utf-8", errors="replace") if path.is_file() else None
            )
        return self._text[rel]

    def sources_reading(self, symbol: str) -> list[str]:
        """Rust and python sources under crates/ and python/antecedent that mention the symbol."""
        if symbol not in self._grep:
            found: list[str] = []
            for base in ("crates", "python/antecedent"):
                if not (self.root / base).is_dir():
                    continue
                proc = subprocess.run(
                    [
                        "grep",
                        "-rlw",
                        "--include=*.rs",
                        "--include=*.py",
                        "--exclude-dir=tests",
                        "--exclude-dir=target",
                        "--",
                        symbol,
                        base,
                    ],
                    cwd=self.root,
                    capture_output=True,
                    text=True,
                    check=False,
                )
                found.extend(sorted(proc.stdout.split()))
            self._grep[symbol] = found
        return self._grep[symbol]

    def cargo(self, crate_dir: str) -> dict:
        if crate_dir not in self._cargo:
            path = self.root / crate_dir / "Cargo.toml"
            self._cargo[crate_dir] = (
                tomllib.loads(path.read_text(encoding="utf-8")) if path.is_file() else {}
            )
        return self._cargo[crate_dir]

    def registry_paths(self) -> set[str]:
        if self._registry is None:
            try:
                data = self.load(REGISTRY)
            except (OSError, tomllib.TOMLDecodeError):
                data = {}
            self._registry = {t.get("path", "") for t in data.get("test", [])}
        return self._registry

    def corpus(self) -> dict[str, str]:
        """Sources that run things: registered Rust tests, python tests, scripts and gates."""
        if self._corpus is None:
            files: dict[str, str] = {}
            patterns = (
                "crates/*/tests/*.rs",
                "crates/*/tests/**/*.rs",
                "python/tests/*.py",
                "python/tests/**/*.py",
                "scripts/*.py",
                "scripts/*.sh",
                "examples/**/*.py",
                "examples/**/*.rs",
            )
            for pattern in patterns:
                for path in sorted(self.root.glob(pattern)):
                    rel = path.relative_to(self.root).as_posix()
                    if rel in files or not path.is_file():
                        continue
                    if rel.endswith(".rs") and not self.rust_test_registered(rel):
                        continue
                    files[rel] = path.read_text(encoding="utf-8", errors="replace")
            self._corpus = files
        return self._corpus

    def rust_test_registered(self, rel: str) -> bool:
        match = re.match(r"(crates/[^/]+)/(tests/.+\.rs)$", rel)
        return bool(match) and match.group(2) in self.crate_tests(match.group(1))

    def crate_tests(self, crate_dir: str) -> set[str]:
        """Crate-relative test sources that cargo compiles into some test target."""
        if crate_dir in self._registered:
            return self._registered[crate_dir]
        manifest = self.cargo(crate_dir)
        explicit = {e.get("path", f"tests/{e.get('name')}.rs") for e in manifest.get("test", [])}
        tests_dir = self.root / crate_dir / "tests"
        found = set(explicit)
        if manifest.get("package", {}).get("autotests", True):
            found |= {f"tests/{p.name}" for p in tests_dir.glob("*.rs")}
        suite_map = tests_dir / "suite_map.txt"
        if suite_map.is_file():
            for raw in suite_map.read_text(encoding="utf-8").splitlines():
                line = raw.strip()
                if not line or line.startswith("#") or ":" not in line:
                    continue
                suite, rest = line.split(":", 1)
                if f"tests/{suite.strip()}.rs" in explicit:
                    found |= {
                        f"tests/{part.strip()}.rs" for part in rest.split(",") if part.strip()
                    }
        # a module that a compiled test pulls in with #[path = "..."] runs with it
        pending = list(found)
        while pending:
            host = pending.pop()
            body = self.text(f"{crate_dir}/{host}") or ""
            for included in re.findall(r'#\[path\s*=\s*"([^"]+\.rs)"\]', body):
                target = f"tests/{included.rsplit('/', 1)[-1]}"
                if target not in found and (self.root / crate_dir / target).is_file():
                    found.add(target)
                    pending.append(target)
        self._registered[crate_dir] = found
        return found


def split_fixture(token: str) -> tuple[str, str | None]:
    path, _, name = token.partition("::")
    return path, (name.rsplit("::", 1)[-1] if name else None)


def paths_in(value: object) -> list[str]:
    """Path-like tokens named by a string or a list of strings; prose is ignored."""
    parts = [value] if isinstance(value, str) else [v for v in (value or []) if isinstance(v, str)]
    found: list[str] = []
    for part in parts:
        if part.strip() in UNLISTED:
            continue
        found.extend(
            m.group(0).rstrip("/") if "::" not in m.group(0) else m.group(0)
            for m in PATH_TOKEN.finditer(part)
        )
    return list(dict.fromkeys(found))


def record_evidence(repo: Repo, path: str) -> list[str]:
    """Test citations held by a fixture record: every `evidence` and `test` entry in it."""
    try:
        data = tomllib.loads(repo.text(path) or "")
    except tomllib.TOMLDecodeError:
        return []
    found: list[str] = []

    def walk(node: object, key: str = "") -> None:
        if isinstance(node, dict):
            for name, value in node.items():
                walk(value, name)
        elif isinstance(node, list):
            for value in node:
                walk(value, key)
        elif isinstance(node, str) and key in ("evidence", "test", "tests", "public_workflow"):
            found.extend(paths_in(node))

    walk(data)
    return list(dict.fromkeys(found))


def fixture_problem(repo: Repo, token: str) -> str | None:
    """None when the fixture exists and a registered test runs it, else the exact reason."""
    path, name = split_fixture(token)
    if not repo.exists(path):
        return f"fixture {path} does not exist"
    if name is not None:
        body = repo.text(path)
        if body is None or not re.search(rf"\b(?:fn|def|class)\s+{re.escape(name)}\b", body):
            return f"fixture {path} defines no `{name}`"
    if path.endswith(".rs") and "/tests/" in path:
        return (
            None
            if repo.rust_test_registered(path)
            else f"fixture {path} is not a registered test target"
        )
    if path.endswith(".rs") and "/src/" in path:
        body = repo.text(path) or ""
        if path in repo.registry_paths() or "#[cfg(test)]" in body or "#[test]" in body:
            return None
        return f"fixture {path} holds no unit tests and is not in the test registry"
    if re.match(r"python/tests/.+\.py$", path):
        return None
    if path.endswith(".toml"):
        listed = record_evidence(repo, path)
        if listed:
            for token in listed:
                if "::" not in token and "/src/" in token:  # a cited source file, not a test
                    if not repo.exists(token):
                        return f"fixture record {path} cites {token}, which does not exist"
                    continue
                problem = fixture_problem(repo, token)
                if problem:
                    return f"fixture record {path} cites evidence that fails: {problem}"
            return None
    if path.startswith("examples/") and path.endswith(".py"):
        catalog = repo.text("examples/catalog.toml") or ""
        if path in catalog and repo.rust_test_registered("crates/antecedent/tests/examples_run.rs"):
            return None
    base = path.rsplit("/", 1)[-1]
    stem = base.rsplit(".", 1)[0]
    for rel, body in repo.corpus().items():
        if rel == path:
            continue
        if path in body or base in body:
            return None
        # a golden file a test finds by scenario name, in a directory the test names
        if "/golden/" in path and f'"{stem}"' in body:
            return None
    if path.startswith("scripts/") and path.endswith(".py"):
        gates = (repo.text("scripts/gate_selftests.sh") or "") + (
            repo.text("scripts/gate_release.sh") or ""
        )
        if base in gates:
            return None
    return f"fixture {path} is read by no registered test, gate or script"


def owner_problem(repo: Repo, owner: str, symbol: str | None = None) -> str | None:
    path = owner.split(" ")[0].rstrip("/")
    if not repo.exists(path):
        return f"owner {path} does not exist"
    if symbol:
        body = repo.text(path)
        if body is None:  # a directory owner defines the symbol somewhere beneath it
            proc = subprocess.run(
                ["grep", "-rlw", "--", symbol, path],
                cwd=repo.root,
                capture_output=True,
                text=True,
                check=False,
            )
            if not proc.stdout.strip():
                return f"owner {path} defines no `{symbol}`"
        elif not re.search(rf"\b{re.escape(symbol)}\b", body):
            return f"owner {path} defines no `{symbol}`"
    return None


SYMBOL = re.compile(
    r"[A-Za-z_][A-Za-z0-9_]*(?:::[A-Za-z_][A-Za-z0-9_]*)+|[a-z][a-z0-9]*(?:_[a-z0-9]+)+|[A-Z][a-z0-9]+(?:[A-Z][a-z0-9]+)+"
)


def consumer_problem(
    repo: Repo, texts: list[str], symbol: str | None, owners: list[str]
) -> str | None:
    """A consumer is a path that exists or a symbol that source code outside tests reads."""
    owner_set = {o.split(" ")[0].rstrip("/") for o in owners}
    paths = paths_in(texts)
    for path in paths:
        if not repo.exists(split_fixture(path)[0]):
            return f"consumer {split_fixture(path)[0]} does not exist"
    readers = [p for p in paths if split_fixture(p)[0] not in owner_set]
    if readers:
        return None
    symbols = [symbol] if symbol else []
    for text in texts:
        if text.strip() in UNLISTED:
            continue
        symbols.extend(m.group(0).rsplit("::", 1)[-1] for m in SYMBOL.finditer(text))
    if not paths and not symbols and not any(t.strip() not in UNLISTED for t in texts):
        return "no consumer is named"
    for name in symbols:
        if (name == symbol or len(name) > 5) and any(
            src not in owner_set for src in repo.sources_reading(name)
        ):
            return None
    if paths:
        return "the only consumer named is the owner itself"
    return (
        f"no source reads the consumer named ({texts[0][:60]!r}...)"
        if texts
        else "no consumer is named"
    )


def route_lowerings(licensed: dict) -> dict[tuple[str, str], set[str]]:
    found: dict[tuple[str, str], set[str]] = defaultdict(set)
    for row in licensed.get("route", []):
        target, graph = row["coordinate"].split(":")[:2]
        found[(target, graph)].add(row["lowering"])
    return found


def gather(repo: Repo) -> list[dict]:
    """One reconciled record per scope row."""
    scope = repo.load(SCOPE)["entry"]
    manifest = {r["id"]: r for r in repo.load(MANIFEST)["route"]}
    children = {c["id"]: c for c in repo.load(CHILDREN)["child"]}
    lowerings = route_lowerings(repo.load(LICENSED))
    evidence = repo.load(EVIDENCE) if repo.exists(EVIDENCE) else {}
    overlay = {r["id"]: r for r in evidence.get("row", [])}
    if evidence.get("awaiting"):
        raise SystemExit(
            f"{EVIDENCE}: an `awaiting` table is no longer honoured; name the owner, fixtures and "
            "consumer of the row instead"
        )
    records = []
    for row in scope:
        rid = row["id"]
        mandatory = row["list"] == "mandatory"
        missing: list[str] = []
        owners: list[str] = []
        fixtures: list[str] = []
        consumers: list[str] = []
        symbol: str | None = None
        owner_symbol: str | None = None
        route = manifest.get(rid) if row["source"] == "route_manifest" else None
        child = children.get(rid) if row["source"] == "method_children" else None
        extra = overlay.get(rid, {})
        if row["source"] == "route_manifest":
            if route is None:
                missing.append(f"route {rid} is not in the route manifest")
            else:
                if route["status"] != "licensed":
                    missing.append(f"route is `{route['status']}` in the manifest, not licensed")
                owners.append(route["owning_module"].split(" ")[0])
                lowered = sorted(lowerings.get((route["target"], route["graph_class"]), ()))
                if not lowered:
                    missing.append(
                        "no lowering is registered for the route in parity/licensed_routes.toml"
                    )
                else:
                    symbol = lowered[0]
                    pass
                fixtures.extend(paths_in(route.get("retained_route_test", "")))
                fixtures.append("crates/antecedent/tests/licensed_compiler.rs")
                consumers.append(route.get("artifact_consumer", ""))
        elif row["source"] == "method_children":
            if child is None:
                missing.append(f"child {rid} is not in {CHILDREN}")
            else:
                route_id = child["route"]
                if (
                    route_id not in UNLISTED
                    and not repo.exists(route_id.split(" ")[0])
                    and route_id not in manifest
                ):
                    missing.append(f"route {route_id} is not in the route manifest")
                owners.extend(paths_in(child["module"]))
                owners.extend(paths_in(child["owner"]))
                fixtures.extend(paths_in(child["fixtures"]))
                consumers.append(child["consumer"])
        for listed in row.get("children", []):
            if listed not in children:
                missing.append(f"child {listed} is not in {CHILDREN}")
        carrier = row.get("carrier")
        if carrier and carrier not in manifest:
            missing.append(f"carrier route {carrier} is not in the route manifest")
        if str(row.get("implementation_evidence", "")).endswith("acceptance.toml") and repo.exists(
            row["implementation_evidence"]
        ):
            capabilities = repo.load(row["implementation_evidence"])
            by_id = {c["id"]: c for c in capabilities.get("capability", [])}
            members = [c for k, c in by_id.items() if k == rid or k.startswith(rid + ".")]
            integrated = by_id.get("integrated_families", {})
            if not members:
                missing.append(f"{row['implementation_evidence']} holds no capability {rid}")
            for member in members:
                owners.extend(member.get("rust", []))
                fixtures.extend(
                    p
                    for p in member.get("rust", [])
                    if p.endswith(".rs") and "#[test]" in (repo.text(p) or "")
                )
            fixtures.extend(integrated.get("tests", []))
            fixtures.extend(p for p in [capabilities.get("python_acceptance", "")] if p)
            consumers.extend(integrated.get("rust", []))
        # evidence declared on the row itself, then the overlay
        for source in (row, extra):
            owners.extend(paths_in(source.get("owner", "")))
            fixtures.extend(
                paths_in(source.get("acceptance_fixtures", []))
                + paths_in(source.get("fixtures", []))
            )
            consumers.extend(source.get("consumer_paths", []))
            consumers.extend(
                [source["consumer"]] if isinstance(source.get("consumer"), str) else []
            )
            symbol = source.get("consumer_symbol", symbol)
            owner_symbol = source.get("owner_symbol", owner_symbol)
        owners = list(dict.fromkeys(owners))
        fixtures = list(dict.fromkeys(fixtures))
        consumers = list(dict.fromkeys(consumers))
        if not owners:
            missing.append("no owner is named")
        for owner in owners:
            problem = owner_problem(repo, owner, owner_symbol if owner is owners[0] else None)
            if problem:
                missing.append(problem)
        if not fixtures:
            missing.append("no acceptance fixture is named")
        for fixture in fixtures:
            problem = fixture_problem(repo, fixture)
            if problem:
                missing.append(problem)
        problem = consumer_problem(repo, consumers, symbol, owners)
        if problem:
            missing.append(problem)
        status = "reconciled" if not missing else "open"
        records.append(
            {
                "id": rid,
                "source": row["source"],
                "list": row["list"],
                "mandatory": mandatory,
                "status": status,
                "owner": owners,
                "fixtures": fixtures,
                "consumer": consumers,
                "missing": missing,
            }
        )
    return records


def quote(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def listing(items: list[str]) -> str:
    return "[" + ", ".join(quote(i) for i in items) + "]"


def render(records: list[dict]) -> str:
    counts = Counter(r["status"] for r in records)
    mandatory = Counter(r["status"] for r in records if r["mandatory"])
    lines = [
        HEADER.rstrip("\n"),
        "",
        "schema = 1",
        f"rows = {len(records)}",
        f"reconciled = {counts['reconciled']}",
        f"open = {counts['open']}",
        f"mandatory_rows = {sum(mandatory.values())}",
        f"mandatory_reconciled = {mandatory['reconciled']}",
        f"mandatory_open = {mandatory['open']}",
        "",
    ]
    for r in records:
        lines += [
            "[[row]]",
            f"id = {quote(r['id'])}",
            f"source = {quote(r['source'])}",
            f"list = {quote(r['list'])}",
            f"status = {quote(r['status'])}",
            f"owner = {listing(r['owner'])}",
            f"fixtures = {listing(r['fixtures'])}",
            f"consumer = {listing(r['consumer'])}",
        ]
        if r["missing"]:
            lines.append(f"missing = {listing(r['missing'])}")
        lines.append("")
    return "\n".join(lines)


def problems(repo: Repo, records: list[dict], stored: str | None) -> list[str]:
    errors: list[str] = []
    expected = render(records)
    if stored is None or stored != expected:
        errors.append(
            f"stale: {OUTPUT} differs from the sources; run python3 scripts/reconcile_release_scope.py"
        )
    for r in records:
        if not r["mandatory"] or r["status"] == "reconciled":
            continue
        for item in r["missing"]:
            kind = (
                "dangling"
                if "does not exist" in item
                or "defines no" in item
                or "not a registered" in item
                or "read by no registered" in item
                or "holds no unit tests" in item
                else "open"
            )
            errors.append(f"{kind}: {r['id']}: {item}")
    return errors


def self_test() -> int:
    import tempfile

    def write(root: Path, rel: str, body: str) -> None:
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(body, encoding="utf-8")

    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        write(
            root,
            MANIFEST,
            '[[route]]\nid = "licensed.A.Dag"\ntarget = "A"\ngraph_class = "Dag"\nstatus = "licensed"\n'
            'owning_module = "crates/c/src/owner.rs"\nartifact_consumer = "unlisted"\n',
        )
        write(
            root,
            CHILDREN,
            '[[child]]\nid = "P.x"\nroute = "licensed.A.Dag"\nmodule = "crates/c/src/owner.rs"\n'
            'owner = "crates/c"\nfixtures = "crates/c/tests/t.rs"\nconsumer = "crates/c/src/reader.rs"\n',
        )
        write(
            root,
            LICENSED,
            '[[route]]\ncoordinate = "A:Dag:explicit:Frequentist:none"\nlowering = "Low"\n',
        )
        write(root, REGISTRY, "schema = 1\n")
        write(
            root,
            "crates/c/Cargo.toml",
            '[package]\nname = "c"\nautotests = false\n[[test]]\nname = "t"\n',
        )
        write(root, "crates/c/src/owner.rs", "pub struct Thing;\n")
        write(root, "crates/c/src/reader.rs", "use Thing;\nLow\n")
        write(root, "crates/c/tests/t.rs", "#[test]\nfn it() {}\n")
        write(root, "crates/antecedent/tests/licensed_compiler.rs", "#[test]\nfn it() {}\n")
        write(root, "crates/antecedent/Cargo.toml", '[package]\nname = "a"\n')
        scope = (
            '[[entry]]\nid = "licensed.A.Dag"\nstatus = "mandatory"\nlist = "mandatory"\nsource = "route_manifest"\n\n'
            '[[entry]]\nid = "P.x"\nstatus = "mandatory"\nlist = "mandatory"\nsource = "method_children"\n'
        )
        write(root, SCOPE, scope)
        repo = Repo(root)
        records = gather(repo)
        by_id = {r["id"]: r for r in records}
        assert by_id["P.x"]["status"] == "reconciled", by_id["P.x"]
        assert by_id["licensed.A.Dag"]["status"] == "reconciled", by_id["licensed.A.Dag"]
        assert problems(repo, records, render(records)) == []
        assert any(e.startswith("stale") for e in problems(repo, records, "old")), (
            "stale output must fail"
        )
        # a fixture that does not exist fails the mandatory row
        (root / "crates/c/tests/t.rs").unlink()
        broken = gather(Repo(root))
        errors = problems(Repo(root), broken, render(broken))
        assert any("dangling: P.x" in e and "does not exist" in e for e in errors), errors
        # a fixture that exists but no Cargo target runs fails
        write(root, "crates/c/tests/t.rs", "#[test]\nfn it() {}\n")
        write(root, "crates/c/Cargo.toml", '[package]\nname = "c"\nautotests = false\n')
        unregistered = gather(Repo(root))
        errors = problems(Repo(root), unregistered, render(unregistered))
        assert any("not a registered test target" in e for e in errors), errors
        # a missing consumer fails, and a research row never does
        write(
            root,
            "crates/c/Cargo.toml",
            '[package]\nname = "c"\nautotests = false\n[[test]]\nname = "t"\n',
        )
        (root / "crates/c/src/reader.rs").unlink()
        errors = problems(Repo(root), gather(Repo(root)), None)
        assert any("consumer" in e and "P.x" in e for e in errors), errors
        write(
            root,
            SCOPE,
            scope.replace(
                'list = "mandatory"\nsource = "method_children"',
                'list = "research"\nsource = "method_children"',
            ),
        )
        research = gather(Repo(root))
        assert not [e for e in problems(Repo(root), research, render(research)) if "P.x" in e]
        # an awaiting table is not an exemption: a mandatory row with no evidence stays open and fails
        write(root, SCOPE, scope)
        write(
            root,
            CHILDREN,
            '[[child]]\nid = "P.x"\nroute = "unlisted"\nmodule = "none"\nowner = "unlisted"\n'
            'fixtures = "unlisted"\nconsumer = "unlisted"\n',
        )
        held = gather(Repo(root))
        assert {r["id"]: r["status"] for r in held}["P.x"] == "open"
        assert any(e.startswith("open: P.x") for e in problems(Repo(root), held, render(held)))
        write(
            root,
            EVIDENCE,
            '[[awaiting]]\nid = "P.x"\nowner_item = "P99"\nreason = "later"\ncompletes_when = "it runs"\n',
        )
        try:
            gather(Repo(root))
        except SystemExit as exit_:
            assert "no longer honoured" in str(exit_)
        else:
            raise AssertionError("an awaiting table must be refused")
    print("reconcile_release_scope self-test passed")
    return 0


def main(argv: list[str]) -> int:
    if "--self-test" in argv:
        return self_test()
    repo = Repo(ROOT)
    records = gather(repo)
    output = ROOT / OUTPUT
    if "--check" in argv:
        stored = output.read_text(encoding="utf-8") if output.is_file() else None
        errors = problems(repo, records, stored)
        for error in errors:
            print(f"FAIL: {error}")
        if errors:
            return 1
        print(f"release scope reconciled: {len(records)} rows")
        return 0
    if "--report" in argv:
        counts = Counter((r["list"], r["status"]) for r in records)
        print(
            f"rows: {len(records)}  "
            + "  ".join(f"{k[0]}/{k[1]}={v}" for k, v in sorted(counts.items()))
        )
        for r in records:
            for item in r["missing"]:
                print(f"{r['status']:10} {r['id']}: {item}")
        return 0
    output.write_text(render(records), encoding="utf-8", newline="\n")
    counts = Counter(r["status"] for r in records)
    print(f"wrote {OUTPUT}: {counts['reconciled']} reconciled, {counts['open']} open")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
