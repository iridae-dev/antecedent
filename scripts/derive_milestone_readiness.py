#!/usr/bin/env python3
"""Derive the readiness of the scope-and-interfaces milestone from evidence.

The milestone is ready when its prerequisites hold, the method children and their
specifications are complete, and the lanes and measurement protocol are registered. A
checkbox records none of that, so this script recomputes each condition from the sources and
writes parity/milestone_readiness.toml. It fails when

  stale       the stored verdict differs from the recomputed one
  not ready   a condition is unmet
  claimed     TODO.md checks the milestone while a condition is unmet

Conditions:

  prerequisite       every prerequisite item names evidence that exists, and the items that
                     have a checker pass it: the route manifest's method records, the method
                     children's fixtures and consumers, the specification review decisions and
                     the release-scope reconciliation
  children           the method children exist, every family records each of its quadrants, and
                     each child has exactly one specification
  owners             every implementation or statistical child names a crate that exists
  evidence           every child names a fixture a registered test runs and a consumer that
                     reads the artifact
  reviews            every specification carries a review decision consistent with the
                     executing evidence, and no admitted record leaves a scientific field unlisted
  lanes              the release lanes and the measurement protocol are registered

    python3 scripts/derive_milestone_readiness.py            # rewrite the verdict
    python3 scripts/derive_milestone_readiness.py --check    # fail when stale or not ready
    python3 scripts/derive_milestone_readiness.py --self-test
"""

from __future__ import annotations

import re
import subprocess
import sys
import tomllib
from collections import Counter

from _repo import REPO_ROOT as ROOT
from _repo import ensure_scripts_on_path

ensure_scripts_on_path()
import check_method_children as method_children  # noqa: E402
import reconcile_method_specs as specs_module  # noqa: E402
import reconcile_release_scope as scope_module  # noqa: E402
import route_methods  # noqa: E402
from method_evidence import Evidence  # noqa: E402

OUTPUT = "parity/milestone_readiness.toml"
PREREQUISITES = ("B01", "B02", "B03", "B04", "B05", "B10", "C01", "C02", "C03", "C04", "C05", "C05.1")
MILESTONE = "K0"
QUADRANTS = {"static.frequentist", "static.bayesian", "temporal.frequentist", "temporal.bayesian"}
HEADER = (
    "# Generated by scripts/derive_milestone_readiness.py; do not edit.\n"
    "# Each condition of the scope-and-interfaces milestone, recomputed from the sources.\n"
)


def quote(value: object) -> str:
    return '"' + str(value).replace("\\", "\\\\").replace('"', '\\"') + '"'


def todo_items(todo: str) -> dict[str, tuple[bool, list[str]]]:
    """Item id -> (checked, evidence paths) for every plan item of TODO.md."""
    items: dict[str, tuple[bool, list[str]]] = {}
    lines = todo.splitlines()
    for index, line in enumerate(lines):
        match = re.match(r"- \[( |x)\] \*\*([A-Z]\d+(?:\.\d+)?)\b", line)
        if not match:
            continue
        block = [line]
        for follower in lines[index + 1 : index + 6]:
            if follower.startswith("- ["):
                break
            block.append(follower)
        text = " ".join(block)
        evidence = []
        for fragment in re.findall(r"Evidence:(.*?)(?:\.\s|$)", text):
            evidence += [t for t in re.findall(r"`([^`\s]+)`", fragment) if "/" in t]
        items[match.group(2)] = (match.group(1) == "x", evidence)
    return items


def evidence_exists(ev: Evidence, path: str) -> bool:
    """A cited path exists, or the Rust module it names has since been split into a directory."""
    clean = path.split("::")[0].rstrip("/")
    return ev.repo.exists(clean) or (clean.endswith(".rs") and (ev.root / clean[:-3]).is_dir())


def conditions(ev: Evidence) -> list[dict]:
    out: list[dict] = []

    def add(ident: str, met: bool, evidence: str, detail: str = "") -> None:
        out.append({"id": ident, "met": met, "evidence": evidence, "detail": detail})

    todo = todo_items(ev.text("TODO.md"))
    children = tomllib.loads(ev.text(method_children.CHILDREN))["child"]
    specs = tomllib.loads(ev.text(specs_module.SPECS))["spec"]

    # derived checkers behind the prerequisites that have one
    src = route_methods.Sources(ev)
    methods = route_methods.build(src)
    route_problems = route_methods.verify(src, methods)
    child_problems = method_children.findings(ev)
    spec_problems = specs_module.verify(ev, specs)
    records = scope_module.gather(ev.repo)
    mandatory_open = [r["id"] for r in records if r["mandatory"] and r["status"] != "reconciled"]
    derived = {
        "B02": (not route_problems, f"{len(methods)} method records verified against the implementation", route_problems[:3]),
        "B03": (not child_problems, f"{len(children)} children verified", child_problems[:3]),
        "B04": (not spec_problems, f"{len(specs)} specifications reconciled", spec_problems[:3]),
        "B05": (not mandatory_open, f"{sum(r['mandatory'] for r in records)} mandatory rows reconciled", mandatory_open[:3]),
    }
    for item in PREREQUISITES:
        checked, paths = todo.get(item, (False, []))
        missing = [p for p in paths if not evidence_exists(ev, p)]
        ok_paths = bool(paths) and not missing
        met, label, extra = derived.get(item, (True, "evidence paths exist", []))
        detail = "; ".join(map(str, missing + list(extra)))
        add(f"prerequisite.{item}", ok_paths and met, f"{', '.join(paths[:3])}: {label}", detail)

    ids = [c["id"] for c in children]
    families: dict[str, set[str]] = {}
    for child in children:
        parts = child["id"].split(".")
        families.setdefault(".".join(parts[:-2]), set()).add(".".join(parts[-2:]))
    incomplete = sorted(f for f, seen in families.items() if not QUADRANTS <= seen)
    add(
        "children.complete",
        len(ids) == len(set(ids)) and not incomplete and {s["id"] for s in specs} == set(ids),
        f"{len(ids)} children, {len(families)} method families, {len(specs)} specifications",
        "; ".join(incomplete[:4]),
    )
    owners = [
        c["id"]
        for c in children
        if c["gap"] in ("implementation", "statistical")
        and not (c["owner"].startswith("crates/") and ev.repo.exists(c["owner"].split(" ")[0]))
    ]
    constrained = sum(c["gap"] in ("implementation", "statistical") for c in children)
    add("owners.crate", not owners, f"{constrained} implementation or statistical children", "; ".join(owners[:4]))
    add("evidence.children", not child_problems, f"{len(children)} children name a registered fixture and a reading consumer", "; ".join(child_problems[:3]))
    decided = Counter(s["review_status"] for s in specs)
    add(
        "reviews.decided",
        not spec_problems and all(s["admission"] and s["decision_basis"] for s in specs),
        "review decisions: " + ", ".join(f"{k}={v}" for k, v in sorted(decided.items())),
        "; ".join(spec_problems[:3]),
    )
    lanes = subprocess.run(
        [sys.executable, "-I", str(ROOT / "parity/performance_lanes/check_lanes.py")],
        capture_output=True, text=True, check=False,
    )
    protocol = tomllib.loads(ev.text("parity/measurement_protocol/protocol.toml"))
    lanes_table = tomllib.loads(ev.text("parity/performance_lanes/lanes.toml"))
    registered = (
        lanes.returncode == 0
        and len(lanes_table.get("lane", [])) == 4
        and protocol.get("lanes_table") == "parity/performance_lanes/lanes.toml"
    )
    add("lanes.registered", registered, lanes.stdout.strip().splitlines()[-1] if lanes.stdout.strip() else "no lane check output", lanes.stderr.strip()[:120])
    return out


def render(items: list[dict], checked_in_todo: bool) -> str:
    ready = all(c["met"] for c in items)
    lines = [
        HEADER, "schema = 1", f"milestone = {quote(MILESTONE)}", f"ready = {str(ready).lower()}",
        f"conditions = {len(items)}", f"met = {sum(c['met'] for c in items)}",
        f"checked_in_plan = {str(checked_in_todo).lower()}", "",
    ]
    for c in items:
        lines += [
            "[[condition]]", f"id = {quote(c['id'])}", f"met = {str(c['met']).lower()}",
            f"evidence = {quote(c['evidence'])}", f"detail = {quote(c['detail'])}", "",
        ]
    return "\n".join(lines)


def findings(items: list[dict], checked_in_todo: bool) -> list[str]:
    out = [f"not ready: {c['id']}: {c['detail'] or c['evidence']}" for c in items if not c["met"]]
    if checked_in_todo and out:
        out.append(f"claimed: TODO.md checks {MILESTONE} while {len(out)} condition(s) are unmet")
    return out


def self_test() -> int:
    todo = (
        "- [x] **B01** Archive things.\n  **After:** none. Evidence: `parity/predecessor/` (published tag).\n\n"
        "- [ ] **C07** Another.\n  **After:** B01. Evidence: `crates/a/b.rs`, `scripts/c.py`.\n"
    )
    items = todo_items(todo)
    assert items["B01"] == (True, ["parity/predecessor/"]), items
    assert items["C07"] == (False, ["crates/a/b.rs", "scripts/c.py"]), items
    met = [{"id": "x", "met": True, "evidence": "e", "detail": ""}]
    unmet = met + [{"id": "y", "met": False, "evidence": "e", "detail": "why"}]
    assert findings(met, True) == []
    assert findings(unmet, False) == ["not ready: y: why"]
    assert any(line.startswith("claimed:") for line in findings(unmet, True))
    text = render(unmet, False)
    parsed = tomllib.loads(text)
    assert parsed["ready"] is False and parsed["met"] == 1 and parsed["conditions"] == 2
    print("derive_milestone_readiness self-test passed")
    return 0


def main(argv: list[str]) -> int:
    if "--self-test" in argv:
        return self_test()
    ev = Evidence(ROOT)
    items = conditions(ev)
    claimed = bool(re.search(rf"- \[x\] \*\*{MILESTONE}\b", ev.text("TODO.md")))
    text = render(items, claimed)
    output = ROOT / OUTPUT
    if "--check" in argv:
        stored = output.read_text(encoding="utf-8") if output.is_file() else None
        problems = findings(items, claimed)
        if stored != text:
            problems.insert(0, f"stale: {OUTPUT} differs from the recomputed verdict; run python3 scripts/derive_milestone_readiness.py")
        for line in problems:
            print(f"FAIL: {line}")
        print(f"{MILESTONE} readiness: {sum(c['met'] for c in items)}/{len(items)} conditions met")
        return 1 if problems else 0
    output.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT}: {MILESTONE} ready = {all(c['met'] for c in items)} ({sum(c['met'] for c in items)}/{len(items)})")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
