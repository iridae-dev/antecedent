def rust_f64(value: float) -> str:
    text = repr(float(value))
    return text if ("." in text or "e" in text or "inf" in text or "nan" in text) else text + ".0"


def attesting_record_ids() -> list[str]:
    """Ids of the coverage records that attest the tree this is generated from.

    The same assessment as `scripts/gate_calibration_attestation.sh` and
    `collect_coverage_records.py --keep-attested`: a record attests while none of
    its facets differs between its `calibration_sha` and the tree, or a valid
    replay waiver covers the change. The runtime reads this list to decide whether
    a matching record may report `calibrated`. It fails closed: a commit this clone
    cannot resolve, or no git at all, leaves a record out.

    An empty live assessment invalidates every prior cached attestation. Matching
    record IDs or unchanged measurement rows cannot establish that the current
    implementation still matches the measured surface.
    """
    return _live_attesting_record_ids()


def _live_attesting_record_ids() -> list[str]:
    import calibration_facets as facets

    try:
        registry = facets.load_records(ROOT / "parity/coverage_records.toml")
        surface = facets.load_surface()
        ids: set[str] = set()
        for assessment in facets.assess(surface, registry, registry=registry):
            stale = {rec["id"] for rec in assessment.stale}
            if assessment.resolved:
                ids |= {rec["id"] for rec in assessment.records if rec["id"] not in stale}
        return sorted(ids)
    except (OSError, subprocess.SubprocessError, SystemExit) as exc:
        print(f"warning: no record is marked attesting ({exc})", file=sys.stderr)
        return []


def write_snapshot(path: Path, payload: dict) -> None:
    """Pretty-printed UTF-8 JSON with a trailing newline. Stable across runs."""
    path.parent.mkdir(parents=True, exist_ok=True)
    write_text(path, json.dumps(payload, indent=2, ensure_ascii=False) + "\n")


def _f64(value: float) -> str:
    """Decimal spelling rustc and `f64::from_str` parse to the same bits."""
    return rust_f64(value)


def _coverage_grid(points: list[dict]) -> list[dict]:
    return [
        {
            "point": int(point["point"]),
            "n_min": int(point["n_min"]),
            "n_max": int(point["n_max"]),
            "observed": _f64(point["observed"]),
            "mcse": _f64(point["mcse"]),
            "replicates": int(point["replicates"]),
            "boundary": bool(point["boundary"]),
        }
        for point in points
    ]


def _coverage_record(row: dict) -> dict:
    item = {key: str(row.get(key) or "") for key in COVERAGE_STR_FIELDS}
    item.update(
        {
            "nominal": _f64(row["nominal"]),
            "n_min": int(row["n_min"]),
            "n_max": int(row["n_max"]),
            "replicates_min": int(row["replicates_min"]),
            "posterior_draws_min": int(row["posterior_draws_min"]),
            "unidentified_mass_max": _f64(row["unidentified_mass_max"]),
            "observed": _f64(row["observed"]),
            "mcse": _f64(row["mcse"]),
            "replicates": int(row["replicates"]),
            "boundary": bool(row.get("boundary")),
            "grid": _coverage_grid(row.get("grid") or []),
        }
    )
    # Validation metadata is optional for legacy rows; it must never be inferred.
    for key in ("validation_schema", "validation"):
        if key in row:
            item[key] = row[key]
    # Only a boundary record that passed an independent confirmation carries these.
    if row.get("confirmation"):
        item["confirmation"] = _coverage_grid(row["confirmation"])
    if row.get("confirmed_passing_range"):
        item["confirmed_passing_range"] = [int(n) for n in row["confirmed_passing_range"]]
    for key in COVERAGE_TAIL_STR_FIELDS:
        item[key] = str(row[key])
    return item


def _interval_method_reasons(records: list[dict]) -> list[dict]:
    """An unmeasured method carries the reason the runtime reports for it."""
    measured = {str(row["interval_method"]) for row in records}
    methods = [
        ("AnalyticSe", "analytic_se"),
        ("BootstrapSe", "bootstrap_se"),
        ("PosteriorQuantile", "posterior_quantile"),
        ("UnitPosteriorQuantile", "unit_posterior_quantile"),
        ("IdentifiedSet", "identified_set"),
        ("CircularBlockSe", "circular_block_se"),
        ("SimultaneousBand", "simultaneous_band"),
        ("AndersonRubin", "anderson_rubin"),
        ("None", "none"),
    ]
    reasons = []
    for variant, name in methods:
        if name in measured:
            reason = None
        elif name == "none":
            reason = "no_interval_reported"
        else:
            reason = "estimator_grid_not_measured"
        reasons.append({"method": variant, "reason": reason})
    return reasons


def coverage_snapshot() -> dict:
    """In-crate snapshot consumed by `coverage_records_data`.

    `parity/coverage_records.toml` stays the registry. Floats are decimal
    strings so the loader's `f64::from_str` matches the old Rust literals.
    Attesting ids and identity aliases are not in that TOML; they are stamped
    here the same way the old literal module carried them.
    """
    records = load("parity/coverage_records.toml").get("record") or []
    aliases = calibration_key_aliases.validated_aliases(ROOT)
    alias_keys = (
        "record_id",
        "measurement_sha",
        "original_functional",
        "canonical_functional",
    )
    return {
        "records": [_coverage_record(row) for row in records],
        "historical_validation_bindings": coverage_validation_bindings.load_bindings(ROOT),
        "functional_identity_aliases": [{key: row[key] for key in alias_keys} for row in aliases],
        "attesting_record_ids": attesting_record_ids(),
        "interval_method_reasons": _interval_method_reasons(records),
    }


def render_reason_codes() -> str:
    """Closed reason-code vocabulary for the runtime (`antecedent_core::reason_code`)."""
    codes = load("parity/reason_codes.toml").get("code") or []
    every = sorted(row["id"] for row in codes)
    runtime = sorted(row["id"] for row in codes if "runtime_refusal" in row.get("applies_to", []))

    def lines(ids: list[str]) -> str:
        return "".join(f'    "{rust_escape(i)}",\n' for i in ids)

    return f"""//! Generated from `parity/reason_codes.toml`. Do not edit.

#![cfg_attr(rustfmt, rustfmt::skip)]

/// Every registered reason code.
pub const REASON_CODES: &[&str] = &[
{lines(every)}];

/// Codes whose `applies_to` includes `runtime_refusal`.
pub const RUNTIME_REFUSAL_CODES: &[&str] = &[
{lines(runtime)}];
"""


def rust_escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"')


# Unambiguous substrings of calibration record ids → EstimatorId::as_str().
# Longer tokens first so e.g. cell_aipw wins over aipw. Only map tokens that
# name one closed-set estimator; do not invent from limitations prose.
CALIBRATION_ESTIMATOR_TOKENS: list[tuple[str, str]] = [
    ("matching_homoskedastic", "propensity.matching"),
    ("frontdoor_stacked", "frontdoor.linear_two_stage"),
    ("codetermined_aipw", "cell.aipw"),
    ("cell_aipw", "cell.aipw"),
    ("ipw_hajek", "propensity.weighting"),
    ("glm_adjustment", "glm.adjustment"),
    ("linear_adjustment", "linear.adjustment.ate"),
    ("wald_iv", "iv.wald"),
    ("iv_2sls", "iv.2sls"),
    ("rd_sharp", "rd.sharp"),
    ("distance_matching", "distance.matching"),
    ("causal_forest", "causal.forest"),
    ("propensity_stratification", "propensity.stratification"),
    ("propensity_weighting", "propensity.weighting"),
    ("propensity_matching", "propensity.matching"),
    ("aipw", "aipw"),
]


def estimators_from_calibration(
    record_ids: list[str], roles: dict[str, str] | None = None
) -> list[str]:
    """Wire-ids implied by unambiguous tokens in calibration record ids.

    Only gated and named-boundary records are support evidence. A
    `reported_level` record is an unasserted diagnostic that a cell may cite,
    but it never supports the estimator it measures.
    """
    if roles is None:
        roles = {r["id"]: r["role"] for r in load("parity/coverage_records.toml").get("record") or []}
    found: set[str] = set()
    for cid in record_ids:
        if not isinstance(cid, str) or roles.get(cid) == "reported_level":
            continue
        for token, wire in CALIBRATION_ESTIMATOR_TOKENS:
            if token in cid:
                found.add(wire)
                break
    return sorted(found)


def cell_route_estimator(row: dict, routes: dict[str, dict]) -> str | None:
    route = routes.get(external_evidence.coordinate(row))
    if route is None:
        return None
    est = route.get("estimator")
    if isinstance(est, str) and est.strip():
        return est
    return None


def cell_estimators(
    row: dict, routes: dict[str, dict], calibration_roles: dict[str, str] | None = None
) -> list[str]:
    """Estimator wire-ids whose evidence ran for this geometric cell.

    Union of the supported_routes compiler-plan estimator, explicitly supported
    estimator ids on the evidence row, and estimators implied by unambiguous
    calibration-record tokens. Never infer an estimator from limitations prose.
    """
    out: list[str] = []
    seen: set[str] = set()

    def add(wire: str) -> None:
        if wire and wire not in seen:
            seen.add(wire)
            out.append(wire)

    route = cell_route_estimator(row, routes)
    if route is not None:
        add(route)
    for wire in row.get("estimators") or []:
        add(wire)
    for wire in estimators_from_calibration(list(row.get("calibration") or []), calibration_roles):
        add(wire)
    return out


def _rule_snapshot(rule: dict) -> dict:
    item = {
        "queries": rule.get("queries"),
        "graph_classes": rule.get("graph_classes"),
        "structures": rule.get("structures"),
        "inferences": rule.get("inferences"),
        "validations": rule.get("validations"),
        "reason": rule["reason"],
    }
    return item


def support_snapshot(
    na_rules: list[dict],
    closed_rules: list[dict],
    cells: list[dict],
) -> dict:
    """Resolved support matrix. Omitted rule axes stay JSON null (`None` in Rust)."""
    routes = external_evidence.routes()
    # The registry is immutable during this generation pass. Parse it once,
    # rather than once per geometric cell.
    calibration_roles = {
        row["id"]: row["role"]
        for row in load("parity/coverage_records.toml").get("record") or []
    }
    supported = []
    for row in cells:
        supported.append(
            {
                "query": row["query"],
                "graph_class": row["graph_class"],
                "structure": row["structure"],
                "inference": row["inference"],
                "validation": row["validation"],
                "route_estimator": cell_route_estimator(row, routes),
                "estimators": cell_estimators(row, routes, calibration_roles),
            }
        )
    return {
        "na_rules": [_rule_snapshot(rule) for rule in na_rules],
        "closed_rules": [_rule_snapshot(rule) for rule in closed_rules],
        "supported": supported,
    }


def _freeze_cli(version: str) -> int:
    path = release_notes_path(version)
    if not path.is_file():
        print(f"no notes to freeze: {path.relative_to(ROOT)}")
        return 0
    if freeze_supported_block(path):
        print(f"Froze supported block in {path.relative_to(ROOT)}")
    else:
        print(f"{path.relative_to(ROOT)} has no live supported-block markers")
    return 0


