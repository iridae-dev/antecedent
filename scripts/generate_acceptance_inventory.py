#!/usr/bin/env python3
"""Generate the authoritative acceptance inventory (parity/acceptance_inventory.toml).

One row per public route, joined row by row from every record that speaks about it:

  parity/counterparts.toml                   the static/temporal x frequentist/Bayesian rows
  parity/capabilities/route_manifest.toml    the public routes and their methods
  parity/capabilities/family_conformance.toml  the family each route is conformance-checked in
  crates/antecedent/tests/family_contract_conformance.rs  the representatives that suite runs
  parity/release_scope/scope.toml            the release scope entries
  parity/method_children/children.toml       the method children and their fixtures/consumers
  parity/route_obligations.toml              the licence, calibration and uncertainty obligations
  parity/residual_limitations.toml           the residual limitation each narrowed row maps to

A row carries the compiler execution it cites, the scientific claim (status and the explicit
licence behind it), the uncertainty it publishes, the consumers that read its artifact and its
closure kind. `acceptance` is `complete` only when the route executes through the compiler,
carries the uncertainty it claims, has its consumers, is conformance-checked by its own
representative and closes as delivered; otherwise it is `incomplete` and every reason is
listed. `conflicts` lists records that disagree about the row (a status, a closure kind, a
scope list, a licence without its evidence); the checker rejects any conflict.

    python3 scripts/generate_acceptance_inventory.py           # rewrite the file
    python3 scripts/generate_acceptance_inventory.py --check   # fail when the file is stale
"""

from __future__ import annotations

import json
import re
import sys
import tomllib
from collections import defaultdict
from pathlib import Path

from _repo import REPO_ROOT as ROOT

OUTPUT = "parity/acceptance_inventory.toml"
CONFORMANCE_SUITE = "crates/antecedent/tests/family_contract_conformance.rs"
UNLISTED = {"", "unlisted", "none"}
FIELDS = (
    "id", "kind", "route", "method", "design", "inference", "target",
    "compiler_execution", "status", "scientific_claim", "licensing_obligations",
    "uncertainty", "uncertainty_basis", "uncertainty_license",
    "consumer", "decision_port", "closure_kind", "scope_status", "scope_list", "gap",
    "family", "representative", "obligations", "limitations", "acceptance",
    "incomplete_reasons", "conflicts",
)
HEADER = (
    "# Generated by scripts/generate_acceptance_inventory.py; do not edit.\n"
    "# One row per public route: compiler execution, scientific claim, uncertainty, consumers\n"
    "# and closure kind, reconciled row by row against the counterpart, release-scope,\n"
    "# conformance, method-child, route-obligation and residual-limitation records.\n"
    "# `acceptance` is `incomplete` with every reason when a route executes without its claimed\n"
    "# uncertainty or consumers, closes as a narrowed promise, or lacks its conformance\n"
    "# representative. `conflicts` must be empty; scripts/check_acceptance_inventory.py rejects it.\n"
)


def association_representative(route: str) -> str:
    """The conformance representative each associational counterpart owes, by its route."""
    m = re.fullmatch(r"(bayesian\.)?association\.descriptive\.(static|temporal)", route)
    if not m:
        return ""
    return f"association_{m.group(2)}" + ("_bayesian" if m.group(1) else "")


def registered_representatives(text: str) -> set[str]:
    """Labels of the representatives the conformance suite actually runs."""
    others = re.search(r"fn others\(\)\s*->\s*Vec<Other>\s*\{\s*vec!\[(.*?)\n    \]\s*\}", text, re.S)
    other_labels = set(re.findall(r'label:\s*"([^"]+)"', others.group(1))) if others else set()
    listed = re.search(r"fn representatives\(\)\s*->\s*Vec<Rep>\s*\{\s*vec!\[(.*?)\]\s*\}", text, re.S)
    if not listed:
        return other_labels
    names = set(re.findall(r"(\w+)\(\)", listed.group(1)))
    labels: set[str] = set(other_labels)
    for name in names:
        body = re.search(rf"fn {name}\(\)\s*->\s*Rep\s*\{{(.*?)\n\}}", text, re.S)
        if body:
            labels.update(re.findall(r'label:\s*"([^"]+)"', body.group(1)))
    return labels


def load_sources(root: Path = ROOT, *, with_children: bool = True) -> dict:
    def toml(rel: str) -> dict:
        return tomllib.loads((root / rel).read_text(encoding="utf-8"))

    suite = root / CONFORMANCE_SUITE
    child_findings: dict[str, list[str]] = defaultdict(list)
    if with_children:
        from _repo import ensure_scripts_on_path

        ensure_scripts_on_path()
        import check_method_children as children_check  # noqa: E402
        from method_evidence import Evidence  # noqa: E402

        for line in children_check.findings(Evidence(root)):
            cid, _, rest = line.partition(": ")
            child_findings[cid].append(rest)
    return {
        "root": root,
        "counterparts": toml("parity/counterparts.toml").get("row", []),
        "manifest": toml("parity/capabilities/route_manifest.toml"),
        "families": toml("parity/capabilities/family_conformance.toml").get("family", []),
        "scope": toml("parity/release_scope/scope.toml").get("entry", []),
        "children": toml("parity/method_children/children.toml").get("child", []),
        "obligations": toml("parity/route_obligations.toml").get("obligation", []),
        "limitations": toml("parity/residual_limitations.toml").get("limitation", []),
        "coverage_ids": {r["id"] for r in toml("parity/coverage_records.toml").get("record", [])},
        "representatives": registered_representatives(suite.read_text(encoding="utf-8")) if suite.is_file() else set(),
        "child_findings": dict(child_findings),
    }


def consumer_problems(root: Path, token: str) -> list[str]:
    """A consumer is a path[::symbol] of a source that exists and mentions its symbol."""
    path, _, symbol = token.partition("::")
    if token in UNLISTED:
        return ["no artifact consumer is named"]
    file = root / path
    if not file.is_file():
        return [f"consumer {path} does not exist"]
    if symbol and not re.search(rf"\b{re.escape(symbol.rsplit('::', 1)[-1])}\b", file.read_text(encoding="utf-8", errors="replace")):
        return [f"consumer {path} does not mention {symbol!r}"]
    return []


def execution_problems(root: Path, token: str) -> list[str]:
    path, _, name = token.partition("::")
    if token in UNLISTED:
        return ["no compiler execution is cited"]
    file = root / path
    if not file.is_file():
        return [f"execution {path} does not exist"]
    if name and not re.search(rf"\b{re.escape(name.rsplit('::', 1)[-1])}\b", file.read_text(encoding="utf-8", errors="replace")):
        return [f"execution {path} does not name {name!r}"]
    return []


class Index:
    """The cross-record lookups, built once."""

    def __init__(self, sources: dict):
        self.s = sources
        self.manifest_routes = {r["id"]: r for r in sources["manifest"].get("route", [])}
        self.manifest_methods = defaultdict(list)
        for m in sources["manifest"].get("method", []):
            self.manifest_methods[m["route"]].append(m)
        self.family_of = {}
        for fam in sources["families"]:
            for route in fam.get("routes", []):
                self.family_of[route] = fam
        self.scope = {e["id"]: e for e in sources["scope"]}
        self.children = {c["id"]: c for c in sources["children"]}
        self.licensed = defaultdict(list)
        self.closed = []
        for ob in sources["obligations"]:
            if ob.get("kind") == "licensed":
                self.licensed[(ob["query"], ob["graph_class"], str(ob["inference"]).lower())].append(ob)
            else:
                self.closed.append(ob)
        self.limits = defaultdict(list)
        for lim in sources["limitations"]:
            self.limits[(lim["kind"], lim["locator"])].append(lim)

    def closed_for(self, query: str, graph: str) -> list[dict]:
        return [
            ob for ob in self.closed
            if (not ob["queries"] or query in ob["queries"])
            and (not ob["graph_classes"] or graph in ob["graph_classes"])
        ]


def split_route(route: str) -> tuple[str, str] | None:
    parts = route.split(".")
    if len(parts) == 3 and parts[0] in ("licensed", "closed"):
        return parts[1], parts[2]
    return None


def counterpart_row(row: dict, ix: Index) -> dict:
    s = ix.s
    root: Path = s["root"]
    rid, route, status = row["id"], row["route"], row["status"]
    reasons: list[str] = []
    conflicts: list[str] = []
    out = {
        "id": rid,
        "kind": "counterpart_" + row["kind"],
        "route": route,
        "method": row["method"],
        "design": row["design"],
        "inference": row["inference"],
        "target": row["target"],
        "compiler_execution": row["execution"],
        "status": status,
        "uncertainty": row["uncertainty"],
        "uncertainty_basis": row["uncertainty_basis"],
        "consumer": row["artifact"],
        "decision_port": row["decision_port"],
        "closure_kind": row["closure"],
        "scope_status": row["scope_status"],
        "gap": row["gap"],
    }

    # Conformance family and representative.
    family = ix.family_of.get(route)
    out["family"] = family["id"] if family else ""
    rep = association_representative(route)
    out["representative"] = rep
    if route in UNLISTED or (root / route).is_file():
        pass  # a facade, library or migration record has no compiled route to conformance-check
    elif family is None:
        conflicts.append(f"route {route} is in no conformance family")
    else:
        if family["status"] != "covered":
            reasons.append(f"conformance family {family['id']} is {family['status']}")
        for label in family.get("representatives", []):
            if label not in s["representatives"]:
                reasons.append(f"family {family['id']} names representative {label}, which the conformance suite does not register")
        if rep and rep not in s["representatives"]:
            reasons.append(f"counterpart {route} has no conformance representative {rep} registered in the conformance suite")

    # Release scope.
    key = rid if row["kind"] == "method" else route
    entry = ix.scope.get(key)
    out["scope_list"] = entry["list"] if entry else ""
    if entry and entry["list"] != row["scope_status"]:
        conflicts.append(f"scope list {entry['list']!r} conflicts with counterpart scope_status {row['scope_status']!r}")

    # Method child.
    child = ix.children.get(rid) if row["kind"] == "method" else None
    if row["kind"] == "method":
        if child is None:
            conflicts.append(f"method row {rid} has no method child")
        else:
            if child["gap"] != row["gap"]:
                conflicts.append(f"child gap {child['gap']!r} conflicts with counterpart gap {row['gap']!r}")
            if child["route"] != route:
                conflicts.append(f"child route {child['route']!r} conflicts with counterpart route {route!r}")
            for finding in s["child_findings"].get(rid, []):
                reasons.append(f"method child: {finding}")

    # Obligations and the licence behind the claim.
    split = split_route(route)
    licensed, execution = [], []
    if split:
        licensed = ix.licensed.get((split[0], split[1], row["inference"]), [])
        execution = ix.closed_for(*split)
    out["obligations"] = sorted([o["id"] for o in licensed] + [o["id"] for o in execution])
    out["licensing_obligations"] = sorted(o["id"] for o in licensed) if status == "licensed" else []
    claim = {"licensed": "licensed", "not_applicable_with_theory_reason": "not_applicable"}.get(status, "unlicensed")
    out["scientific_claim"] = claim
    cal: list[str] = []
    if status == "licensed":
        if split and not licensed:
            conflicts.append("licensed row has no explicit licence obligation (unsupported licensing evidence)")
        for ob in licensed:
            if not str(ob["identification_license"]).split("|")[:3] or not all(str(ob["identification_license"]).split("|")[:3]):
                conflicts.append(f"obligation {ob['id']} has no explicit identification licence")
            if not ob["calibration_license"]:
                conflicts.append(f"obligation {ob['id']} has no explicit calibration licence")
            cal.append(ob["uncertainty"])
            lic = str(ob["calibration_license"])
            if lic.startswith("records:"):
                for rec in lic[len("records:"):].split(","):
                    if rec not in s["coverage_ids"]:
                        conflicts.append(f"obligation {ob['id']} cites coverage record {rec}, which is not recorded")
        if row["uncertainty_basis"] == "measured_record" and licensed and not any(
            str(o["calibration_license"]).startswith("records:") for o in licensed
        ):
            conflicts.append("uncertainty rests on a measured record but no obligation cites a coverage record (unsupported licensing evidence)")
        if not split:
            if row["uncertainty_basis"] not in ("measured_record", "estimator_records", "point_only_cell"):
                conflicts.append(f"licensed row without a route obligation rests on {row['uncertainty_basis']!r} (unsupported licensing evidence)")
    else:
        if licensed:
            conflicts.append("row is not licensed although an explicit licence obligation exists for its coordinate")
        if status == "executing_unlicensed" and split and not execution and not licensed:
            reasons.append("executes with no route obligation recording what it owes")
    out["uncertainty_license"] = sorted(set(cal)) if cal else ("unmeasured" if claim == "unlicensed" else "none")

    # Closure kind against the residual limitation.
    narrowed = ix.limits.get(("narrowed_promise", rid), [])
    theory = ix.limits.get(("theory_reason", rid), [])
    manifest_lims = [
        lim for k in ("route_counterpart", "route_narrowed") for lim in ix.limits.get((k, route), [])
    ] if route not in UNLISTED else []
    out["limitations"] = sorted(lim["id"] for lim in narrowed + theory + manifest_lims)
    if row["closure"] == "narrowed_promise":
        if not row["next_attempt"] and status != "not_applicable_with_theory_reason":
            conflicts.append("narrowed_promise carries no next attempt")
        if not narrowed:
            conflicts.append("narrowed_promise has no residual limitation row")
        reasons.append(f"narrowed_promise: {row['reason'] or 'claim reduced'}; next attempt: {row['next_attempt'] or 'none recorded'}")
    else:
        if narrowed:
            conflicts.append("delivered row has a narrowed_promise residual limitation")
        if row["next_attempt"]:
            conflicts.append("delivered row carries a next attempt")
    if status == "closed_with_next_attempt" and row["closure"] != "narrowed_promise":
        conflicts.append("closed_with_next_attempt must close as narrowed_promise")
    if status == "not_applicable_with_theory_reason":
        if row["closure"] != "delivered":
            conflicts.append("not_applicable_with_theory_reason must close as delivered")
        if not theory:
            conflicts.append("not-applicable row has no theory_reason residual limitation")
        elif not all(t["decision"] == "scope" and t["rationale"] for t in theory):
            conflicts.append("theory_reason limitation records no scope decision with a rationale")
    for lim in manifest_lims:
        reasons.append(f"residual limitation {lim['id']} open to {lim['owner'] or lim['decision']}")

    # Execution, uncertainty and consumers of an executing route.
    executing = status in ("licensed", "executing_unlicensed", "closed_with_next_attempt")
    if executing:
        reasons += execution_problems(root, row["execution"])
        if row["uncertainty"] == "none" and row["uncertainty_basis"] != "point_only_cell":
            reasons.append(f"executes without its claimed uncertainty (basis {row['uncertainty_basis']})")
        if row["uncertainty_basis"] in ("no_executing_route", "refused_route", "no_method_record"):
            reasons.append(f"uncertainty basis is {row['uncertainty_basis']} for an executing route")
        reasons += consumer_problems(root, row["artifact"])
    return finish(out, reasons, conflicts)


def manifest_row(route: dict, ix: Index) -> dict:
    """A manifest route no counterpart row names: recorded, and incomplete for that reason."""
    root: Path = ix.s["root"]
    rid = route["id"]
    methods = ix.manifest_methods.get(rid, [])
    method = methods[0] if methods else {}
    execution = route.get("retained_route_test") or next(iter(method.get("evidence", []) or []), "")
    consumers = [c for c in method.get("artifact_consumer", []) if "/tests/" not in c] or [""]
    family = ix.family_of.get(rid)
    uncertainty = method.get("uncertainty") or "none"
    reasons = [f"route {rid} has no counterpart row recording its static/temporal x frequentist/Bayesian quadrants"]
    conflicts: list[str] = []
    if family is None:
        conflicts.append(f"route {rid} is in no conformance family")
    if route["status"] != "fitting_gap":
        reasons += execution_problems(root, execution)
        reasons += consumer_problems(root, consumers[0])
        if uncertainty in UNLISTED:
            reasons.append("executes without its claimed uncertainty")
    else:
        reasons.append("fitting gap: the route does not execute")
    entry = ix.scope.get(rid)
    out = {
        "id": f"route:{rid}",
        "kind": "manifest_route",
        "route": rid,
        "method": method.get("estimator", "") or "",
        "design": method.get("design", "") or "",
        "inference": route["inference"],
        "target": route["target"],
        "compiler_execution": execution,
        "status": route["status"],
        "scientific_claim": "licensed" if route["status"] in ("licensed", "graphless") else "unlicensed",
        "licensing_obligations": [],
        "uncertainty": uncertainty,
        "uncertainty_basis": method.get("uncertainty_basis", "") or "",
        "uncertainty_license": "unmeasured",
        "consumer": consumers[0],
        "decision_port": route["decision_ports"],
        "closure_kind": "",
        "scope_status": "",
        "scope_list": entry["list"] if entry else "",
        "gap": "",
        "family": family["id"] if family else "",
        "representative": "",
        "obligations": [],
        "limitations": sorted(lim["id"] for k in ("route_counterpart", "route_narrowed") for lim in ix.limits.get((k, rid), [])),
    }
    return finish(out, reasons, conflicts)


def finish(out: dict, reasons: list[str], conflicts: list[str]) -> dict:
    out["incomplete_reasons"] = sorted(set(reasons))
    out["conflicts"] = sorted(set(conflicts))
    out["acceptance"] = "complete" if not out["incomplete_reasons"] and not out["conflicts"] else "incomplete"
    return out


def build(sources: dict) -> list[dict]:
    ix = Index(sources)
    rows = [counterpart_row(r, ix) for r in sources["counterparts"]]
    named = {r["route"] for r in sources["counterparts"]}
    rows += [manifest_row(r, ix) for r in sources["manifest"].get("route", []) if r["id"] not in named]
    return rows


def render(rows: list[dict]) -> str:
    out = [HEADER, "\nschema = 1\n"]
    for row in rows:
        out.append("\n[[row]]\n")
        for name in FIELDS:
            out.append(f"{name} = {json.dumps(row[name], ensure_ascii=True)}\n")
    return "".join(out)


def summary(rows: list[dict]) -> str:
    complete = sum(r["acceptance"] == "complete" for r in rows)
    conflicts = sum(bool(r["conflicts"]) for r in rows)
    return f"{len(rows)} rows: {complete} complete, {len(rows) - complete} incomplete, {conflicts} with conflicts"


def main(argv: list[str]) -> int:
    rows = build(load_sources())
    text = render(rows)
    path = ROOT / OUTPUT
    if "--check" in argv:
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            print(f"FAIL: {OUTPUT} is stale; run python3 scripts/generate_acceptance_inventory.py")
            return 1
        print(f"{OUTPUT} is current ({summary(rows)})")
        return 0
    path.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT}: {summary(rows)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
