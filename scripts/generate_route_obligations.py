#!/usr/bin/env python3
"""Generate the route obligations (parity/route_obligations.toml).

One row per executing route, derived from the checked recipes and reconciled with
`crates/antecedent/data/support_matrix.json` (itself built from `parity/support_closed.toml`
and the license table):

  licensed        one row per licensed coordinate. It owes a compiler execution (the
                  checked-execution citation per estimator), an identification license, a
                  calibration license, an uncertainty statement and reachable evidence. The
                  identification and calibration licenses are copied from the explicit license
                  table, never inferred from the recipe.
  execution_only  one row per closed rule that still executes. It owes the compiler execution
                  and carries no identification or calibration license: a recipe that runs is
                  not a license.

    python3 scripts/generate_route_obligations.py           # rewrite the file
    python3 scripts/generate_route_obligations.py --check   # fail when the file is stale
"""

from __future__ import annotations

import hashlib
import json
import sys
import tomllib
from itertools import product
from pathlib import Path

from _repo import REPO_ROOT as ROOT
from _repo import ensure_scripts_on_path

ensure_scripts_on_path()
import gate_recipe_obligations as gate  # noqa: E402

OUTPUT = "parity/route_obligations.toml"
MATRIX = "crates/antecedent/data/support_matrix.json"
AXES = gate.AXIS
HEADER = (
    "# Generated by scripts/generate_route_obligations.py; do not edit.\n"
    "# One obligation row per executing route: what must be shown (compiler execution,\n"
    "# identification license, calibration license, uncertainty, evidence reachability).\n"
    "# Checked by scripts/check_route_obligations.py.\n"
)
LICENSED_FIELDS = (
    "id",
    "kind",
    *AXES,
    "estimators",
    "route_estimator",
    "matrix_digest",
    "license_basis",
    "compiler_execution",
    "identification_license",
    "calibration_license",
    "uncertainty",
    "evidence_reachability",
)
CLOSED_FIELDS = (
    "id",
    "kind",
    "queries",
    "graph_classes",
    "structures",
    "inferences",
    "validations",
    "coordinates",
    "reason_digest",
    "license_basis",
    "compiler_execution",
    "identification_license",
    "calibration_license",
    "uncertainty",
    "evidence_reachability",
)


def digest(value: object) -> str:
    blob = json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=True)
    return hashlib.sha256(blob.encode()).hexdigest()[:16]


def load_sources(root: Path = ROOT) -> dict:
    def toml(rel: str) -> dict:
        return tomllib.loads((root / rel).read_text(encoding="utf-8"))

    axes = toml("parity/support_axes.toml")
    return {
        "licensed": toml("parity/support_licensed.toml").get("cell", []),
        "closed": toml("parity/support_closed.toml").get("closed", []),
        "na": toml("parity/support_n_a.toml").get("n_a", []),
        "matrix": json.loads((root / MATRIX).read_text(encoding="utf-8")),
        "axes": {
            "query": list(axes["queries"]),
            "graph_class": list(axes["graph_classes"]),
            "structure": list(axes["structures"]),
            "inference": list(axes["inferences"]),
            "validation": list(axes["validations"]),
        },
    }


def licensed_row(cell: dict, matrix_cell: dict | None) -> dict:
    key = gate.coordinate(cell)
    citations = [
        f"{e['estimator']} = {e['test']}::{e['assertion']}"
        for e in cell.get("checked_execution") or []
        if isinstance(e, dict)
    ]
    records = list(cell.get("calibration") or [])
    reason = cell.get("calibration_reason") or ""
    reach = [cell.get("evidence_test") or ""]
    reach += [e["test"] for e in cell.get("checked_execution") or [] if isinstance(e, dict)]
    fixture = cell.get("known_truth_fixture") or ""
    return {
        "id": key,
        "kind": "licensed",
        **{axis: cell.get(axis) for axis in AXES},
        "estimators": list(cell.get("estimators") or []),
        "route_estimator": (matrix_cell or {}).get("route_estimator", ""),
        "matrix_digest": digest(matrix_cell) if matrix_cell else "",
        "license_basis": "explicit_license",
        "compiler_execution": citations,
        "identification_license": "|".join(
            [
                cell.get("evidence_kind") or "",
                cell.get("evidence_test") or "",
                cell.get("evidence_assertion") or "",
                fixture,
            ]
        ),
        "calibration_license": ("records:" + ",".join(records))
        if records
        else (f"reason:{reason}" if reason else ""),
        "uncertainty": reason or ("coverage_records" if records else ""),
        "evidence_reachability": sorted(set(reach)) + ([fixture] if fixture else []),
    }


def closed_rows(sources: dict) -> list[dict]:
    rules = sources["closed"]
    counts = [0] * len(rules)
    axes = sources["axes"]
    for values in product(*(axes[a] for a in AXES)):
        cell = dict(zip(AXES, values, strict=False))
        for i, rule in enumerate(rules):
            if gate.rule_matches(rule, cell):
                counts[i] += 1
                break
    rows = []
    for rule, count in zip(rules, counts, strict=False):
        if not rule.get("executes_unlicensed"):
            continue
        first = (rule.get("queries") or ["*"])[0]
        rdigest = digest(rule.get("reason", ""))
        rows.append(
            {
                "id": f"closed.{first}.{digest(gate.rule_key(rule))[:8]}",
                "kind": "execution_only",
                "queries": list(rule.get("queries") or []),
                "graph_classes": list(rule.get("graph_classes") or []),
                "structures": list(rule.get("structures") or []),
                "inferences": list(rule.get("inferences") or []),
                "validations": list(rule.get("validations") or []),
                "coordinates": count,
                "reason_digest": rdigest,
                "license_basis": "none",
                "compiler_execution": ["executes_through_compiler"],
                "identification_license": "none",
                "calibration_license": "none",
                "uncertainty": "unmeasured",
                "evidence_reachability": [],
            }
        )
    return rows


def build(sources: dict) -> list[dict]:
    matrix = {gate.coordinate(c): c for c in sources["matrix"].get("licensed") or []}
    rows = [licensed_row(c, matrix.get(gate.coordinate(c))) for c in sources["licensed"]]
    return rows + closed_rows(sources)


def fields_of(row: dict) -> tuple[str, ...]:
    return LICENSED_FIELDS if row.get("kind") == "licensed" else CLOSED_FIELDS


def render(rows: list[dict]) -> str:
    out = [HEADER]
    for row in rows:
        out.append("\n[[obligation]]\n")
        for name in fields_of(row):
            out.append(f"{name} = {json.dumps(row[name], ensure_ascii=True)}\n")
    return "".join(out)


def main(argv: list[str]) -> int:
    text = render(build(load_sources()))
    path = ROOT / OUTPUT
    if "--check" in argv:
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            print(f"FAIL: {OUTPUT} is stale; run python3 scripts/generate_route_obligations.py")
            return 1
        print(f"{OUTPUT} is current")
        return 0
    path.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
