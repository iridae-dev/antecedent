#!/usr/bin/env python3
"""Ledger of residual limitations and their owners.

A residual limitation is something a closure record, a recorded evidence row or checked work says
is still missing: a narrowed promise with its next attempt, a theory reason that closes a quadrant,
an evidence row whose interval has no coverage record, a failed promotion gate, or a source comment
that says a coverage claim has not been measured. This script scans

  parity/counterparts.toml                    narrowed promises and theory-closed quadrants
  parity/capabilities/route_manifest.toml     counterpart and narrowed next attempts on routes
  parity/*.toml `limitations` fields          sentences naming an unmeasured or uncalibrated claim
  parity/promotion_carryovers.toml            failed promotion gates and their corrective action
  crates, python, docs                        comments and prose saying a claim is not yet measured

and writes parity/residual_limitations.toml, one row per limitation with its source, its text and
its owner. The owner comes from the hand-maintained parity/residual_limitation_owners.toml: the
first rule whose patterns all match names either an open tracker item or a scope decision with a
written rationale. A limitation no rule matches is written without an owner and
scripts/check_residual_limitations.py rejects it.

    python3 scripts/residual_limitations.py            # rewrite the ledger
    python3 scripts/residual_limitations.py --check    # fail when the ledger is stale
"""

from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path

from _repo import REPO_ROOT as ROOT
from _repo import ensure_scripts_on_path, load_toml, read_text, write_text

ensure_scripts_on_path()

LEDGER = "parity/residual_limitations.toml"
OWNERS = "parity/residual_limitation_owners.toml"
TRACKER = "TODO.md"

HEADER = (
    "# Generated by scripts/residual_limitations.py; do not edit.\n"
    "# One row per residual limitation: where it is recorded, what it says and who owns it.\n"
    "# Owners come from parity/residual_limitation_owners.toml (an open tracker item or a scope\n"
    "# decision with a rationale); scripts/check_residual_limitations.py rejects unmapped rows,\n"
    "# self-ownership, closed or absent owners and a decision without a rationale.\n"
)

# A sentence of a recorded `limitations` field is a limitation when it says a claim is unmeasured.
EVIDENCE_RESIDUAL = re.compile(
    r"(?i)no coverage record|has not been measured|not been measured|not yet measured"
    r"|remains unmeasured|(?<!no-)\bunmeasured\b|\bnot measured\b"
)
# Source comments and prose: the explicit residual phrases.
CODE_RESIDUAL = re.compile(
    r"(?i)still missing|remains open|has not been measured|not been measured"
    r"|not yet (?:measured|implemented|wired|attempted|calibrated)"
)
SCANNED_ROOTS = ("crates", "python", "docs")
SCANNED_SUFFIXES = {".rs", ".py", ".md"}
# Generated prose repeats the evidence rows scanned above; tests assert refusal strings.
SKIPPED_PATHS = ("docs/support-matrix.md", "docs/graphless-support-matrix.md")
SKIPPED_PARITY = {
    "counterparts.toml", "residual_limitations.toml", "residual_limitation_owners.toml",
    "promotion.toml", "evidence_ledger.toml", "transport_stages.toml",
}
ITEM_PREFIX = re.compile(r"^([A-Z]\d+(?:\.\d+)?)\b")


def toml_str(value: str) -> str:
    return json.dumps(value, ensure_ascii=True)


def digest(*parts: str) -> str:
    return hashlib.sha1("\x1f".join(parts).encode()).hexdigest()[:10]


def squash(text: str) -> str:
    return " ".join(text.split())


def sentences(text: str) -> list[str]:
    return [s.strip() for s in re.split(r"(?<=[.;])\s+", squash(text)) if s.strip()]


# ---------------------------------------------------------------------------------- tracker


def parse_tracker(text: str) -> dict[str, bool]:
    """Item id -> open, for every checkbox item of the tracker."""
    items: dict[str, bool] = {}
    for line in text.splitlines():
        m = re.match(r"^- \[([ xX])\] \*\*(.+?)\*\*", line)
        if not m:
            continue
        title = m.group(2).strip()
        ident = ITEM_PREFIX.match(title)
        key = ident.group(1) if ident else re.split(r"\s+[—-]\s+", title)[0].strip()
        items[key] = m.group(1) == " "
    return items


# ---------------------------------------------------------------------------------- scanners


def counterpart_limitations(rows: list[dict]) -> list[dict]:
    out = []
    for row in rows:
        narrowed = row.get("closure") == "narrowed_promise"
        theory = row.get("status") == "not_applicable_with_theory_reason"
        if not (narrowed or theory):
            continue
        text = squash(row.get("reason", ""))
        if row.get("next_attempt"):
            text = f"{text} Next attempt: {squash(row['next_attempt'])}"
        item = ITEM_PREFIX.match(row["id"])
        out.append({
            "id": f"counterpart.{row['id']}",
            "kind": "narrowed_promise" if narrowed else "theory_reason",
            "source": "parity/counterparts.toml",
            "locator": row["id"],
            "text": text,
            "item": item.group(1) if item else "",
        })
    return out


ROUTE_FIELDS = (
    ("counterpart_next_attempt", "counterpart_reason", "route_counterpart"),
    ("narrowed_next_attempt", "narrowed_reason", "route_narrowed"),
)


def route_limitations(routes: list[dict]) -> list[dict]:
    out = []
    for route in routes:
        for attempt, reason, kind in ROUTE_FIELDS:
            if not route.get(attempt):
                continue
            text = f"{squash(route.get(reason, ''))} Next attempt: {squash(route[attempt])}".strip()
            out.append({
                "id": f"route.{route['id']}.{kind}",
                "kind": kind,
                "source": "parity/capabilities/route_manifest.toml",
                "locator": route["id"],
                "text": text,
                "item": "",
            })
    return out


def _walk_limitations(node: object, found: list[tuple[str, str]]) -> None:
    if isinstance(node, dict):
        for key, value in node.items():
            if key == "limitations" and isinstance(value, str):
                found.append((str(node.get("id") or node.get("key") or node.get("query") or ""), value))
            else:
                _walk_limitations(value, found)
    elif isinstance(node, list):
        for value in node:
            _walk_limitations(value, found)


def evidence_limitations(source: str, document: dict) -> list[dict]:
    """One row per distinct unmeasured-claim sentence of a file, with the count of rows saying it."""
    found: list[tuple[str, str]] = []
    _walk_limitations(document, found)
    grouped: dict[str, int] = {}
    for _, field in found:
        for sentence in sentences(field):
            if EVIDENCE_RESIDUAL.search(sentence):
                grouped[sentence] = grouped.get(sentence, 0) + 1
    stem = Path(source).stem
    return [
        {
            "id": f"evidence.{stem}.{digest(source, sentence)}",
            "kind": "evidence_limit",
            "source": source,
            "locator": f"{count} rows" if count > 1 else "1 row",
            "text": sentence,
            "item": "",
        }
        for sentence, count in sorted(grouped.items())
    ]


def carryover_limitations(document: dict) -> list[dict]:
    out = []
    for cell in document.get("cell", []):
        gates = ", ".join(cell.get("failed_gates", []))
        text = f"{gates}: {squash(cell.get('corrective_action', ''))}"
        out.append({
            "id": f"carryover.{cell['id']}",
            "kind": "failed_gate",
            "source": "parity/promotion_carryovers.toml",
            "locator": cell["id"],
            "text": text,
            "item": "",
        })
    return out


def _is_test_path(path: Path) -> bool:
    name = path.name
    return (
        name in {"tests.rs", "conftest.py"}
        or name.startswith("test_")
        or "tests" in path.parts
        or "target" in path.parts
        or ".venv" in path.parts
    )


def phrase_limitations(root: Path) -> list[dict]:
    """Source comments and prose that say a claim is still missing or not yet measured."""
    out = []
    seen: dict[str, int] = {}
    for top in SCANNED_ROOTS:
        base = root / top
        if not base.is_dir():
            continue
        for path in sorted(base.rglob("*")):
            if path.suffix not in SCANNED_SUFFIXES or not path.is_file() or _is_test_path(path):
                continue
            rel = path.relative_to(root).as_posix()
            if rel in SKIPPED_PATHS:
                continue
            for line in read_text(path, errors="replace").splitlines():
                if not CODE_RESIDUAL.search(line):
                    continue
                text = squash(line.strip().lstrip("/!#*>-` ").strip())
                key = f"{rel}\x1f{text}"
                seen[key] = seen.get(key, 0) + 1
                suffix = "" if seen[key] == 1 else f".{seen[key]}"
                out.append({
                    "id": f"phrase.{Path(rel).stem}.{digest(rel, text)}{suffix}",
                    "kind": "source_phrase",
                    "source": rel,
                    "locator": "",
                    "text": text,
                    "item": "",
                })
    return out


def collect(root: Path = ROOT) -> list[dict]:
    rows: list[dict] = []
    rows += counterpart_limitations(load_toml(root / "parity/counterparts.toml").get("row", []))
    manifest = load_toml(root / "parity/capabilities/route_manifest.toml")
    rows += route_limitations(manifest.get("route", []))
    for path in sorted((root / "parity").glob("**/*.toml")):
        if path.name in SKIPPED_PARITY or path.parent.name == "release_snapshots":
            continue
        rel = path.relative_to(root).as_posix()
        if rel == "parity/capabilities/route_manifest.toml":
            continue
        rows += evidence_limitations(rel, load_toml(path))
    carry = root / "parity/promotion_carryovers.toml"
    if carry.is_file():
        rows += carryover_limitations(load_toml(carry))
    rows += phrase_limitations(root)
    ids = [r["id"] for r in rows]
    duplicated = sorted({i for i in ids if ids.count(i) > 1})
    if duplicated:
        raise SystemExit(f"duplicate limitation ids: {duplicated[:5]}")
    return sorted(rows, key=lambda r: (r["source"], r["id"]))


# ---------------------------------------------------------------------------------- owners


def rule_matches(rule: dict, row: dict) -> bool:
    """Every pattern the rule carries must match; a rule with no pattern matches nothing."""
    patterns = {"limitation": "id", "kind": "kind", "path": "source", "locator": "locator", "text": "text"}
    present = [k for k in patterns if k in rule]
    if not present:
        return False
    for key in present:
        value = row[patterns[key]]
        if key == "limitation":
            if value != rule[key]:
                return False
        elif not re.search(rule[key], value):
            return False
    return True


def assign(rows: list[dict], rules: list[dict]) -> list[dict]:
    """Attach the first matching rule's owner or scope decision; leave a row unowned otherwise."""
    out = []
    for row in rows:
        row = dict(row)
        row.setdefault("owner", "")
        row.setdefault("decision", "")
        row.setdefault("rationale", "")
        row["rule"] = ""
        for rule in rules:
            if rule_matches(rule, row):
                row["rule"] = rule.get("name", "")
                row["owner"] = rule.get("owner", "")
                row["decision"] = rule.get("decision", "")
                row["rationale"] = squash(rule.get("rationale", ""))
                if rule.get("item"):
                    row["item"] = rule["item"]
                break
        out.append(row)
    return out


def render(rows: list[dict]) -> str:
    lines = [HEADER, "schema = 1", f"count = {len(rows)}", ""]
    for row in rows:
        lines.append("[[limitation]]")
        for key in ("id", "kind", "source", "locator", "text", "item", "owner", "decision", "rationale", "rule"):
            lines.append(f"{key} = {toml_str(row.get(key, ''))}")
        lines.append("")
    return "\n".join(lines)


def build(root: Path = ROOT) -> str:
    rules = load_toml(root / OWNERS).get("owner", []) if (root / OWNERS).is_file() else []
    return render(assign(collect(root), rules))


def main(argv: list[str]) -> int:
    text = build()
    target = ROOT / LEDGER
    if "--check" in argv:
        if not target.is_file() or read_text(target) != text:
            print(f"{LEDGER} is stale; run python3 scripts/residual_limitations.py", file=sys.stderr)
            return 1
        return 0
    write_text(target, text)
    print(f"wrote {LEDGER}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
