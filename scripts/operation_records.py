#!/usr/bin/env python3
"""Operation records: one description, with the same fields, for every verified operation.

`parity/operation_records.toml` holds one record per verified operation: every operation an
assurance record (`parity/assurance_records.toml`) lists in its `operations`. A record is keyed
by the operation's existing identity, its defining Rust path (`id`), and is attached to the
operation's code by `file` and `item` (a scripts/rust_items.py locator). Its fields are those
of the roadmap's operation records:

    inputs          named quantities and the kinds of evidence accepted
    output          the resulting quantity and its identity
    premises        what must hold; each premise names the token (reason code, refusal
                    variant or the call that refuses) the operation refuses or restricts with
                    when it fails (`refused_with`, found in the operation's item or in the
                    helper `item` of the same file it delegates to), or says why the operation
                    cannot check it (`unchecked`); `tests` name the cases that remove it
    transformation  the formula, estimation step or computation
    justification   generated: every check of every assurance record listing the operation,
                    by kind (`binds_item`: the check's digest binds the operation's item, so
                    a change to it stales the check), and the identity-site checks that run
                    on its item
    implementation  generated: how the operation is reached (public path, facade re-exports,
                    compiled-path disposition, plan route and support unit) and which
                    assurance records bind its item by digest
    obligations     requirements not yet met that the output carries to its users, each with
                    the identifier it is carried in (`carried_in`)
    limitations     what is not justified

A list field may be empty only with a reason in `empty.<field>`. A record attached to a plan
route (`route`) whose support unit is a capability record takes `inputs`, `output` and
`transformation` from that record instead of hand-written text. `generated` names the fields
this script owns; every other field is written by hand.

    python3 scripts/operation_records.py check        # every verified operation has a current record
    python3 scripts/operation_records.py --write      # regenerate the generated fields, add skeletons
    python3 scripts/operation_records.py --self-test  # the check rejects deliberately broken inputs

`check` reads files only and fails when a verified operation has no record, a record describes
no verified operation, a field is empty without a reason, a referenced item, refusal token,
carried identifier, route, test or assurance record does not exist, an assurance check binds
an operation's item without the record listing the operation, or a generated field or the
file's layout differs from what `--write` produces.
"""

