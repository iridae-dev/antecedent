"""Generated route behaviour: what code and the registries state, not what a record repeats.

A capability record keeps what only a person can say: the claim, its provenance, the
evidence it cites and its boundary prose. The behaviour that follows from it is derived:

* the `(code, detail)` refusal pairs of a supported record: its declared details joined
  with the reason-detail registry (`parity/reason_details.toml`) and proven emitted by
  non-test source;
* the stage, status and reason code of every route a record owns in the transport stage
  registry, so `parity/transport_stages.toml` holds only the contract a stage adds.

`scripts/generate_route_behaviour.py` writes the result to `parity/generated/route_behaviour.toml`
and `--check` fails on drift; `scripts/check_capability_records.py` reads that file instead of
comparing hand-written rows against source. This module is pure: no argv, no cargo.
"""

import tomllib
from pathlib import Path

import _repo
from _repo import REPO_ROOT

GENERATED = "parity/generated/route_behaviour.toml"
REASON_DETAILS = "parity/reason_details.toml"
STAGES = "parity/transport_stages.toml"
DERIVED_ROW_FIELDS = ("stage", "status", "reason_code", "claim")
HEADER = (
    "# Generated by scripts/generate_route_behaviour.py from parity/capability_records.toml,\n"
    "# parity/reason_details.toml and non-test source. Do not edit; rerun the script.\n"
    "# A supported record's refusals are its declared details joined with the registry's\n"
    "# codes and proven emitted; a route is a transport stage route its record owns.\n"
)


def load_details(path: Path) -> dict[str, list[str]]:
    """Detail id -> the reason codes it is refused under."""
    rows = _repo.load_toml(path).get("detail", [])
    return {row["id"]: list(row.get("codes", [])) for row in rows}


def owned_routes(record: dict) -> list[dict]:
    return [
        r for r in record.get("routes") or [] if r.get("registry", "transport_stages") == "transport_stages"
    ]


def derive(records: list[dict], details: dict[str, list[str]], emitted: dict[str, dict]) -> tuple[dict, list[str]]:
    """The generated data and the problems that stop it being derived.

    `emitted` is namespace -> detail -> [(path, in_crate, Lit)] (capability_source's scan of
    non-test source). A supported record's detail must be registered, emitted by source, and
    any code source proves for it must be one the registry lists."""
    problems: list[str] = []
    out: dict[str, dict] = {}
    for rec in records:
        rid, supported = rec.get("id", "?"), rec.get("status") == "supported"
        entry: dict = {"status": rec.get("status", "")}
        if supported:
            pairs: list[tuple[str, str]] = []
            for row in rec.get("refusals") or []:
                detail = row.get("detail", "")
                codes = details.get(detail)
                if codes is None:
                    problems.append(f"{rid}: refusal detail {detail} is not in {REASON_DETAILS}")
                    continue
                uses = emitted.get(detail.split(".")[0], {}).get(detail, [])
                proven = {lit.reason_code for _, _, lit in uses if lit.reason_code is not None}
                if proven - set(codes):
                    problems.append(
                        f"{rid}: source emits {detail} under {', '.join(sorted(proven - set(codes)))}, "
                        f"which {REASON_DETAILS} does not list"
                    )
                for code in codes:
                    if (code, detail) not in pairs:
                        pairs.append((code, detail))
            entry["refusals"] = pairs
        entry["routes"] = [
            {k: v for k, v in (("route", r.get("name")), ("stage", r.get("stage")),
                               ("status", r.get("status")), ("reason_code", r.get("reason_code")),
                               ("claim", r.get("claim") or rec.get("inference_claim")))
             if v is not None}
            for r in owned_routes(rec)
        ]
        out[rid] = entry
    return out, problems


def _q(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(data: dict) -> str:
    lines = [HEADER, "version = 1", ""]
    for rid, entry in data.items():
        lines += ["[[record]]", f"id = {_q(rid)}", f"status = {_q(entry['status'])}"]
        if "refusals" in entry:
            lines.append("refusals = [")
            lines += [f"  {{ code = {_q(c)}, detail = {_q(d)} }}," for c, d in entry["refusals"]]
            lines.append("]")
        lines.append("routes = [")
        for r in entry["routes"]:
            lines.append("  { " + ", ".join(f"{k} = {_q(v)}" for k, v in r.items()) + " },")
        lines += ["]", ""]
    return "\n".join(lines)


def parse(text: str) -> dict:
    """The inverse of `render`, in `derive`'s shape."""
    rows = tomllib.loads(text).get("record", [])
    out: dict[str, dict] = {}
    for row in rows:
        entry: dict = {"status": row.get("status", "")}
        if "refusals" in row:
            entry["refusals"] = [(r["code"], r["detail"]) for r in row["refusals"]]
        entry["routes"] = list(row.get("routes", []))
        out[row["id"]] = entry
    return out


def load(path: Path) -> dict | None:
    return parse(path.read_text(encoding="utf-8")) if path.is_file() else None


def materialise_refusals(records: list[dict], generated: dict) -> list[str]:
    """Give each supported record's refusal rows the codes the generated data states.

    A row is `{ detail, when?, remedy? }`; a row carrying its own `code` restates what is
    generated. Returns the problems found; the rows are expanded in place."""
    problems: list[str] = []
    for rec in records:
        entry = generated.get(rec.get("id"))
        if rec.get("status") != "supported" or entry is None:
            continue
        codes: dict[str, list[str]] = {}
        for code, detail in entry.get("refusals", []):
            codes.setdefault(detail, []).append(code)
        rows = []
        for row in rec.get("refusals") or []:
            if "code" in row:
                problems.append(f"{rec.get('id')}: refusal {row.get('detail')} states its code {row['code']}; it is generated")
                rows.append(row)
                continue
            rows.extend({**row, "code": c} for c in codes.get(row.get("detail", ""), [None]) if c is not None)
        rec["refusals"] = rows
    return problems


def stage_routes(root: Path, stages: dict, generated: dict | None) -> tuple[list[dict], list[str]]:
    """The transport stage rows with the generated stage, status and reason code merged in.

    A row of a record-owned route may not state those fields itself. A generated route
    without a row becomes a row of its own."""
    problems: list[str] = []
    owned: dict[str, dict] = {}
    for rid, entry in (generated or {}).items():
        for r in entry["routes"]:
            owned[r["route"]] = {**r, "record": rid}
    rows = []
    seen = set()
    for row in stages.get("routes", []):
        name = row.get("route")
        seen.add(name)
        gen = owned.get(name)
        if gen is None:
            rows.append(row)
            continue
        restated = [f for f in DERIVED_ROW_FIELDS if f in row]
        if restated:
            problems.append(f"{name}: stage row states {', '.join(restated)}; generated from its record")
        rows.append({**gen, **{k: v for k, v in row.items() if k not in DERIVED_ROW_FIELDS}})
    rows.extend(gen for name, gen in owned.items() if name not in seen)
    return rows, problems


def load_stage_routes(root: Path = REPO_ROOT, stages_path: Path | None = None) -> list[dict]:
    """The merged stage rows of the committed registries (readers outside the checker)."""
    stages = _repo.load_toml(stages_path or root / STAGES)
    rows, _ = stage_routes(root, stages, load(root / GENERATED))
    return rows
