use std::sync::Arc;

use crate::{LearnError, LearnerProvenance};

/// Provenance attached to one posterior-prediction matrix.
#[derive(Clone, Debug, Eq, PartialEq)]
pub struct PosteriorPredictionProvenance {
    /// Stable model identity, including its basis or learner configuration.
    pub model_id: Arc<str>,
    /// Stable prior identity, including its declared scale or bank reference.
    pub prior_id: Arc<str>,
    /// Implementation provenance.
    pub model: LearnerProvenance,
}

/// Small diagnostics summary for a joint prediction matrix.
#[derive(Clone, Debug, PartialEq)]
pub struct PosteriorPredictionDiagnostics {
    /// Number of retained joint draws.
    pub draw_count: usize,
    /// Number of rows represented in every draw.
    pub row_count: usize,
    /// Number of named prediction targets in each row.
    pub target_count: usize,
    /// Number of distinct validation folds, or `None` for non-cross-fitted predictions.
    pub fold_count: Option<usize>,
    /// Minimum prediction value over the complete matrix.
    pub minimum: f64,
    /// Maximum prediction value over the complete matrix.
    pub maximum: f64,
}

/// Posterior predictions that preserve joint dependence across targets and rows.
///
/// `values` is draw-major with layout `[draw, target, row]`; entries for all
/// targets and rows in one posterior draw therefore remain coupled. `row_ids`
/// identify physical observations and `fold_ids`, when supplied, preserve the
/// out-of-fold assignment used to produce each row's predictions.
#[derive(Clone, Debug, PartialEq)]
pub struct PosteriorPrediction {
    /// Number of joint draws.
    pub draw_count: usize,
    /// Ordered target names.
    pub target_names: Arc<[Arc<str>]>,
    /// Stable physical row identity in the same order as the row axis.
    pub row_ids: Arc<[u32]>,
    /// Fold identity per row, if generated by cross-fitting.
    pub fold_ids: Option<Arc<[u16]>>,
    /// Draw-major `[draw, target, row]` prediction values.
    pub values: Arc<[f64]>,
    /// Model and prior provenance.
    pub provenance: PosteriorPredictionProvenance,
    /// Shape and finite-range diagnostics.
    pub diagnostics: PosteriorPredictionDiagnostics,
}

impl PosteriorPrediction {
    /// Construct a validated joint posterior-prediction matrix.
    ///
    /// # Errors
    ///
    /// Returns [`LearnError::Shape`] when the dimensions, row identities, fold
    /// identities, or finite-value contract do not match.
    pub fn new(
        draw_count: usize,
        target_names: Vec<Arc<str>>,
        row_ids: Vec<u32>,
        fold_ids: Option<Vec<u16>>,
        values: Vec<f64>,
        provenance: PosteriorPredictionProvenance,
    ) -> Result<Self, LearnError> {
        let row_count = row_ids.len();
        let target_count = target_names.len();
        let expected =
            draw_count.checked_mul(target_count).and_then(|size| size.checked_mul(row_count));
        if draw_count == 0 || row_count == 0 || target_count == 0 || expected != Some(values.len())
        {
            return Err(LearnError::Shape {
                message: "posterior prediction dimensions do not match draw × target × row values",
            });
        }
        if row_ids.iter().copied().collect::<std::collections::HashSet<_>>().len() != row_count {
            return Err(LearnError::Shape {
                message: "posterior prediction row ids must be unique",
            });
        }
        if fold_ids.as_ref().is_some_and(|folds| folds.len() != row_count) {
            return Err(LearnError::Shape {
                message: "posterior prediction fold ids length != rows",
            });
        }
        if target_names.iter().any(|name| name.trim().is_empty()) {
            return Err(LearnError::Shape {
                message: "posterior prediction target names must be nonempty",
            });
        }
        if values.iter().any(|value| !value.is_finite()) {
            return Err(LearnError::Shape {
                message: "posterior prediction values must be finite",
            });
        }
        let minimum = values.iter().copied().fold(f64::INFINITY, f64::min);
        let maximum = values.iter().copied().fold(f64::NEG_INFINITY, f64::max);
        let fold_count = fold_ids
            .as_ref()
            .map(|folds| folds.iter().copied().collect::<std::collections::HashSet<_>>().len());
        Ok(Self {
            draw_count,
            target_names: Arc::from(target_names),
            row_ids: Arc::from(row_ids),
            fold_ids: fold_ids.map(Arc::from),
            values: Arc::from(values),
            provenance,
            diagnostics: PosteriorPredictionDiagnostics {
                draw_count,
                row_count,
                target_count,
                fold_count,
                minimum,
                maximum,
            },
        })
    }

    /// Borrow one target's contiguous row vector for a draw.
    ///
    /// # Errors
    ///
    /// Returns [`LearnError::Shape`] when `draw` or `target` is out of range.
    pub fn draw_target(&self, draw: usize, target: usize) -> Result<&[f64], LearnError> {
        if draw >= self.draw_count || target >= self.target_names.len() {
            return Err(LearnError::Shape {
                message: "posterior prediction draw/target out of range",
            });
        }
        let rows = self.row_ids.len();
        let start = (draw * self.target_names.len() + target) * rows;
        Ok(&self.values[start..start + rows])
    }
}
