//! A participant-level adaptive family: three or four arms, participant-level
//! randomization, a few binary responses per participant, historical
//! informative priors, adaptive allocation and decision-based stopping, all
//! at once.
//!
//! # The model and the posterior update
//!
//! Participant `i` is randomized to arm `k` and gives `m` binary responses
//! (`m` is 3 or 6 in the delivered configurations, any `m` from 2 to
//! [`MAX_PARTICIPANT_RESPONSES`] is accepted). Their success count `s_i` is
//! beta-binomial: given a participant propensity `p_i ~ Beta(mu_k kappa,
//! (1 - mu_k) kappa)`, `s_i ~ Binomial(m, p_i)`, with `kappa = (1 - rho) / rho`
//! and `rho` the declared intra-participant correlation. Then `s_i / m` has
//! mean `mu_k` and variance `mu_k (1 - mu_k) D / m` with the design effect
//! `D = 1 + (m - 1) rho`; `rho = 0` is `m` independent Bernoulli responses.
//!
//! The arm mean `mu_k` has a Beta prior `Beta(alpha0_k, beta0_k)` resolved from
//! a declared initial prior and the historical sources the arm borrows from
//! ([`super::historical_prior`]). The posterior of the arm means after the
//! *completed* participants (follow-up finished) is the exact one: the
//! likelihood of an arm is the product over its participants of the
//! beta-binomial mass of their success counts, a function of the arm mean and
//! the correlation, and the posterior is evaluated by the two-dimensional
//! quadrature of [`super::participant_posterior`] (no conjugate form exists
//! for a positive correlation, and none is imitated). The posterior probability
//! of being best, the expected loss, the exceedance of a margin and the
//! moments all come from that one posterior, and the simulation, the exact
//! reading of a retained history and the declared decisions share that single
//! implementation.
//!
//! The correlation is either declared (a stated value; `0` declares the
//! responses independent, where the posterior is the conjugate Beta) or
//! estimated: a `Beta` prior on it, shared by all arms and fixed before
//! recruitment, is integrated jointly with the arm means, so the posterior of
//! every arm is a mixture over the correlation weighted by what the data say
//! about it, and the correlation's own posterior mean and standard deviation
//! are reported at every look.
//!
//! The posterior depends on the data only through the completed participants'
//! counts, so by the likelihood principle it is the same under any allocation
//! that depends on the observed history and independent randomization only.
//!
//! # Allocation and stopping
//!
//! Allocation is Thompson sampling with a minimum exploration probability: the
//! probabilities that each arm is best, clamped from below and renormalized by
//! [`super::procedure_law::apply_exploration_floor`] (the same function the
//! single-outcome exact law uses). At each look, after the participants whose
//! follow-up has completed are revealed, the declared decisions are evaluated
//! in this order and the first that holds ends the procedure: the smallest
//! posterior expected loss of choosing an arm below its threshold (decide that
//! arm), futility (no treatment arm has a posterior probability of exceeding
//! the control by the margin that reaches the threshold; decide the control),
//! and the recruitment cap. A procedure that no decision ends runs its
//! schedule and selects the arm with the highest posterior mean.
//!
//! # Two separate claims
//!
//! Every look reports a [`PosteriorClaim`] and a [`FrequentistClaim`], never
//! merged. The posterior claim is the Bayesian one above. The frequentist claim
//! is a time-uniform confidence sequence for each arm's mean, read from the
//! participants' success proportions (bounded in `[0, 1]`, independent across
//! participants whatever the correlation among one participant's responses),
//! valid at every look and at the data-dependent stopping time.
//!
//! The sequence is the variance-adaptive predictable plug-in empirical
//! Bernstein betting sequence of Waudby-Smith and Ramdas (2024), documented in
//! [`super::confidence_sequence`]. Its validity does not depend on how the
//! arms were allocated: for each arm the sequence is built from that arm's own
//! observations in the order the arm completes them, and under the stack
//! model of a bandit (the `j`-th completed participant of an arm is the
//! `j`-th element of that arm's independent sequence of outcomes, whatever
//! the allocation that decided when it was drawn) the filtration of the arm's
//! sequence is generated by its own previous outcomes, so the tilts are
//! predictable and the Ville bound holds for every arm size at once. A
//! data-dependent allocation or stopping rule only selects which arm size is
//! read, so the readings at the looks and at the stopping look are covered.
//!
//! The miscoverage `alpha` is split evenly over the `K` arms, each sequence at
//! `alpha / K`: all `K` arm sequences cover their means at once with
//! probability at least `1 - alpha`. Every contrast between any two arms is
//! then covered at once (the difference of two covered means lies between the
//! difference of the bounds), so the comparison of the data-selected best
//! treatment with the control is covered whatever the data selected: no
//! further correction for the selection is needed or applied. A comparison is
//! built from two arm sequences and so spends `2 alpha / K`. Procedures
//! declared under the earlier normal-mixture Hoeffding sequence
//! ([`SequenceKind::MixtureHoeffding`], arms at `alpha / (2 (K - 1))`) keep
//! that construction when they are replayed. The sequence is a finite-time
//! theorem under its premise; it is not a measured coverage of the whole
//! procedure, and every number carries [`DERIVED_UNMEASURED`].
//!
//! SPDX-License-Identifier: MIT OR Apache-2.0

