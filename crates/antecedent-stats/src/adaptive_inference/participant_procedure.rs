/// Futility: stop when no treatment arm is likely to beat the control by a
/// margin that matters.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct FutilityRule {
    /// Smallest advantage over the control that matters, in `[0, 1)`.
    pub margin: f64,
    /// Posterior probability of exceeding the control by the margin below
    /// which an arm is judged futile, in `(0, 0.5)`.
    pub threshold: f64,
}

/// What the procedure decides at a look.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct DecisionRules {
    /// Stop when the smallest posterior expected loss of choosing an arm
    /// falls below this, in units of the success probability.
    pub loss_threshold: f64,
    /// Futility, if declared.
    pub futility: Option<FutilityRule>,
    /// Stop at the first look at which this many participants are enrolled.
    pub participant_cap: Option<u32>,
}

/// The confidence sequences read at every look.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct AnytimeSettings {
    /// Total miscoverage of the simultaneous family, in `(0, 1)`.
    pub alpha: f64,
    /// Participants per arm at which a mixture-Hoeffding sequence is
    /// tightest. The predictable plug-in sequence follows the data's own
    /// variance and does not read it; it must still be positive.
    pub tuning_samples: f64,
}

/// Everything a producer states about the participant-level procedure. Each
/// declared quantity is an `Option` so that a missing declaration is
/// representable and refused with its own detail.
#[derive(Clone, Debug, PartialEq)]
pub struct ParticipantDeclaration {
    /// Number of arms; arm 0 is the control.
    pub arms: usize,
    /// Binary responses per participant.
    pub responses: Option<u32>,
    /// A declared intra-participant correlation `rho` in `[0, 1)`; zero
    /// declares the responses independent. Exactly one of this and
    /// [`Self::correlation_prior`] is given.
    pub correlation: Option<f64>,
    /// A `Beta` prior on the intra-participant correlation, shared by the
    /// arms and integrated jointly with the arm means (estimated correlation).
    /// Frozen before recruitment like the arm priors.
    pub correlation_prior: Option<CorrelationPrior>,
    /// Arm priors and the historical sources they borrow from. Frozen before
    /// recruitment.
    pub borrowing: Option<BorrowingPlan>,
    /// Participants enrolled at each look.
    pub enrolment: Option<Vec<u32>>,
    /// Looks between a participant's enrolment and the completion of their
    /// follow-up.
    pub lag_looks: usize,
    /// The minimum probability any arm keeps under the allocation.
    pub min_exploration: Option<f64>,
    /// The decisions taken at the looks.
    pub decisions: Option<DecisionRules>,
    /// The confidence sequences read at every look.
    pub anytime: Option<AnytimeSettings>,
}

/// A validated participant-level procedure.
#[derive(Clone, Debug, PartialEq)]
pub struct ParticipantSpec {
    declaration: ParticipantDeclaration,
    borrowing: BorrowingPlan,
    responses: u32,
    correlation: CorrelationModel,
    priors: Vec<ResolvedArmPrior>,
    enrolment: Vec<u32>,
    min_exploration: f64,
    decisions: DecisionRules,
    anytime: AnytimeSettings,
    sequence: SequenceKind,
}

fn in_open_unit(value: f64) -> bool {
    value.is_finite() && value > 0.0 && value < 1.0
}

impl ParticipantSpec {
    /// Validate a declaration.
    ///
    /// # Errors
    /// One gap per missing element and per invalid element; nothing is
    /// defaulted.
    #[allow(
        clippy::too_many_lines,
        reason = "one flat list of the element checks keeps each refusal next to its condition"
    )]
    pub fn new(declaration: ParticipantDeclaration) -> Result<Self, ProcedureContractError> {
        let mut gaps = Vec::new();
        let arms = declaration.arms;
        if !(2..=MAX_PROCEDURE_ARMS).contains(&arms) {
            gaps.push(ContractGap::Invalid("adaptive_inference.arms_invalid"));
        }
        match declaration.responses {
            None => gaps.push(ContractGap::OutcomeStructureMissing),
            Some(m) if !(2..=MAX_PARTICIPANT_RESPONSES).contains(&m) => {
                gaps.push(ContractGap::Invalid("adaptive_inference.measurements_invalid"));
            }
            Some(_) => {}
        }
        let correlation = match (declaration.correlation, declaration.correlation_prior) {
            (None, None) => {
                gaps.push(ContractGap::WithinUnitCorrelationMissing);
                None
            }
            (Some(rho), None) if rho.is_finite() && (0.0..1.0).contains(&rho) => {
                Some(CorrelationModel::Declared(rho))
            }
            (None, Some(prior)) if prior.is_valid() => Some(CorrelationModel::Estimated(prior)),
            _ => {
                gaps.push(ContractGap::Invalid("adaptive_inference.correlation_invalid"));
                None
            }
        };
        let resolved = match &declaration.borrowing {
            None => {
                gaps.push(ContractGap::HistoricalBorrowingMissing);
                None
            }
            Some(plan) => {
                let resolved = plan.resolve().filter(|r| r.len() == arms);
                if resolved.is_none() {
                    gaps.push(ContractGap::Invalid("adaptive_inference.historical_prior_invalid"));
                }
                resolved
            }
        };
        let mut total = 0_u64;
        match &declaration.enrolment {
            None => gaps.push(ContractGap::EnrolmentScheduleMissing),
            Some(schedule) => {
                total = schedule.iter().map(|&n| u64::from(n)).sum();
                if schedule.len() < 2 || schedule.contains(&0) {
                    gaps.push(ContractGap::Invalid("adaptive_inference.looks_not_ordered"));
                }
                if schedule.len() > MAX_PARTICIPANT_LOOKS {
                    gaps.push(ContractGap::Capacity(CapacityError::DeclaredLooks {
                        limit: MAX_PARTICIPANT_LOOKS as u64,
                        requested: schedule.len() as u64,
                    }));
                }
                if total > u64::from(MAX_PROCEDURE_UNITS) {
                    gaps.push(ContractGap::Capacity(CapacityError::DeclaredUnits {
                        limit: u64::from(MAX_PROCEDURE_UNITS),
                        requested: total,
                    }));
                }
            }
        }
        if declaration.lag_looks > MAX_UNIT_LAG {
            gaps.push(ContractGap::Invalid("adaptive_inference.outcome_availability_invalid"));
        }
        match declaration.min_exploration {
            None => gaps.push(ContractGap::AssignmentPolicyMissing),
            Some(floor) => {
                if !(floor.is_finite() && floor > 0.0 && floor <= 1.0 / arms as f64) {
                    gaps.push(ContractGap::Invalid("adaptive_inference.rule_mismatch"));
                }
            }
        }
        match &declaration.decisions {
            None => gaps.push(ContractGap::StoppingRuleMissing),
            Some(rules) => {
                let futility_ok = rules.futility.is_none_or(|f| {
                    f.margin.is_finite()
                        && (0.0..1.0).contains(&f.margin)
                        && f.threshold.is_finite()
                        && f.threshold > 0.0
                        && f.threshold < 0.5
                });
                let cap_ok =
                    rules.participant_cap.is_none_or(|cap| cap > 0 && u64::from(cap) <= total);
                let loss_ok = rules.loss_threshold.is_finite() && rules.loss_threshold > 0.0;
                if !(loss_ok && futility_ok && cap_ok) {
                    gaps.push(ContractGap::Invalid("adaptive_inference.rule_mismatch"));
                }
            }
        }
        match &declaration.anytime {
            None => gaps.push(ContractGap::AnytimeSettingsMissing),
            Some(settings) => {
                if !(in_open_unit(settings.alpha)
                    && settings.tuning_samples.is_finite()
                    && settings.tuning_samples > 0.0)
                {
                    gaps.push(ContractGap::Invalid("adaptive_inference.anytime_settings_invalid"));
                }
            }
        }
        if !gaps.is_empty() {
            return Err(ProcedureContractError { gaps });
        }
        match (
            declaration.responses,
            correlation,
            declaration.borrowing.clone(),
            resolved,
            declaration.enrolment.clone(),
            declaration.min_exploration,
            declaration.decisions,
            declaration.anytime,
        ) {
            (
                Some(responses),
                Some(correlation),
                Some(borrowing),
                Some(priors),
                Some(enrolment),
                Some(min_exploration),
                Some(decisions),
                Some(anytime),
            ) => Ok(Self {
                declaration,
                borrowing,
                responses,
                correlation,
                priors,
                enrolment,
                min_exploration,
                decisions,
                anytime,
                sequence: SequenceKind::PredictablePlugInBernstein,
            }),
            _ => Err(ProcedureContractError { gaps }),
        }
    }

    /// The validated declaration.
    #[must_use]
    pub const fn declaration(&self) -> &ParticipantDeclaration {
        &self.declaration
    }

    /// Number of arms.
    #[must_use]
    pub const fn arms(&self) -> usize {
        self.declaration.arms
    }

    /// Binary responses per participant.
    #[must_use]
    pub const fn responses(&self) -> u32 {
        self.responses
    }

    /// The declared intra-participant correlation; `None` when it is
    /// estimated.
    #[must_use]
    pub const fn correlation(&self) -> Option<f64> {
        match self.correlation {
            CorrelationModel::Declared(rho) => Some(rho),
            CorrelationModel::Estimated(_) => None,
        }
    }

    /// The prior of the estimated correlation; `None` when it is declared.
    #[must_use]
    pub const fn correlation_prior(&self) -> Option<CorrelationPrior> {
        match self.correlation {
            CorrelationModel::Declared(_) => None,
            CorrelationModel::Estimated(prior) => Some(prior),
        }
    }

    /// The work one participant adds to a simulation, in responses: each
    /// response, plus the posterior evaluated at every look, which an estimated
    /// correlation makes about sixteen times heavier because it integrates over
    /// the correlation too.
    #[must_use]
    pub const fn work_per_participant(&self) -> u32 {
        match self.correlation {
            CorrelationModel::Declared(_) => self.responses,
            CorrelationModel::Estimated(_) => self.responses.saturating_mul(16),
        }
    }

    /// How the correlation enters the posterior.
    #[must_use]
    pub const fn correlation_model(&self) -> CorrelationModel {
        self.correlation
    }

    /// The design effect `1 + (m - 1) rho` of a participant's mean response
    /// at the declared correlation; `None` when the correlation is estimated.
    #[must_use]
    pub fn design_effect(&self) -> Option<f64> {
        self.correlation().map(|rho| design_effect(self.responses, rho))
    }

    /// The resolved prior of every arm, with its sources, discounts and
    /// effective sample size.
    #[must_use]
    pub fn priors(&self) -> &[ResolvedArmPrior] {
        &self.priors
    }

    /// The borrowing plan the procedure was declared with.
    #[must_use]
    pub const fn borrowing(&self) -> &BorrowingPlan {
        &self.borrowing
    }

    /// Participants enrolled at each look.
    #[must_use]
    pub fn enrolment(&self) -> &[u32] {
        &self.enrolment
    }

    /// Participants enrolled in total.
    #[must_use]
    pub fn total_participants(&self) -> u32 {
        self.enrolment.iter().sum()
    }

    /// Looks between enrolment and completed follow-up.
    #[must_use]
    pub const fn lag_looks(&self) -> usize {
        self.declaration.lag_looks
    }

    /// The minimum probability any arm keeps.
    #[must_use]
    pub const fn min_exploration(&self) -> f64 {
        self.min_exploration
    }

    /// The declared decisions.
    #[must_use]
    pub const fn decisions(&self) -> &DecisionRules {
        &self.decisions
    }

    /// The confidence-sequence settings.
    #[must_use]
    pub const fn anytime(&self) -> &AnytimeSettings {
        &self.anytime
    }

    /// The construction of the confidence sequences. A procedure declared now
    /// reads the predictable plug-in sequence; a retained one keeps the
    /// construction it was produced under.
    #[must_use]
    pub const fn sequence_kind(&self) -> SequenceKind {
        self.sequence
    }

    /// The same procedure reading another confidence-sequence construction.
    /// A different construction is a different procedure and a different
    /// identity; this is how a retained mixture-Hoeffding procedure replays.
    #[must_use]
    pub const fn with_sequence_kind(mut self, sequence: SequenceKind) -> Self {
        self.sequence = sequence;
        self
    }

    /// Miscoverage of the sequence of each arm. The plug-in construction
    /// splits the family's `alpha` evenly over the `K` arms; the
    /// mixture-Hoeffding construction splits it over the `K - 1` comparisons
    /// against the control, each over its two arms.
    #[must_use]
    pub fn alpha_per_arm(&self) -> f64 {
        match self.sequence {
            SequenceKind::PredictablePlugInBernstein => self.anytime.alpha / self.arms() as f64,
            SequenceKind::MixtureHoeffding => self.anytime.alpha / (2.0 * (self.arms() - 1) as f64),
        }
    }

    /// Canonical identity (hex) of the declared procedure: the arms, the
    /// responses per participant and their correlation (the declared value, or
    /// the prior it is estimated under), every arm's initial
    /// prior and historical sources with their discounts (borrowing is part
    /// of the declaration), the schedule and delay, the allocation floor, the
    /// decisions and the confidence-sequence settings.
    #[must_use]
    pub fn identity(&self) -> String {
        let mut writer = CanonicalWriter::new(IDENTITY_DOMAIN);
        writer
            .word(PARTICIPANT_PROCEDURE_VERSION)
            .word(self.arms() as u64)
            .word(u64::from(self.responses));
        match self.correlation {
            CorrelationModel::Declared(rho) => writer.word(0).real(rho),
            CorrelationModel::Estimated(prior) => writer.word(1).real(prior.alpha).real(prior.beta),
        };
        for arm in &self.borrowing.arms {
            writer.real(arm.initial.alpha).real(arm.initial.beta).word(arm.historical.len() as u64);
            for source in &arm.historical {
                writer
                    .text(&source.source)
                    .word(source.successes)
                    .word(source.trials)
                    .real(source.discount);
            }
        }
        writer.word(self.enrolment.len() as u64);
        for &batch in &self.enrolment {
            writer.word(u64::from(batch));
        }
        writer.word(self.declaration.lag_looks as u64).real(self.min_exploration);
        writer.real(self.decisions.loss_threshold);
        match self.decisions.futility {
            Some(rule) => writer.word(1).real(rule.margin).real(rule.threshold),
            None => writer.word(0),
        };
        writer.opt_word(self.decisions.participant_cap.map(u64::from));
        writer.real(self.anytime.alpha).real(self.anytime.tuning_samples);
        // The released construction enters no bytes: only a later one names itself.
        if self.sequence != SequenceKind::MixtureHoeffding {
            writer.text(self.sequence.label());
        }
        writer.finish_hex()
    }

    /// The matrix cell of this procedure.
    #[must_use]
    pub fn cell(&self) -> CellLabel {
        CellLabel {
            family: "thompson_beta_bernoulli",
            outcome: "repeated_measures",
            monitoring: "fixed_interim_looks",
            stopping: "decision_theoretic",
            paradigm: "bayesian_posterior",
        }
    }

    /// The exact posterior of the arm means given the success-count histograms
    /// of the completed participants of each arm (`counts[arm][s]` participants
    /// with `s` successes), under the declared priors and correlation model,
    /// with the exceedance of `margin` over the control when given.
    ///
    /// # Errors
    /// Histograms of the wrong shape, a margin outside `[0, 1)`, a posterior the
    /// quadrature cannot resolve, or cancellation.
    pub fn posterior(
        &self,
        counts: &[Vec<u64>],
        margin: Option<f64>,
        cancelled: &dyn Fn() -> bool,
    ) -> Result<ExactPosterior, Error> {
        if counts.len() != self.arms() {
            return Err(Error::Shape("one success-count histogram per arm"));
        }
        self.exact(counts, margin, cancelled)
    }

    /// Re-declare the procedure with another borrowing plan, if borrowing is
    /// still open.
    ///
    /// Borrowing is frozen before recruitment: it is part of the declaration
    /// identity and a change after the first look would let the data choose
    /// the prior. `looks_performed` is the number of looks already made.
    ///
    /// # Errors
    /// [`Error::PremiseFailed`] with `adaptive_inference.borrowing_frozen`
    /// when a different plan is proposed after the first look; an invalid
    /// proposal.
    pub fn amend_borrowing(
        &self,
        proposed: &BorrowingPlan,
        looks_performed: usize,
    ) -> Result<Self, Error> {
        if proposed == self.borrowing() {
            return Ok(self.clone());
        }
        if looks_performed > 0 {
            return Err(Error::PremiseFailed {
                detail: "adaptive_inference.borrowing_frozen",
                message: "historical borrowing is part of the declared procedure and is frozen before recruitment; a change after the first look would let the data choose the prior",
            });
        }
        let mut declaration = self.declaration.clone();
        declaration.borrowing = Some(proposed.clone());
        Self::new(declaration).map(|spec| spec.with_sequence_kind(self.sequence)).map_err(|_| {
            Error::InvalidParameter("the proposed borrowing plan is not a valid plan for the arms")
        })
    }
}

/// The design effect `1 + (m - 1) rho` of the mean of `responses` responses
/// with intra-participant correlation `correlation`.
#[must_use]
pub fn design_effect(responses: u32, correlation: f64) -> f64 {
    1.0 + f64::from(responses.saturating_sub(1)) * correlation
}

/// Probability mass function of one participant's success count among
/// `responses` binary responses when the arm mean is `mean` and the
/// intra-participant correlation is `correlation`: the beta-binomial with
/// shapes `mean * kappa` and `(1 - mean) * kappa`, `kappa = (1 - rho) / rho`,
/// and the binomial at `rho = 0`.
///
/// Computed from the product form
/// `C(m, s) prod_{j<s}(mu + j d) prod_{j<m-s}(1 - mu + j d) / prod_{j<m}(1 + j d)`
/// with `d = rho / (1 - rho)`, which needs no gamma function and covers
/// `rho = 0` without a special case.
#[must_use]
pub fn beta_binomial_pmf(responses: u32, mean: f64, correlation: f64) -> Vec<f64> {
    let m = responses as usize;
    let d = correlation / (1.0 - correlation);
    let normalizer: f64 = (0..m).map(|j| 1.0 + j as f64 * d).product();
    let mut binomial = 1.0_f64;
    let mut pmf = Vec::with_capacity(m + 1);
    for s in 0..=m {
        let successes: f64 = (0..s).map(|j| mean + j as f64 * d).product();
        let failures: f64 = (0..m - s).map(|j| 1.0 - mean + j as f64 * d).product();
        pmf.push(binomial * successes * failures / normalizer);
        if s < m {
            binomial = binomial * (m - s) as f64 / (s + 1) as f64;
        }
    }
    let total: f64 = pmf.iter().sum();
    pmf.iter_mut().for_each(|p| *p /= total);
    pmf
}

// -- Readings -------------------------------------------------------------------------------------

/// Why the procedure ended at a look.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum StopReason {
    /// The smallest posterior expected loss fell below its threshold.
    ExpectedLoss,
    /// No treatment arm is likely to beat the control by the margin.
    Futility,
    /// The recruitment cap was reached.
    RecruitmentCap,
    /// The planned schedule ran out.
    Horizon,
}

named_variants! {
    StopReason {
        ExpectedLoss => "expected_loss",
        Futility => "futility",
        RecruitmentCap => "recruitment_cap",
        Horizon => "horizon",
    }
}

impl StopReason {
    /// Whether a declared decision, rather than the schedule, ended the
    /// procedure.
    #[must_use]
    pub const fn ended_by_rule(self) -> bool {
        !matches!(self, Self::Horizon)
    }
}

/// What a look decided.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum LookDecision {
    /// The procedure goes on.
    Continue,
    /// The procedure ends; `arm` is the arm decided for or selected.
    Stop {
        /// Why it ended.
        reason: StopReason,
        /// The arm decided for or selected.
        arm: usize,
    },
}

/// The Bayesian claim at a look, from the declared priors and the completed
/// participants.
#[derive(Clone, Debug, PartialEq)]
pub struct PosteriorClaim {
    /// Always `bayesian_posterior`.
    pub paradigm: &'static str,
    /// Posterior mean of each arm.
    pub mean: Vec<f64>,
    /// Posterior standard deviation of each arm's success probability.
    pub sd: Vec<f64>,
    /// Posterior probability that each arm is best.
    pub probability_best: Vec<f64>,
    /// Posterior expected loss of choosing each arm.
    pub expected_loss: Vec<f64>,
    /// For each treatment arm (arms 1 and up), the posterior probability of
    /// exceeding the control by the futility margin (by zero when no futility
    /// rule is declared); empty when it was not computed.
    pub exceeds_control: Vec<f64>,
    /// Posterior mean of the intra-participant correlation (the declared value
    /// when it is declared).
    pub correlation_mean: f64,
    /// Posterior standard deviation of the correlation (zero when declared).
    pub correlation_sd: f64,
    /// The arm with the highest posterior mean.
    pub selected_arm: usize,
}

/// One arm's confidence sequence at a look.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct ArmReading {
    /// Completed participants of the arm.
    pub count: u64,
    /// Mean success proportion; `None` without a completed participant.
    pub mean: Option<f64>,
    /// Lower bound of the sequence.
    pub lower: f64,
    /// Upper bound of the sequence.
    pub upper: f64,
}

/// Simultaneous bounds on the difference of a treatment arm's mean and the
/// control's.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct ComparisonReading {
    /// The treatment arm.
    pub arm: usize,
    /// Lower bound of `mean(arm) - mean(control)`.
    pub lower: f64,
    /// Upper bound of `mean(arm) - mean(control)`.
    pub upper: f64,
}

/// The time-uniform frequentist claim at a look.
#[derive(Clone, Debug, PartialEq)]
pub struct FrequentistClaim {
    /// Always `anytime_valid_frequentist`.
    pub paradigm: &'static str,
    /// Always `derived_unmeasured`.
    pub calibration: &'static str,
    /// Label of the sequence construction ([`SequenceKind::label`]).
    pub sequence: &'static str,
    /// Total miscoverage of the simultaneous family.
    pub alpha: f64,
    /// Miscoverage allotted to each comparison against the control: the two
    /// arm sequences it is built from spend `alpha_per_arm` each.
    pub alpha_per_comparison: f64,
    /// Miscoverage of each arm's sequence.
    pub alpha_per_arm: f64,
    /// Each arm's sequence.
    pub arms: Vec<ArmReading>,
    /// The comparisons of arms 1 and up against the control.
    pub comparisons: Vec<ComparisonReading>,
    /// The data-selected best treatment: the non-control arm with the
    /// highest posterior mean.
    pub best_treatment: usize,
    /// Its comparison with the control. It is one of [`Self::comparisons`] and
    /// holds under the selection, because the family covers every
    /// treatment arm at once; no correction for selection is applied or
    /// needed.
    pub best_treatment_comparison: ComparisonReading,
}

/// Everything read at one performed look.
#[derive(Clone, Debug, PartialEq)]
pub struct LookReading {
    /// The look, zero-based.
    pub look: usize,
    /// Participants enrolled through this look.
    pub enrolled: u32,
    /// Completed participants of each arm at this look.
    pub completed: Vec<u32>,
    /// The allocation probabilities the participants of this look were
    /// randomized under (a function of the completed participants of the
    /// looks before it).
    pub assignment_probabilities: Vec<f64>,
    /// The Bayesian claim.
    pub posterior: PosteriorClaim,
    /// The time-uniform frequentist claim.
    pub frequentist: FrequentistClaim,
    /// What the look decided.
    pub decision: LookDecision,
}

impl LookReading {
    /// Every number of the reading in a fixed order, for comparison with a
    /// stored copy.
    #[must_use]
    pub fn numbers(&self) -> Vec<f64> {
        let mut out = Vec::new();
        out.extend(self.assignment_probabilities.iter().copied());
        out.extend(self.completed.iter().map(|&c| f64::from(c)));
        let p = &self.posterior;
        for values in [&p.mean, &p.sd, &p.probability_best, &p.expected_loss, &p.exceeds_control] {
            out.extend(values.iter().copied());
        }
        out.extend([p.correlation_mean, p.correlation_sd]);
        let f = &self.frequentist;
        for arm in &f.arms {
            out.extend([arm.count as f64, arm.mean.unwrap_or(0.0), arm.lower, arm.upper]);
        }
        for comparison in &f.comparisons {
            out.extend([comparison.lower, comparison.upper]);
        }
        out.extend([f.best_treatment_comparison.lower, f.best_treatment_comparison.upper]);
        out
    }
}

// -- Walking the looks ----------------------------------------------------------------------------

/// The completed participants of one arm: how many gave each success count.
#[derive(Clone, Debug)]
struct Tally {
    participants: u64,
    counts: Vec<u64>,
}

impl Tally {
    fn new(responses: u32) -> Self {
        Self { participants: 0, counts: vec![0; responses as usize + 1] }
    }

    fn record(&mut self, successes: u32) {
        self.participants += 1;
        self.counts[successes as usize] += 1;
    }
}

#[derive(Clone, Copy, Debug)]
struct Participant {
    arm: usize,
    successes: u32,
}

/// Where the participants of each batch come from: drawn under a truth, or
/// read back from a retained history.
trait Enrolment {
    fn batch(&mut self, look: usize, size: u32, row: &[f64]) -> Result<Vec<Participant>, Error>;
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum Detail {
    /// Compute only what the declared rules need.
    Lean,
    /// Compute every reported number.
    Full,
}

/// The exact posterior of the completed participants: every functional the
/// rules and readings ask of it, computed once.
struct View {
    exact: ExactPosterior,
}

impl View {
    fn means(&self) -> &[f64] {
        &self.exact.mean
    }
}

fn completed_count(tally: &Tally) -> u32 {
    u32::try_from(tally.participants).unwrap_or(u32::MAX)
}

struct Walk {
    /// Looks performed.
    looks_run: usize,
    /// Participants enrolled when the walk ended.
    enrolled: u32,
    /// Completed participants when the walk ended.
    completed: u32,
}

impl ParticipantSpec {
    fn exact(
        &self,
        counts: &[Vec<u64>],
        margin: Option<f64>,
        cancelled: &dyn Fn() -> bool,
    ) -> Result<ExactPosterior, Error> {
        let arms: Vec<ArmEvidence<'_>> = self
            .priors
            .iter()
            .zip(counts)
            .map(|(prior, counts)| ArmEvidence {
                prior_alpha: prior.prior.alpha,
                prior_beta: prior.prior.beta,
                counts,
            })
            .collect();
        exact_posterior(
            &PosteriorRequest {
                responses: self.responses,
                correlation: self.correlation,
                arms: &arms,
                exceedance_margin: margin,
            },
            cancelled,
        )
    }

    /// The exceedance margin the rules and the reading need: the futility
    /// margin when futility is declared, a zero margin when a full reading
    /// reports the exceedance anyway, none otherwise.
    fn margin_needed(&self, detail: Detail) -> Option<f64> {
        match self.decisions.futility {
            Some(rule) => Some(rule.margin),
            None if detail == Detail::Full => Some(0.0),
            None => None,
        }
    }

    fn view(
        &self,
        tallies: &[Tally],
        detail: Detail,
        cancelled: &dyn Fn() -> bool,
    ) -> Result<View, Error> {
        let counts: Vec<Vec<u64>> = tallies.iter().map(|t| t.counts.clone()).collect();
        Ok(View { exact: self.exact(&counts, self.margin_needed(detail), cancelled)? })
    }

    /// The allocation probabilities for the next batch.
    fn assignment_row(&self, view: &View) -> Result<Vec<f64>, Error> {
        let mut row = normalize_probabilities(view.exact.probability_best.clone())?;
        apply_exploration_floor(&mut row, self.min_exploration);
        Ok(row)
    }

    /// The first declared decision that holds on the completed participants.
    fn fired(&self, view: &View, enrolled: u32) -> Option<(StopReason, usize)> {
        let losses = &view.exact.expected_loss;
        let negated: Vec<f64> = losses.iter().map(|l| -l).collect();
        let cheapest = first_maximum(&negated);
        if losses[cheapest] < self.decisions.loss_threshold {
            return Some((StopReason::ExpectedLoss, cheapest));
        }
        if let Some(rule) = self.decisions.futility {
            if view.exact.exceedance.iter().all(|&p| p < rule.threshold) {
                return Some((StopReason::Futility, 0));
            }
        }
        if self.decisions.participant_cap.is_some_and(|cap| enrolled >= cap) {
            return Some((StopReason::RecruitmentCap, first_maximum(view.means())));
        }
        None
    }

    #[allow(
        clippy::too_many_arguments,
        reason = "a reading is assembled from the look's state; bundling it would only move the arguments into a struct built once"
    )]
    fn reading(
        &self,
        look: usize,
        enrolled: u32,
        tallies: &[Tally],
        sequences: &[SequenceState],
        view: &View,
        row: Vec<f64>,
        decision: LookDecision,
    ) -> Result<LookReading, Error> {
        let exact = &view.exact;
        let mean = exact.mean.clone();
        let posterior = PosteriorClaim {
            paradigm: "bayesian_posterior",
            selected_arm: first_maximum(&mean),
            mean,
            sd: exact.sd.clone(),
            probability_best: exact.probability_best.clone(),
            expected_loss: exact.expected_loss.clone(),
            exceeds_control: exact.exceedance.clone(),
            correlation_mean: exact.correlation_mean,
            correlation_sd: exact.correlation_sd,
        };
        let readings =
            sequences.iter().map(SequenceState::reading).collect::<Result<Vec<_>, _>>()?;
        let arms: Vec<ArmReading> = readings
            .iter()
            .map(|r| ArmReading {
                count: r.count,
                mean: (r.count > 0).then_some(r.mean),
                lower: r.lower,
                upper: r.upper,
            })
            .collect();
        let comparisons: Vec<ComparisonReading> = (1..self.arms())
            .map(|arm| ComparisonReading {
                arm,
                lower: arms[arm].lower - arms[0].upper,
                upper: arms[arm].upper - arms[0].lower,
            })
            .collect();
        let best_treatment = 1 + first_maximum(&posterior.mean[1..]);
        let best_treatment_comparison = comparisons[best_treatment - 1];
        let frequentist = FrequentistClaim {
            paradigm: "anytime_valid_frequentist",
            calibration: DERIVED_UNMEASURED,
            sequence: self.sequence.label(),
            alpha: self.anytime.alpha,
            alpha_per_comparison: 2.0 * self.alpha_per_arm(),
            alpha_per_arm: self.alpha_per_arm(),
            arms,
            comparisons,
            best_treatment,
            best_treatment_comparison,
        };
        Ok(LookReading {
            look,
            enrolled,
            completed: tallies.iter().map(completed_count).collect(),
            assignment_probabilities: row,
            posterior,
            frequentist,
            decision,
        })
    }

    /// Run the looks of the procedure over `source`, reporting each look's
    /// reading to `observer`, until a declared decision or the schedule ends
    /// the procedure.
    fn walk(
        &self,
        source: &mut dyn Enrolment,
        detail: Detail,
        cancelled: &dyn Fn() -> bool,
        observer: &mut dyn FnMut(&LookReading) -> Result<(), Error>,
    ) -> Result<Walk, Error> {
        let arms = self.arms();
        let looks = self.enrolment.len();
        let mut tallies = vec![Tally::new(self.responses); arms];
        let mut sequences = (0..arms)
            .map(|_| {
                SequenceState::of_kind(
                    self.sequence,
                    self.alpha_per_arm(),
                    self.anytime.tuning_samples,
                )
            })
            .collect::<Result<Vec<_>, _>>()?;
        let mut pending: VecDeque<Vec<Participant>> = VecDeque::new();
        let mut enrolled = 0_u32;
        let mut view = self.view(&tallies, detail, cancelled)?;
        for look in 0..looks {
            if cancelled() {
                return Err(Error::Cancelled);
            }
            let row = self.assignment_row(&view)?;
            let size = self.enrolment[look];
            let batch = source.batch(look, size, &row)?;
            enrolled += size;
            pending.push_back(batch);
            if pending.len() > self.declaration.lag_looks {
                if let Some(completed) = pending.pop_front() {
                    for participant in completed {
                        tallies[participant.arm].record(participant.successes);
                        sequences[participant.arm]
                            .push(f64::from(participant.successes) / f64::from(self.responses))?;
                    }
                }
            }
            view = self.view(&tallies, detail, cancelled)?;
            let decision = match self.fired(&view, enrolled) {
                Some((reason, arm)) => LookDecision::Stop { reason, arm },
                None if look + 1 == looks => LookDecision::Stop {
                    reason: StopReason::Horizon,
                    arm: first_maximum(view.means()),
                },
                None => LookDecision::Continue,
            };
            let reading =
                self.reading(look, enrolled, &tallies, &sequences, &view, row, decision)?;
            observer(&reading)?;
            if matches!(decision, LookDecision::Stop { .. }) {
                let completed = tallies.iter().map(completed_count).sum();
                return Ok(Walk { looks_run: look + 1, enrolled, completed });
            }
        }
        Err(Error::Numerical("the schedule ended without a final look"))
    }
}

