/// What to simulate.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct ParticipantSimulationRequest {
    /// Replications to run.
    pub replications: u32,
    /// Seed of the replicate streams.
    pub seed: u64,
    /// The intra-participant correlation the simulated participants have. When
    /// absent the declared correlation is used; a procedure that estimates the
    /// correlation has no declared value and needs this one.
    pub true_correlation: Option<f64>,
}

/// One simulated run of the whole procedure.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct ParticipantReplicate {
    /// Look (zero-based) at which the procedure ended.
    pub look: usize,
    /// Why it ended.
    pub reason: StopReason,
    /// The arm decided for or selected.
    pub decision: usize,
    /// Participants enrolled when it ended.
    pub enrolled: u32,
    /// Participants whose follow-up had completed.
    pub completed: u32,
    /// The data-selected best treatment at the end.
    pub best_treatment: usize,
    /// Whether every arm's sequence contained its true mean at every look.
    pub covered_every_look: bool,
    /// Whether every arm's sequence contained its true mean at the last look.
    pub covered_at_stop: bool,
    /// Whether the best treatment's bounds contained its true difference from
    /// the control at the last look.
    pub contrast_covered_at_stop: bool,
}

/// The replicates of a simulation.
#[derive(Clone, Debug, PartialEq)]
pub struct ParticipantSimulation {
    /// Replicates, in index order.
    pub replicates: Vec<ParticipantReplicate>,
    /// The work the simulation was admitted for and did.
    pub receipt: ResourceReceipt,
}

/// Fractions of the replicates by why they ended.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct StopFractions {
    /// Ended by the expected-loss decision.
    pub expected_loss: f64,
    /// Ended by futility.
    pub futility: f64,
    /// Ended by the recruitment cap.
    pub recruitment_cap: f64,
    /// Ran the schedule.
    pub horizon: f64,
}

/// Summary of a simulation. Not a coverage claim: the fractions are measured
/// properties of this simulation under this truth.
#[derive(Clone, Debug, PartialEq)]
pub struct ParticipantSimulationSummary {
    /// Replicates summarized.
    pub replications: usize,
    /// Mean participants enrolled at the end.
    pub mean_enrolled: f64,
    /// Mean completed participants at the end.
    pub mean_completed: f64,
    /// Fractions by stopping reason.
    pub stop_fractions: StopFractions,
    /// Fraction deciding for or selecting each arm.
    pub decision_fractions: Vec<f64>,
    /// Fraction with every arm covered at every look.
    pub covered_every_look: f64,
    /// Fraction with every arm covered at the last look.
    pub covered_at_stop: f64,
    /// Fraction whose best-treatment contrast was covered at the last look.
    pub contrast_covered_at_stop: f64,
}

impl ParticipantSimulation {
    /// Summarize the replicates over `arms` arms.
    ///
    /// # Errors
    /// No replicate.
    pub fn summarize(&self, arms: usize) -> Result<ParticipantSimulationSummary, Error> {
        if self.replicates.is_empty() {
            return Err(Error::Shape("a summary needs at least one replicate"));
        }
        let n = self.replicates.len() as f64;
        let fraction = |count: usize| count as f64 / n;
        let by_reason = |reason: StopReason| {
            fraction(self.replicates.iter().filter(|r| r.reason == reason).count())
        };
        let mut decisions = vec![0.0; arms];
        for replicate in &self.replicates {
            decisions[replicate.decision] += 1.0 / n;
        }
        Ok(ParticipantSimulationSummary {
            replications: self.replicates.len(),
            mean_enrolled: self.replicates.iter().map(|r| f64::from(r.enrolled)).sum::<f64>() / n,
            mean_completed: self.replicates.iter().map(|r| f64::from(r.completed)).sum::<f64>() / n,
            stop_fractions: StopFractions {
                expected_loss: by_reason(StopReason::ExpectedLoss),
                futility: by_reason(StopReason::Futility),
                recruitment_cap: by_reason(StopReason::RecruitmentCap),
                horizon: by_reason(StopReason::Horizon),
            },
            decision_fractions: decisions,
            covered_every_look: fraction(
                self.replicates.iter().filter(|r| r.covered_every_look).count(),
            ),
            covered_at_stop: fraction(self.replicates.iter().filter(|r| r.covered_at_stop).count()),
            contrast_covered_at_stop: fraction(
                self.replicates.iter().filter(|r| r.contrast_covered_at_stop).count(),
            ),
        })
    }
}

struct Simulated<'a> {
    rng: CausalRng,
    pmfs: &'a [Vec<f64>],
}

impl Enrolment for Simulated<'_> {
    fn batch(&mut self, _look: usize, size: u32, row: &[f64]) -> Result<Vec<Participant>, Error> {
        let mut batch = Vec::with_capacity(size as usize);
        for _ in 0..size {
            let arm = draw(&mut self.rng, row);
            let successes = u32::try_from(draw(&mut self.rng, &self.pmfs[arm]))
                .map_err(|_| Error::Numerical("a success count does not fit a count"))?;
            batch.push(Participant { arm, successes });
        }
        Ok(batch)
    }
}

/// The success-count distribution of one participant of each arm.
fn success_pmfs(
    spec: &ParticipantSpec,
    truth: &[f64],
    true_correlation: Option<f64>,
) -> Result<Vec<Vec<f64>>, Error> {
    let correlation = match (true_correlation, spec.correlation()) {
        (Some(rho), _) => rho,
        (None, Some(declared)) => declared,
        (None, None) => {
            return Err(Error::InvalidParameter(
                "a procedure that estimates the correlation needs the true correlation to simulate",
            ));
        }
    };
    if !(correlation.is_finite() && (0.0..1.0).contains(&correlation)) {
        return Err(Error::InvalidParameter("the true correlation must lie in [0, 1)"));
    }
    if truth.len() != spec.arms() {
        return Err(Error::Shape("one mean success probability per arm"));
    }
    if truth.iter().any(|p| !(p.is_finite() && (0.0..=1.0).contains(p))) {
        return Err(Error::InvalidParameter("a success probability must lie in [0, 1]"));
    }
    Ok(truth.iter().map(|&mean| beta_binomial_pmf(spec.responses(), mean, correlation)).collect())
}

fn covers(arm: &ArmReading, truth: f64) -> bool {
    arm.lower <= truth && truth <= arm.upper
}

/// Run the declared procedure `request.replications` times under the arm
/// means `truth`, within the library work and memory bounds.
///
/// Each replicate draws every participant's arm from the allocation the
/// procedure computes from the participants completed so far, and their
/// success count from the beta-binomial of the arm's mean at the declared
/// correlation; applies the declared decisions at every look; and records how
/// it ended and whether the arms' confidence sequences covered the truth at
/// every look and at the end. This is the whole-procedure entry point a
/// calibration design calls.
///
/// # Errors
/// A truth of the wrong shape or outside `[0, 1]`, a request outside bounds
/// (a capacity refusal for the replication bound, the work budget or the
/// memory budget), a numerical failure of a posterior, or cancellation.
pub fn simulate_participant_procedure(
    spec: &ParticipantSpec,
    truth: &[f64],
    request: &ParticipantSimulationRequest,
    cancelled: &dyn Fn() -> bool,
) -> Result<ParticipantSimulation, Error> {
    simulate_participant_procedure_within(spec, truth, request, &ResourceBudget::DEFAULT, cancelled)
}

/// [`simulate_participant_procedure`] within an explicit work and memory
/// budget.
///
/// # Errors
/// As [`simulate_participant_procedure`].
pub fn simulate_participant_procedure_within(
    spec: &ParticipantSpec,
    truth: &[f64],
    request: &ParticipantSimulationRequest,
    budget: &ResourceBudget,
    cancelled: &dyn Fn() -> bool,
) -> Result<ParticipantSimulation, Error> {
    let pmfs = success_pmfs(spec, truth, request.true_correlation)?;
    if request.replications == 0 {
        return Err(Error::InvalidParameter("a simulation needs at least one replication"));
    }
    if request.replications > MAX_SIMULATION_REPLICATIONS {
        return Err(Error::Capacity(CapacityError::SimulationReplications {
            limit: u64::from(MAX_SIMULATION_REPLICATIONS),
            requested: u64::from(request.replications),
        }));
    }
    let admitted = budget.admit(&SimulationShape {
        replications: request.replications,
        units: spec.total_participants(),
        measurements: spec.work_per_participant(),
        record_bytes: std::mem::size_of::<ParticipantReplicate>() as u64,
        unit_bytes: 4 * std::mem::size_of::<Participant>() as u64,
        fixed_bytes: 0,
    })?;
    let mut receipt = ResourceReceipt {
        work_planned: admitted.work_planned,
        estimated_peak_bytes: admitted.estimated_peak_bytes,
        ..ResourceReceipt::default()
    };
    let states = spec.arms() as u64 * (u64::from(spec.responses()) + 1);
    let mut replicates = Vec::with_capacity(request.replications as usize);
    for replicate in 0..request.replications {
        if cancelled() {
            return Err(Error::Cancelled);
        }
        let mut source = Simulated {
            rng: CausalRng::from_seed(
                request.seed ^ (u64::from(replicate) + 1).wrapping_mul(STREAM_MIX),
            ),
            pmfs: &pmfs,
        };
        let mut covered_every_look = true;
        let mut last: Option<LookReading> = None;
        let walk = spec.walk(&mut source, Detail::Lean, cancelled, &mut |reading| {
            covered_every_look &=
                reading.frequentist.arms.iter().zip(truth).all(|(arm, &t)| covers(arm, t));
            last = Some(reading.clone());
            Ok(())
        })?;
        let Some(reading) = last else {
            return Err(Error::Numerical("a replicate ended without a look"));
        };
        let LookDecision::Stop { reason, arm } = reading.decision else {
            return Err(Error::Numerical("a replicate ended without a decision"));
        };
        let covered_at_stop =
            reading.frequentist.arms.iter().zip(truth).all(|(a, &t)| covers(a, t));
        let best = reading.frequentist.best_treatment;
        let comparison = reading.frequentist.best_treatment_comparison;
        let difference = truth[best] - truth[0];
        replicates.push(ParticipantReplicate {
            look: walk.looks_run - 1,
            reason,
            decision: arm,
            enrolled: walk.enrolled,
            completed: walk.completed,
            best_treatment: best,
            covered_every_look,
            covered_at_stop,
            contrast_covered_at_stop: comparison.lower <= difference
                && difference <= comparison.upper,
        });
        receipt
            .record_replicate(walk.looks_run, walk.enrolled, spec.work_per_participant(), states)
            .map_err(Error::Capacity)?;
    }
    Ok(ParticipantSimulation { replicates, receipt })
}

// -- Retained history -----------------------------------------------------------------------------

/// The retained history of a participant procedure: what was randomized and
/// observed, as a contract keeps it.
#[derive(Clone, Debug, PartialEq)]
pub struct ParticipantHistory {
    /// Participants enrolled at each performed look.
    pub batches: Vec<u32>,
    /// The arm of each participant, in enrolment order.
    pub arms: Vec<usize>,
    /// The success count of each participant, or `None` when their follow-up
    /// had not completed when the procedure ended.
    pub successes: Vec<Option<u32>>,
    /// The allocation probabilities recorded for each participant.
    pub assignment: Vec<Vec<f64>>,
}

struct Recording<'a> {
    inner: Simulated<'a>,
    arms: Vec<usize>,
    successes: Vec<u32>,
    assignment: Vec<Vec<f64>>,
}

impl Enrolment for Recording<'_> {
    fn batch(&mut self, look: usize, size: u32, row: &[f64]) -> Result<Vec<Participant>, Error> {
        let batch = self.inner.batch(look, size, row)?;
        for participant in &batch {
            self.arms.push(participant.arm);
            self.successes.push(participant.successes);
            self.assignment.push(row.to_vec());
        }
        Ok(batch)
    }
}

/// Run the procedure once under the arm means `truth` (and the true
/// correlation, the declared one when absent) and retain what
/// happened as a history: the batches, each participant's arm and success
/// count (none while their follow-up had not completed when the procedure
/// ended), and the allocation probabilities they were randomized under.
///
/// The history replays under the same declaration by
/// [`ParticipantSpec::read_history`]. It is the shape a contract keeps, and
/// the way to obtain a consistent one without a real trial.
///
/// # Errors
/// A truth of the wrong shape, a numerical failure of a posterior, or
/// cancellation.
pub fn simulate_participant_history(
    spec: &ParticipantSpec,
    truth: &[f64],
    true_correlation: Option<f64>,
    seed: u64,
    cancelled: &dyn Fn() -> bool,
) -> Result<ParticipantHistory, Error> {
    let pmfs = success_pmfs(spec, truth, true_correlation)?;
    let mut source = Recording {
        inner: Simulated { rng: CausalRng::from_seed(seed ^ STREAM_MIX), pmfs: &pmfs },
        arms: Vec::new(),
        successes: Vec::new(),
        assignment: Vec::new(),
    };
    let walk = spec.walk(&mut source, Detail::Lean, cancelled, &mut |_| Ok(()))?;
    Ok(source.into_history(spec, walk.looks_run))
}

impl Recording<'_> {
    /// The history of the first `looks_run` looks.
    fn into_history(self, spec: &ParticipantSpec, looks_run: usize) -> ParticipantHistory {
        let batches = spec.enrolment[..looks_run].to_vec();
        let lag = spec.declaration.lag_looks;
        let mut successes = Vec::with_capacity(self.successes.len());
        let mut unit = 0;
        for (look, &size) in batches.iter().enumerate() {
            for _ in 0..size {
                successes.push((look + lag < looks_run).then_some(self.successes[unit]));
                unit += 1;
            }
        }
        ParticipantHistory { batches, arms: self.arms, successes, assignment: self.assignment }
    }
}

/// One run of the procedure, ended by its stopping look or by cancellation
/// between batches.
#[derive(Clone, Debug, PartialEq)]
pub struct ParticipantRun {
    /// What was randomized and observed in the looks that completed.
    pub history: ParticipantHistory,
    /// The reading of every completed look.
    pub readings: Vec<LookReading>,
    /// Looks the declaration schedules.
    pub looks_planned: usize,
    /// What the run did: one replication, the looks it performed, the
    /// participants it enrolled and the work it did, against what it was
    /// admitted for.
    pub receipt: ResourceReceipt,
    /// Whether the run reached its stopping look. A cancelled run is
    /// incomplete: its history is a prefix of the run and stops no decision.
    pub complete: bool,
}

/// Run the procedure once under the arm means `truth` (and the true
/// correlation, the declared one when absent), within the library work and
/// memory bounds, and retain it as [`simulate_participant_history`] does.
///
/// Cancellation is polled once before the first batch and once after each
/// batch that does not end the procedure, so it is honoured within one batch:
/// the run stops with the batches already completed, never with a partial
/// batch, and the result is marked incomplete rather than refused. A run that
/// reached its stopping look before the token tripped is complete.
///
/// # Errors
/// A truth of the wrong shape or outside `[0, 1]`, a capacity refusal for the
/// work or memory budget, or a numerical failure of a posterior.
pub fn run_participant_procedure_within(
    spec: &ParticipantSpec,
    truth: &[f64],
    true_correlation: Option<f64>,
    seed: u64,
    budget: &ResourceBudget,
    cancelled: &dyn Fn() -> bool,
) -> Result<ParticipantRun, Error> {
    let pmfs = success_pmfs(spec, truth, true_correlation)?;
    let arms = spec.arms() as u64;
    let looks_planned = spec.enrolment.len();
    let admitted = budget.admit(&SimulationShape {
        replications: 1,
        units: spec.total_participants(),
        measurements: spec.work_per_participant(),
        record_bytes: looks_planned as u64
            * (std::mem::size_of::<LookReading>() as u64 + 16 * arms * 8),
        unit_bytes: (4 * std::mem::size_of::<Participant>()
            + std::mem::size_of::<usize>()
            + 2 * std::mem::size_of::<Option<u32>>()
            + std::mem::size_of::<Vec<f64>>()) as u64
            + arms * std::mem::size_of::<f64>() as u64,
        fixed_bytes: 0,
    })?;
    let mut receipt = ResourceReceipt {
        work_planned: admitted.work_planned,
        estimated_peak_bytes: admitted.estimated_peak_bytes,
        ..ResourceReceipt::default()
    };
    let mut source = Recording {
        inner: Simulated { rng: CausalRng::from_seed(seed ^ STREAM_MIX), pmfs: &pmfs },
        arms: Vec::new(),
        successes: Vec::new(),
        assignment: Vec::new(),
    };
    let mut readings: Vec<LookReading> = Vec::new();
    let uninterrupted = || false;
    let outcome = if cancelled() {
        Err(Error::Cancelled)
    } else {
        spec.walk(&mut source, Detail::Lean, &uninterrupted, &mut |reading| {
            readings.push(reading.clone());
            if matches!(reading.decision, LookDecision::Continue) && cancelled() {
                return Err(Error::Cancelled);
            }
            Ok(())
        })
        .map(|_| ())
    };
    let complete = match outcome {
        Ok(()) => true,
        Err(Error::Cancelled) => false,
        Err(other) => return Err(other),
    };
    let performed = readings.len();
    let history = source.into_history(spec, performed);
    let enrolled = u32::try_from(history.arms.len())
        .map_err(|_| Error::Numerical("the enrolled participants do not fit a count"))?;
    receipt
        .record_replicate(
            performed,
            enrolled,
            spec.work_per_participant(),
            arms * (u64::from(spec.responses()) + 1),
        )
        .map_err(Error::Capacity)?;
    Ok(ParticipantRun { history, readings, looks_planned, receipt, complete })
}

struct Replayed<'a> {
    history: &'a ParticipantHistory,
    cursor: usize,
}

impl Enrolment for Replayed<'_> {
    fn batch(&mut self, look: usize, size: u32, row: &[f64]) -> Result<Vec<Participant>, Error> {
        if look >= self.history.batches.len() {
            return Err(Error::PremiseFailed {
                detail: "adaptive_inference.stopping_not_replayed",
                message: "the retained history ends at a look where the declared decisions do not stop the procedure",
            });
        }
        let end = self.cursor + size as usize;
        let mut batch = Vec::with_capacity(size as usize);
        for index in self.cursor..end {
            let recorded = &self.history.assignment[index];
            if recorded.len() != row.len()
                || recorded.iter().zip(row).any(|(a, b)| (a - b).abs() > REPLAY_TOLERANCE)
            {
                return Err(Error::PremiseFailed {
                    detail: "adaptive_inference.assignment_not_replayed",
                    message: "the retained assignment probabilities are not the declared policy's allocation from the completed participants and the declared priors",
                });
            }
            batch.push(Participant {
                arm: self.history.arms[index],
                successes: self.history.successes[index].unwrap_or(0),
            });
        }
        self.cursor = end;
        Ok(batch)
    }
}

impl ParticipantSpec {
    /// Recompute every look of a retained history under the declared
    /// procedure: the allocation each batch was randomized under, the
    /// posterior, the decisions and the confidence sequences.
    ///
    /// The retained assignment probabilities must be the declared policy's
    /// allocation from the participants completed before each batch, under the
    /// declared (frozen) priors; every look before the last must continue and
    /// the last must stop (by a declared decision, or by running the
    /// schedule).
    ///
    /// # Errors
    /// A history that disagrees with the declaration in shape, arms, counts,
    /// delay or schedule; [`Error::PremiseFailed`] with
    /// `adaptive_inference.assignment_not_replayed` when a retained
    /// probability is not the recomputed one, or
    /// `adaptive_inference.stopping_not_replayed` when the procedure
    /// continued past a look the declared decisions stop at, or stopped
    /// without one; cancellation.
    pub fn read_history(
        &self,
        history: &ParticipantHistory,
        cancelled: &dyn Fn() -> bool,
    ) -> Result<Vec<LookReading>, Error> {
        let performed = history.batches.len();
        let total: u64 = history.batches.iter().map(|&n| u64::from(n)).sum();
        if performed == 0
            || performed > self.enrolment.len()
            || history.batches[..] != self.enrolment[..performed]
        {
            return Err(Error::Shape(
                "the retained looks are not a prefix of the declared enrolment schedule",
            ));
        }
        let units = history.arms.len();
        if units as u64 != total
            || history.successes.len() != units
            || history.assignment.len() != units
        {
            return Err(Error::Shape("the retained history holds one record per participant"));
        }
        if history.arms.iter().any(|&arm| arm >= self.arms()) {
            return Err(Error::Shape("a participant's arm is outside the declared arms"));
        }
        if history.successes.iter().flatten().any(|&s| s > self.responses) {
            return Err(Error::InvalidParameter(
                "a participant's success count exceeds the responses per participant",
            ));
        }
        let lag = self.declaration.lag_looks;
        let mut index = 0;
        for (look, &size) in history.batches.iter().enumerate() {
            let completes = look + lag < performed;
            let mut incomplete = 0_u32;
            for _ in 0..size {
                match (history.successes[index].is_some(), completes) {
                    (false, true) => incomplete += 1,
                    (true, false) => {
                        return Err(Error::Shape(
                            "the retained outcome availability disagrees with the declared delay",
                        ));
                    }
                    _ => {}
                }
                index += 1;
            }
            if incomplete > 0 {
                return Err(Error::PremiseFailed {
                    detail: "adaptive_inference.batch_incomplete",
                    message: "a batch whose follow-up delay has elapsed holds participants without complete responses; decisions are taken only on batches of completed participants, never on a partial batch",
                });
            }
        }
        let mut readings = Vec::with_capacity(performed);
        let mut source = Replayed { history, cursor: 0 };
        let walk = self.walk(&mut source, Detail::Full, cancelled, &mut |reading| {
            readings.push(reading.clone());
            Ok(())
        })?;
        if walk.looks_run != performed {
            return Err(Error::PremiseFailed {
                detail: "adaptive_inference.stopping_not_replayed",
                message: "the procedure continued past a look at which the declared decisions stop it",
            });
        }
        Ok(readings)
    }
}

// -- Borrowing receipt ----------------------------------------------------------------------------

/// What one arm borrowed from its historical sources, and whether the current
/// data of the arm agree with what it borrowed.
#[derive(Clone, Debug, PartialEq)]
pub struct ArmBorrowing {
    /// The arm (0 is the control).
    pub arm: usize,
    /// Every historical source with its counts and its discount.
    pub sources: Vec<HistoricalPrior>,
    /// Historical responses the discounts are worth: the sum over the sources
    /// of their trials times their discounts.
    pub effective_historical_sample_size: f64,
    /// The effective sample size `alpha + beta` of the resolved prior, the
    /// declared initial prior included.
    pub prior_effective_sample_size: f64,
    /// Participants of the arm whose responses had completed.
    pub current_participants: u64,
    /// The prior-data conflict diagnostic; `None` for an arm that borrowed
    /// nothing or has no completed participant.
    pub conflict: Option<PriorDataConflict>,
}

/// Agreement between the resolved (borrowed) prior of an arm and its current
/// data, read from the exact posteriors of the two.
///
/// The current-data posterior is the arm mean under the declared initial prior
/// and the participant-aware likelihood of the completed participants alone;
/// the borrowed prior is the arm's resolved Beta prior. Both are independent
/// distributions of the arm mean, so `current_exceeds_prior` is the exact
/// probability that a draw of the former exceeds a draw of the latter. It is a
/// diagnostic of how far the borrowed information sits from the new data, not a
/// test with an error rate.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct PriorDataConflict {
    /// Probability that the arm mean drawn from the current-data posterior
    /// exceeds the one drawn from the borrowed prior.
    pub current_exceeds_prior: f64,
    /// `2 min(p, 1 - p)` of that probability: near zero when the current data
    /// sit entirely on one side of what was borrowed, one when they agree.
    pub agreement: f64,
}

impl ParticipantSpec {
    /// The borrowing receipt of a retained history: per arm, every source with
    /// its discount, the effective historical sample size, and the prior-data
    /// conflict between the borrowed prior and the participants whose
    /// responses had completed.
    ///
    /// # Errors
    /// A history that disagrees with the declaration in shape or counts, a
    /// posterior the quadrature cannot resolve, or cancellation.
    pub fn borrowing_receipt(
        &self,
        history: &ParticipantHistory,
        cancelled: &dyn Fn() -> bool,
    ) -> Result<Vec<ArmBorrowing>, Error> {
        let mut counts = vec![vec![0_u64; self.responses as usize + 1]; self.arms()];
        for (&arm, success) in history.arms.iter().zip(&history.successes) {
            let Some(successes) = *success else { continue };
            if arm >= self.arms() || successes > self.responses {
                return Err(Error::Shape(
                    "a participant's arm or success count is outside the declaration",
                ));
            }
            counts[arm][successes as usize] += 1;
        }
        let mut receipt = Vec::with_capacity(self.arms());
        for (arm, ((resolved, declared), histogram)) in
            self.priors.iter().zip(&self.borrowing.arms).zip(&counts).enumerate()
        {
            let current_participants: u64 = histogram.iter().sum();
            let conflict = if resolved.sources.is_empty() || current_participants == 0 {
                None
            } else {
                let silent = vec![0_u64; histogram.len()];
                let pair = [
                    ArmEvidence {
                        prior_alpha: resolved.prior.alpha,
                        prior_beta: resolved.prior.beta,
                        counts: &silent,
                    },
                    ArmEvidence {
                        prior_alpha: declared.initial.alpha,
                        prior_beta: declared.initial.beta,
                        counts: histogram,
                    },
                ];
                let posterior = exact_posterior(
                    &PosteriorRequest {
                        responses: self.responses,
                        correlation: self.correlation,
                        arms: &pair,
                        exceedance_margin: Some(0.0),
                    },
                    cancelled,
                )?;
                let exceeds = *posterior
                    .exceedance
                    .first()
                    .ok_or(Error::Numerical("the conflict comparison returned no exceedance"))?;
                Some(PriorDataConflict {
                    current_exceeds_prior: exceeds,
                    agreement: 2.0 * exceeds.min(1.0 - exceeds),
                })
            };
            receipt.push(ArmBorrowing {
                arm,
                sources: resolved.sources.clone(),
                effective_historical_sample_size: resolved.borrowed_sample_size,
                prior_effective_sample_size: resolved.effective_sample_size,
                current_participants,
                conflict,
            });
        }
        Ok(receipt)
    }
}
