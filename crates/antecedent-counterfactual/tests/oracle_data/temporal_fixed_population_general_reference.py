"""Exact-rational reference for the general-horizon temporal counterfactual.

Regenerate with:  uv run --offline --script temporal_fixed_population_general_reference.py > temporal_fixed_population_general_reference.json

The chain L0 -> A0 -> L1 -> A1 -> ... -> L(k-1) -> A(k-1) -> Y has node 2t (covariate of slice t),
2t+1 (action of slice t) and 2k (outcome).  Every covariate and the outcome is
V = intercept + sum_p coef_p * node_p + U_V over ANY strictly earlier nodes.  As in the two-slice
reference, each unit's history is generated by forward simulation from chosen noise with exact
fractions and rounded to doubles; the reference abduces the noise from those doubles with exact
rational residuals, replays every named action history forward with that same noise, and averages.
Horizons 1, 3 and 4, dense and sparse parent sets (including parents several slices back and an
outcome with no direct action parent), three or four worlds, and a one-unit group.
Repository-authored (MIT OR Apache-2.0).  Uses only the standard library.
"""
import json
import random
from fractions import Fraction as F


def forward(h, mechs, noise, acts):
    n = 2 * h + 1
    vals = [F(0)] * n
    g = 0
    for node in range(n):
        if node % 2 == 1:
            vals[node] = F(acts[node // 2])
        else:
            m = mechs[g]
            vals[node] = F(m["intercept"]) + sum(F(c) * vals[p] for p, c in m["parents"]) + noise[g]
            g += 1
    return vals


def case(name, h, mechs, noise, facts, worlds):
    units = []
    sums = [F(0)] * len(worlds)
    for nz, fa in zip(noise, facts):
        fac = [float(v) for v in forward(h, mechs, [F(x) for x in nz], fa)]
        ff = [F(v) for v in fac]
        res = []
        g = 0
        for node in range(2 * h + 1):
            if node % 2 == 0:
                m = mechs[g]
                res.append(ff[node] - F(m["intercept"]) - sum(F(c) * ff[p] for p, c in m["parents"]))
                g += 1
        outs = [forward(h, mechs, res, w)[-1] for w in worlds]
        for i, o in enumerate(outs):
            sums[i] += o
        units.append({"factual": fac, "outcomes": [float(o) for o in outs]})
    n = len(noise)
    return {"name": name, "horizon": h, "mechanisms": mechs, "worlds": worlds, "units": units,
            "world_means": [float(s / n) for s in sums]}


def main():
    rnd = random.Random(20261029)
    out = []

    def dy():
        return rnd.randint(-8, 8) / 8

    def mech_set(h, dense):
        mechs = []
        for t in range(h + 1):
            node = 2 * t if t < h else 2 * h
            cands = list(range(node))
            if not dense:
                cands = [p for p in cands if rnd.random() < 0.45]
            mechs.append({"node": node, "intercept": dy(),
                          "parents": [[p, rnd.choice([-1.25, -0.5, 0.375, 0.8, 1.5])] for p in cands]})
        return mechs

    def make(name, h, dense, n_units, n_worlds):
        mechs = mech_set(h, dense)
        noise = [[dy() for _ in range(h + 1)] for _ in range(n_units)]
        facts = [[rnd.choice([0.0, 1.0, 0.5, -1.0]) for _ in range(h)] for _ in range(n_units)]
        worlds = [[rnd.choice([0.0, 1.0, 2.0, -0.5]) for _ in range(h)] for _ in range(n_worlds)]
        out.append(case(name, h, mechs, noise, facts, worlds))

    make("horizon_1_dense", 1, True, 5, 3)
    make("horizon_3_dense", 3, True, 6, 3)
    make("horizon_3_sparse", 3, False, 7, 4)
    make("horizon_4_dense_odd_units", 4, True, 9, 3)
    make("horizon_4_sparse_single_unit", 4, False, 1, 3)
    # outcome with no direct action parent and a parent three slices back
    mechs = [{"node": 0, "intercept": 0.25, "parents": []},
             {"node": 2, "intercept": -0.5, "parents": [[1, 0.75]]},
             {"node": 4, "intercept": 0.125, "parents": [[0, 1.25], [3, -0.5]]},
             {"node": 6, "intercept": 0.5, "parents": [[0, 0.5], [2, -1.5], [4, 2.0]]}]
    noise = [[0.25, -0.5, 0.125, 0.75], [0.0, 0.5, -0.25, -0.125], [-0.75, 0.25, 0.5, 0.0]]
    facts = [[0.0, 1.0, 0.0], [1.0, 0.0, 1.0], [1.0, 1.0, 1.0]]
    out.append(case("outcome_without_action_parent", 3, mechs, noise, facts,
                    [[0.0, 0.0, 0.0], [1.0, 1.0, 1.0], [1.0, 0.0, 1.0]]))
    json.dump(out, open("/dev/stdout", "w"), separators=(",", ":"))


main()
