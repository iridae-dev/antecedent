//! Host-integration contract: what an application or tool layer reads to tell
//! a supported claim from a partial answer or a refusal before using it.
//!
//! Antecedent is a library; it ships no agent. A host (a service, a notebook
//! tool, an LLM tool layer) compiles a request, reads the capability report,
//! executes, and reads the claim. This module owns the three things such a host
//! needs to do that without parsing prose:
//!
//! * [`HostStatus`], the closed `supported` / `partial` / `unsupported`
//!   vocabulary, decided from a claim, an operation report or an error by one
//!   rule that Python shares through the native module;
//! * [`error_family`] and [`refusal_record`], the stable exception family and
//!   registered reason code of a failure;
//! * [`HOST_SCHEMA_TEXT`], the versioned JSON Schema describing requests,
//!   contracts, claims, refusals and statuses. The file is generated by
//!   `scripts/generate_host_schema.py` from the registries and enums that own
//!   each vocabulary, and the `host_contract` test checks it against the types
//!   compiled here.
//!
//! SPDX-License-Identifier: MIT OR Apache-2.0

use antecedent_contract::{
    ClaimDomains, ClaimEnvelope, ClaimKind, DomainStatus, EvidenceObligation, LicensedNeighbor,
    ObligationRecord, OperationReadiness, OperationReport, SemanticApplicability,
};
use antecedent_core::named_variants;
use serde_json::{Value, json};

use crate::analysis::fallback::{
    AnalysisWithFallback, FallbackUnavailable, NONCAUSAL_NOTICE, RankedPlan,
};
use crate::error::CausalError;

/// Version of the host contract. A consumer must change when it moves; new
/// enumeration members and optional fields do not move it.
pub const HOST_CONTRACT_VERSION: u32 = 1;

/// The committed JSON Schema, exactly as generated.
pub const HOST_SCHEMA_TEXT: &str = include_str!("../schemas/host_contract.schema.json");

/// The committed JSON Schema, parsed.
///
/// # Errors
///
/// The embedded text is not valid JSON, which the `host_contract` test rules out.
pub fn host_schema() -> Result<Value, serde_json::Error> {
    serde_json::from_str(HOST_SCHEMA_TEXT)
}

/// What a host may do with a claim or an operation.
#[derive(Clone, Copy, Debug, Eq, PartialEq, Hash)]
#[non_exhaustive]
pub enum HostStatus {
    /// Use it as stated.
    Supported,
    /// Use only what the record says: an identified set, an open obligation, an
    /// unreviewed graph, an unknown domain.
    Partial,
    /// Do not use it; read the refusal.
    Unsupported,
}

named_variants! {
    HostStatus {
        Supported => "supported",
        Partial => "partial",
        Unsupported => "unsupported",
    }
}

impl HostStatus {
    /// Status of a claim of `kind` over `domains`.
    ///
    /// A refusal, or a domain that is contradicted or outside the declared scope,
    /// is unsupported. A bounds or incomplete claim is partial by construction.
    /// An associational claim is a noncausal claim: it is supported when it states
    /// that identification is not claimed and the association was evaluated, and
    /// partial otherwise; it is never read as an identified, causal claim.
    /// Every other kind is supported when the structure is identified and the
    /// claim was evaluated and nothing contradicts it; a support domain that is
    /// merely `unknown` (no empirical check ran) stays visible in the claim's
    /// domains for the host to read but does not demote a licensed, identified,
    /// executed claim. Anything else is partial.
    #[must_use]
    pub fn of_claim_parts(kind: ClaimKind, domains: &ClaimDomains) -> Self {
        let all = [domains.identification, domains.support, domains.evaluated];
        if matches!(kind, ClaimKind::Refusal)
            || all
                .iter()
                .any(|d| matches!(d, DomainStatus::Contradicted | DomainStatus::OutsideScope))
        {
            return Self::Unsupported;
        }
        if matches!(kind, ClaimKind::Incomplete | ClaimKind::Bounds) {
            return Self::Partial;
        }
        if matches!(kind, ClaimKind::Associational) {
            return if matches!(domains.identification, DomainStatus::NotClaimed)
                && matches!(domains.evaluated, DomainStatus::Evaluated)
            {
                Self::Supported
            } else {
                Self::Partial
            };
        }
        if matches!(domains.identification, DomainStatus::Identified)
            && matches!(domains.evaluated, DomainStatus::Evaluated)
        {
            Self::Supported
        } else {
            Self::Partial
        }
    }

    /// Status of a [`ClaimEnvelope`].
    #[must_use]
    pub fn of_claim(claim: &ClaimEnvelope) -> Self {
        Self::of_claim_parts(claim.kind, &claim.domains)
    }

    /// [`Self::of_claim_parts`] over wire names; `None` for a name outside the
    /// registered vocabularies, which a host must treat as unsupported.
    #[must_use]
    pub fn of_claim_names(
        kind: &str,
        identification: &str,
        support: &str,
        evaluated: &str,
    ) -> Option<Self> {
        let domains = ClaimDomains::new(
            DomainStatus::from_name(identification)?,
            DomainStatus::from_name(support)?,
            DomainStatus::from_name(evaluated)?,
        );
        Some(Self::of_claim_parts(ClaimKind::from_name(kind)?, &domains))
    }

    /// Status of an operation from its support applicability and readiness.
    ///
    /// Only a licensed cell with met bindings is supported. An impossible or
    /// unlicensed cell, or a failed empirical check, is unsupported. Everything
    /// else (review pending, an assumption or binding missing, a check not yet
    /// run, a resource limit, unknown support) is partial: not a refusal of the
    /// question and not a license to run it.
    #[must_use]
    pub const fn of_operation_parts(
        applicability: SemanticApplicability,
        readiness: Option<OperationReadiness>,
    ) -> Self {
        match (applicability, readiness) {
            (SemanticApplicability::Impossible | SemanticApplicability::Unlicensed, _)
            | (_, Some(OperationReadiness::EmpiricalSupportFailed)) => Self::Unsupported,
            (SemanticApplicability::Licensed, Some(OperationReadiness::Executable)) => {
                Self::Supported
            }
            _ => Self::Partial,
        }
    }

    /// Status of an [`OperationReport`].
    #[must_use]
    pub const fn of_operation(report: &OperationReport) -> Self {
        Self::of_operation_parts(report.applicability, report.readiness)
    }

    /// [`Self::of_operation_parts`] over wire names; `None` for an unregistered name.
    #[must_use]
    pub fn of_operation_names(applicability: &str, readiness: Option<&str>) -> Option<Self> {
        let applicability =
            SemanticApplicability::ALL.into_iter().find(|v| v.as_str() == applicability)?;
        let readiness = match readiness {
            None => None,
            Some(name) => Some(OperationReadiness::ALL.into_iter().find(|v| v.as_str() == name)?),
        };
        Some(Self::of_operation_parts(applicability, readiness))
    }
}

/// Stable exception family code of `error`.
///
/// The codes are the `error_family` vocabulary of the host schema and name the
/// same families as the Python exception classes (`identify` is
/// `CausalIdentifyError`, `unsupported` is `CausalUnsupportedError`, ...). The
/// classification mirrors the one the Python boundary applies to the same
/// error, so a Rust host and a Python host triage a failure identically.
#[must_use]
pub fn error_family(error: &CausalError) -> &'static str {
    use antecedent_estimate::EstimationError;
    match error.peeled() {
        CausalError::Identify(_) => "identify",
        CausalError::Estimate(
            EstimationError::Refused { .. }
            | EstimationError::RefusedWithFields { .. }
            | EstimationError::TargetPopulation,
        )
        | CausalError::Unsupported { .. }
        | CausalError::Support { .. } => "unsupported",
        CausalError::Estimate(_) => "estimate",
        CausalError::Validate(_) => "validate",
        CausalError::Discovery(_) => "discovery",
        CausalError::Model(_) => "model",
        CausalError::Counterfactual(_) => "counterfactual",
        CausalError::Attribution(_) => "attribution",
        CausalError::Serialization(_) => "serialization",
        CausalError::Data(_) | CausalError::Schema(_) | CausalError::SchemaMismatch { .. } => {
            "data"
        }
        CausalError::Graph(_) => "graph",
        CausalError::Design(_) | CausalError::Callback { .. } => "design",
        CausalError::State(antecedent_state::StateError::CacheBudget { .. })
        | CausalError::Resource { .. } => "resource",
        CausalError::State(_) => "state",
        CausalError::Compile { .. } | CausalError::Rejected(_) | CausalError::Missing { .. } => {
            "compile"
        }
        CausalError::NotIdentified { .. } => "not_identified",
        CausalError::ReviewRequired { .. } => "review_required",
        CausalError::Cancelled { .. } => "cancelled",
        _ => "error",
    }
}

/// The registered runtime-refusal code `error` carries, when it carries one.
///
/// A code that is not in the runtime-refusal vocabulary is not reported, so a
/// host never sees a code the schema does not list.
#[must_use]
pub fn refusal_code(error: &CausalError) -> Option<&str> {
    error.reason_code().filter(|code| antecedent_core::reason_code::is_runtime_refusal(code))
}

/// Host record of a failed call, shaped as the schema's `refusal`.
#[must_use]
pub fn refusal_record(error: &CausalError) -> Value {
    json!({
        "status": HostStatus::Unsupported.as_str(),
        "family": error_family(error),
        "reason_code": refusal_code(error),
        "message": error.to_string(),
        "remedy": error.remedy(),
    })
}

/// Host record of a failed call as a `host_response`. A failed call is always
/// unsupported; `family` tells a host whether to retry (`resource`, `cancelled`),
/// ask for a review (`review_required`) or give up (`unsupported`).
#[must_use]
pub fn error_response(error: &CausalError) -> Value {
    json!({ "status": HostStatus::Unsupported.as_str(), "refusal": refusal_record(error) })
}

/// Host record of an unavailable part of a fallback, shaped as the schema's
/// `fallback_unavailable`.
#[must_use]
pub fn fallback_unavailable_record(unavailable: &FallbackUnavailable) -> Value {
    json!({
        "available": false,
        "part": unavailable.part.as_str(),
        "reason_code": unavailable.code,
        "detail": unavailable.detail,
        "message": unavailable.message,
    })
}

/// Host record of an obligation, shaped as the schema's `evidence_obligation`.
#[must_use]
pub fn evidence_obligation_record(obligation: &EvidenceObligation, names: &[String]) -> Value {
    let named = |variables: &[antecedent_core::VariableId]| {
        variables
            .iter()
            .map(|v| names.get(v.as_usize()).cloned().unwrap_or_else(|| format!("v{}", v.raw())))
            .collect::<Vec<_>>()
    };
    json!({
        "id": obligation.id.as_ref(),
        "kind": obligation.kind.as_str(),
        "scope": obligation.scope.as_str(),
        "variables": named(&obligation.variables),
        "reason": obligation.reason.as_ref(),
        "family": obligation.provenance.family.as_ref(),
        "proof_step": obligation.provenance.proof_step.as_deref(),
        "satisfiable_by_study": obligation.satisfiable_by_study(),
    })
}

/// Host record of a descriptive fallback, shaped as the schema's `fallback_response`.
///
/// The causal question stays refused: `status` is `unsupported` and `refusal` is the unchanged
/// refusal record. Beside it the record shows both statuses: `causal_status` (always
/// `unsupported`) and `associational_status` (the host status of the noncausal claim, or
/// `unavailable` with its typed reason). The associational claim carries `causal: false` and
/// never reads as an identified effect; it ranks no action.
#[must_use]
pub fn fallback_response(fallback: &AnalysisWithFallback) -> Value {
    let (associational_status, associational) = match &fallback.associational {
        Ok(part) => {
            let record = claim_record(&part.claim);
            (
                record["status"].clone(),
                json!({
                    "available": true,
                    "noncausal": true,
                    "ranks_actions": false,
                    "rule": part.roles.rule,
                    "claim": record,
                }),
            )
        }
        Err(unavailable) => (json!("unavailable"), fallback_unavailable_record(unavailable)),
    };
    let evidence = match &fallback.evidence {
        Ok(needs) => json!({
            "available": true,
            "obligations": needs
                .obligations
                .iter()
                .map(|o| evidence_obligation_record(o, &needs.names))
                .collect::<Vec<_>>(),
            "next_actions": needs
                .next_actions
                .iter()
                .map(|a| json!({ "id": a.id.as_ref(), "description": a.description.as_ref() }))
                .collect::<Vec<_>>(),
            "ranked_plan": match &needs.ranking {
                RankedPlan::NotRequested => json!({ "available": false, "requested": false }),
                RankedPlan::Ranked(plan) => json!({
                    "available": true,
                    "requested": true,
                    "outcome": plan.plan.outcome.as_str(),
                    "options": plan.plan.options.len(),
                }),
                RankedPlan::Unavailable(unavailable) => fallback_unavailable_record(unavailable),
            },
        }),
        Err(unavailable) => fallback_unavailable_record(unavailable),
    };
    json!({
        "status": HostStatus::Unsupported.as_str(),
        "causal_status": HostStatus::Unsupported.as_str(),
        "associational_status": associational_status,
        "refusal": refusal_record(&fallback.refusal),
        "associational": associational,
        "evidence_plan": evidence,
        "notice": NONCAUSAL_NOTICE,
    })
}

/// Host record of a claim, shaped as the schema's `claim_envelope`.
#[must_use]
pub fn claim_record(claim: &ClaimEnvelope) -> Value {
    json!({
        "claim_id": claim.claim_id.to_hex(),
        "kind": claim.kind.as_str(),
        "causal": claim.kind.is_causal(),
        "value": claim.value,
        "outcome_units": claim.outcome_units.as_deref(),
        "domains": {
            "identification": claim.domains.identification.as_str(),
            "support": claim.domains.support.as_str(),
            "evaluated": claim.domains.evaluated.as_str(),
        },
        "execution": claim.execution.map(|digest| digest.to_hex()),
        "evidence": claim.evidence.iter().map(std::convert::AsRef::as_ref).collect::<Vec<_>>(),
        "status": HostStatus::of_claim(claim).as_str(),
    })
}

/// Host record of a claim as a `host_response`. A refusal-kind claim is carried
/// as the claim with status `unsupported`; use [`error_response`] for a failed call.
#[must_use]
pub fn claim_response(claim: &ClaimEnvelope) -> Value {
    let record = claim_record(claim);
    json!({ "status": record["status"].clone(), "claim": record })
}

/// Host record of an operation report, shaped as the schema's `operation_report`.
#[must_use]
pub fn operation_record(report: &OperationReport) -> Value {
    json!({
        "operation": report.operation.as_str(),
        "applicability": report.applicability.as_str(),
        "readiness": report.readiness.map(OperationReadiness::as_str),
        "coordinate": report.coordinate.as_deref(),
        "blockers": report
            .blockers
            .iter()
            .map(|b| json!({ "id": b.id.as_ref(), "reason": b.reason.as_ref(), "scientific": b.scientific }))
            .collect::<Vec<_>>(),
        "next_actions": report
            .next_actions
            .iter()
            .map(|a| json!({ "id": a.id.as_ref(), "description": a.description.as_ref() }))
            .collect::<Vec<_>>(),
        "neighbors": neighbor_records(&report.neighbors),
        "unmet_obligations": unmet_obligation_records(&report.unmet_obligations),
        "status": HostStatus::of_operation(report).as_str(),
    })
}

/// Host records of licensed neighbors, shaped as the schema's `licensed_neighbor`.
///
/// A neighbor names the premises it changes; it is an explicit alternative the
/// caller chooses, never an automatic fallback.
#[must_use]
pub fn neighbor_records(neighbors: &[LicensedNeighbor]) -> Vec<Value> {
    neighbors
        .iter()
        .map(|n| {
            json!({
                "coordinate": n.coordinate.as_ref(),
                "changed": n.changed
                    .iter()
                    .map(|c| json!({
                        "axis": c.axis.as_ref(),
                        "from": c.from.as_ref(),
                        "to": c.to.as_ref(),
                    }))
                    .collect::<Vec<_>>(),
                "required_action": n.required_action.as_ref(),
            })
        })
        .collect()
}

/// Host records of unresolved obligations, shaped as the schema's `unmet_obligation`.
#[must_use]
pub fn unmet_obligation_records(obligations: &[ObligationRecord]) -> Vec<Value> {
    obligations
        .iter()
        .map(|o| {
            json!({
                "id": o.id.as_ref(),
                "scope": o.scope.as_str(),
                "kind": o.kind.as_str(),
                "status": o.status.as_str(),
                "required_check": o.required_check.as_deref(),
                "description": o.description.as_ref(),
            })
        })
        .collect()
}
