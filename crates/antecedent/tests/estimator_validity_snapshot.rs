//! The estimator validity inventory: for every supported cell, which estimators estimate the
//! cell's quantity (declarative, nothing executes), which the cell lists, and which are valid
//! but unlisted (the under-support inventory).
//!
//! `UPDATE_ESTIMATOR_VALIDITY=1` rewrites `parity/estimator_validity.toml`; otherwise the file
//! must match.
//!
//! SPDX-License-Identifier: MIT OR Apache-2.0

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::PathBuf;

use antecedent::strategy_table::{EstimatorId, estimator_targets_cell};
use antecedent::support::{cell_coordinate, supported_cells, supported_estimators};

const HEADER: &str = "# Generated by crates/antecedent/tests/estimator_validity_snapshot.rs.\n\
# Regenerate: UPDATE_ESTIMATOR_VALIDITY=1 cargo test -p antecedent --test estimator_validity_snapshot\n\
#\n\
# One row per supported cell. `valid`: estimators whose declared target (query kind, design\n\
# variant, inference mode; strategy_table/targets.rs) is the cell's quantity. `listed`: the\n\
# estimators the cell's evidence list names. `unlisted_valid`: valid minus listed, the\n\
# under-support inventory. `listed_not_valid`: listed minus valid, a declaration gap (a cell\n\
# lists an estimator the target table says does not estimate its quantity); it must be empty.\n";

struct Row {
    valid: Vec<&'static str>,
    listed: Vec<&'static str>,
    unlisted_valid: Vec<&'static str>,
    listed_not_valid: Vec<&'static str>,
}

fn array(out: &mut String, key: &str, values: &[&str]) {
    if values.is_empty() {
        let _ = writeln!(out, "{key} = []");
        return;
    }
    let _ = writeln!(out, "{key} = [");
    for value in values {
        let _ = writeln!(out, "  \"{value}\",");
    }
    out.push_str("]\n");
}

fn rows() -> BTreeMap<String, Row> {
    let mut rows = BTreeMap::new();
    for cell in supported_cells() {
        let mut valid: Vec<&'static str> = EstimatorId::ALL
            .iter()
            .filter(|estimator| estimator_targets_cell(cell, **estimator).is_ok())
            .map(EstimatorId::as_str)
            .collect();
        valid.sort_unstable();
        let mut listed: Vec<&'static str> = supported_estimators(cell).to_vec();
        listed.sort_unstable();
        listed.dedup();
        let unlisted_valid = valid.iter().copied().filter(|e| !listed.contains(e)).collect();
        let listed_not_valid = listed.iter().copied().filter(|e| !valid.contains(e)).collect();
        rows.insert(cell_coordinate(cell), Row { valid, listed, unlisted_valid, listed_not_valid });
    }
    rows
}

fn render(rows: &BTreeMap<String, Row>) -> String {
    let mut out = String::from(HEADER);
    for (coordinate, row) in rows {
        out.push_str("\n[[cell]]\n");
        let _ = writeln!(out, "coordinate = \"{coordinate}\"");
        array(&mut out, "valid", &row.valid);
        array(&mut out, "listed", &row.listed);
        array(&mut out, "unlisted_valid", &row.unlisted_valid);
        array(&mut out, "listed_not_valid", &row.listed_not_valid);
    }
    out
}

fn snapshot_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../parity/estimator_validity.toml")
}

#[test]
fn estimator_validity_matches_the_snapshot() {
    let rows = rows();
    assert!(!rows.is_empty(), "the support matrix has no supported cell");
    let rendered = render(&rows);
    let path = snapshot_path();
    if std::env::var_os("UPDATE_ESTIMATOR_VALIDITY").is_some_and(|value| value == "1") {
        std::fs::write(&path, &rendered).expect("write parity/estimator_validity.toml");
        return;
    }
    let committed = std::fs::read_to_string(&path).unwrap_or_else(|error| {
        panic!(
            "{}: {error}; generate it with UPDATE_ESTIMATOR_VALIDITY=1 cargo test -p antecedent \
             --test estimator_validity_snapshot",
            path.display()
        )
    });
    assert!(
        committed.replace("\r\n", "\n") == rendered,
        "parity/estimator_validity.toml is stale; regenerate it with UPDATE_ESTIMATOR_VALIDITY=1"
    );
}

#[test]
fn a_cell_lists_only_estimators_that_estimate_its_quantity() {
    let offenders: Vec<String> = rows()
        .into_iter()
        .filter(|(_, row)| !row.listed_not_valid.is_empty())
        .map(|(coordinate, row)| format!("{coordinate}: {}", row.listed_not_valid.join(", ")))
        .collect();
    assert!(
        offenders.is_empty(),
        "cells list estimators the target table says do not estimate their quantity:\n{}",
        offenders.join("\n")
    );
}
