/// Effect of `x_{t-1}` on `y_t`.
const BETA1: f64 = 0.8;
/// Effect of `x_{t-2}` on `y_t` in the multi-step DGP (nonzero second lag).
const BETA2: f64 = 0.4;
const DRAWS: usize = 400;
const LEVEL: f64 = 0.9;
/// Treatment persistence used when the outcome residual is iid.
const IID_TREATMENT_RHO: f64 = 0.5;

/// Noise family of the treatment and the outcome residual.
#[derive(Clone, Copy, Debug, PartialEq)]
enum Noise {
    /// iid residual; the treatment stays AR(1) at [`IID_TREATMENT_RHO`].
    Iid,
    /// AR(1) treatment and residual at this coefficient.
    Ar1(f64),
    /// AR(2)(0.3, 0.5) treatment and residual: dominant root 0.87, so the
    /// autocorrelation decays far more slowly than an AR(1) fitted to its first lag.
    Ar2,
    /// ARMA(1,1)(φ 0.5, θ 0.4) treatment and residual: not in the AR(q) family the
    /// tempering factor fits.
    Arma11,
    /// MA(2)(0.6, 0.4) treatment and residual: finite memory, no AR representation
    /// of finite order.
    Ma2,
}

impl Noise {
    /// `(φ, θ)` of the ARMA families generated by [`arma_noise`].
    const fn arma(self) -> Option<(&'static [f64], &'static [f64])> {
        match self {
            Self::Ar2 => Some((&[0.3, 0.5], &[])),
            Self::Arma11 => Some((&[0.5], &[0.4])),
            Self::Ma2 => Some((&[], &[0.6, 0.4])),
            Self::Iid | Self::Ar1(_) => None,
        }
    }

    fn label(self) -> String {
        match self {
            Self::Iid => format!("iid residual (treatment rho {IID_TREATMENT_RHO})"),
            Self::Ar1(rho) => format!("AR(1) rho={rho}"),
            Self::Ar2 => "AR(2)(0.3, 0.5)".to_string(),
            Self::Arma11 => "ARMA(1,1)(0.5, 0.4)".to_string(),
            Self::Ma2 => "MA(2)(0.6, 0.4)".to_string(),
        }
    }
}

/// Noise regime: family and series length.
#[derive(Clone, Copy, Debug)]
struct Regime {
    noise: Noise,
    n: usize,
    seed: u64,
}

impl Regime {
    const IID: Self = Self { noise: Noise::Iid, n: 160, seed: 1_000_000 };
    const RHO05_N160: Self = Self { noise: Noise::Ar1(0.5), n: 160, seed: 2_000_000 };
    const RHO09_N400: Self = Self { noise: Noise::Ar1(0.9), n: 400, seed: 3_000_000 };
    const RHO05_N60: Self = Self { noise: Noise::Ar1(0.5), n: 60, seed: 4_000_000 };
    const AR2_N400: Self = Self { noise: Noise::Ar2, n: 400, seed: 5_000_000 };
    const AR2_N160: Self = Self { noise: Noise::Ar2, n: 160, seed: 6_000_000 };
    const AR2_N60: Self = Self { noise: Noise::Ar2, n: 60, seed: 7_000_000 };
    const AR2_N100: Self = Self { noise: Noise::Ar2, n: 100, seed: 8_000_000 };
    const ARMA11_N60: Self = Self { noise: Noise::Arma11, n: 60, seed: 9_000_000 };
    const ARMA11_N100: Self = Self { noise: Noise::Arma11, n: 100, seed: 10_000_000 };
    const ARMA11_N160: Self = Self { noise: Noise::Arma11, n: 160, seed: 11_000_000 };
    const ARMA11_N400: Self = Self { noise: Noise::Arma11, n: 400, seed: 12_000_000 };
    const MA2_N60: Self = Self { noise: Noise::Ma2, n: 60, seed: 13_000_000 };
    const MA2_N160: Self = Self { noise: Noise::Ma2, n: 160, seed: 14_000_000 };

    fn label(self) -> String {
        format!("{} n={}", self.noise.label(), self.n)
    }

    /// The regime at this run's sample-size grid point (`n` is the base point).
    fn at_grid(self) -> Self {
        Self { n: grid_n(self.n), ..self }
    }

    /// Stream seed for `rep`. The harness generator uses `seed | 1`, so streams
    /// must differ above bit 0: offsets are odd and ten apart per replicate.
    fn stream(self, rep: u64, k: u64) -> u64 {
        self.seed + 10 * rep + 2 * k + 1
    }

    /// Treatment series with marginal SD `sd`.
    fn treatment(self, sd: f64, seed: u64) -> Vec<f64> {
        match self.noise {
            Noise::Iid => ar1_noise(self.n, IID_TREATMENT_RHO, sd, seed),
            Noise::Ar1(rho) => ar1_noise(self.n, rho, sd, seed),
            family => {
                let (phi, theta) = family.arma().unwrap();
                arma_noise(self.n, phi, theta, sd, seed)
            }
        }
    }

    /// Residual (or innovation) series with marginal SD `sd`.
    fn residual(self, sd: f64, seed: u64) -> Vec<f64> {
        match self.noise {
            Noise::Iid => ar1_noise(self.n, 0.0, sd, seed),
            Noise::Ar1(rho) => ar1_noise(self.n, rho, sd, seed),
            family => {
                let (phi, theta) = family.arma().unwrap();
                arma_noise(self.n, phi, theta, sd, seed)
            }
        }
    }
}

/// Stationary ARMA(φ, θ) noise with marginal SD `sd` (500-step burn-in): the
/// unit-innovation process is scaled by `1 / sqrt(Σ ψ_k²)` of its MA(∞) weights.
fn arma_noise(n: usize, phi: &[f64], theta: &[f64], sd: f64, seed: u64) -> Vec<f64> {
    let mut ma_inf = vec![1.0];
    for k in 1..2_000 {
        let mut v = theta.get(k - 1).copied().unwrap_or(0.0);
        for (j, f) in phi.iter().enumerate() {
            if k > j {
                v += f * ma_inf[k - 1 - j];
            }
        }
        ma_inf.push(v);
    }
    let scale = sd / ma_inf.iter().map(|w| w * w).sum::<f64>().sqrt();
    let mut z = common::calibration::gaussian(seed);
    let burn = 500;
    let mut innovations = Vec::with_capacity(n + burn);
    let mut series: Vec<f64> = Vec::with_capacity(n + burn);
    for t in 0..n + burn {
        let innovation = z();
        let mut next = innovation;
        for (j, f) in phi.iter().enumerate() {
            if t > j {
                next += f * series[t - 1 - j];
            }
        }
        for (j, g) in theta.iter().enumerate() {
            if t > j {
                next += g * innovations[t - 1 - j];
            }
        }
        innovations.push(innovation);
        series.push(next);
    }
    series[burn..].iter().map(|v| scale * v).collect()
}

/// `y_t = 0.8 x_{t-1} + beta2 x_{t-2} + e_t`, `x` and `e` independent draws of the
/// regime's noise family.
fn series_xy(regime: Regime, rep: u64, beta2: f64) -> TimeSeriesData {
    let x = regime.treatment(0.5, regime.stream(rep, 0));
    let e = regime.residual(0.35, regime.stream(rep, 1));
    let mut y = vec![0.0; regime.n];
    for t in 2..regime.n {
        y[t] = BETA1 * x[t - 1] + beta2 * x[t - 2] + e[t];
    }
    TimeSeriesData::from_f64_columns([("x", x.as_slice()), ("y", y.as_slice())], 1).unwrap()
}

/// `x_{t-1} → y_t` (Pulse / single-step Sustained DGP has `beta2 = 0`).
fn lag1_dag() -> TemporalDag {
    let mut g = TemporalDag::empty();
    let x1 = ensure_lagged(&mut g, VariableId::from_raw(0), Lag::from_raw(1)).unwrap();
    let y0 = ensure_lagged(&mut g, VariableId::from_raw(1), Lag::CONTEMPORANEOUS).unwrap();
    g.insert_directed(x1, y0).unwrap();
    g
}

/// `x_{t-1} → y_t`, `x_{t-2} → y_t` (multi-step DGP).
fn lag12_dag() -> TemporalDag {
    let mut g = lag1_dag();
    let x2 = ensure_lagged(&mut g, VariableId::from_raw(0), Lag::from_raw(2)).unwrap();
    let y0 = ensure_lagged(&mut g, VariableId::from_raw(1), Lag::CONTEMPORANEOUS).unwrap();
    g.insert_directed(x2, y0).unwrap();
    g
}

fn pulse() -> TemporalEffectQuery {
    TemporalEffectQuery::pulse(VariableId::from_raw(0), VariableId::from_raw(1), 1.0)
        .with_policy(TemporalPolicy::pulse(-1))
        .with_horizon_steps(1)
}

fn single_sustained() -> TemporalEffectQuery {
    TemporalEffectQuery::sustained(VariableId::from_raw(0), VariableId::from_raw(1), -1, 1.0)
        .with_policy(TemporalPolicy::sustained(-1, -1))
        .with_horizon_steps(1)
}

fn multi_sustained() -> TemporalEffectQuery {
    TemporalEffectQuery::sustained(VariableId::from_raw(0), VariableId::from_raw(1), -2, 1.0)
        .with_policy(TemporalPolicy::sustained(-2, -1))
        .with_horizon_steps(1)
}

fn bayes() -> InferenceMode {
    InferenceMode::Bayesian(BayesianConfig::conjugate().n_draws(DRAWS).prior_scale(10.0))
}

/// Run the study and keep it beside its result, so a coverage tally can bind
/// the execution to the construction the runtime reported.
fn run(
    data: TimeSeriesData,
    graph: impl Into<antecedent::AcceptedGraph>,
    query: TemporalEffectQuery,
    prior: Option<ClassPrior>,
    seed: u64,
) -> (Study, StudyResult) {
    let mut builder = Study::series(data)
        .graph(graph.into())
        .query(CausalQuery::TemporalEffect(query))
        .inference(bayes());
    if let Some(prior) = prior {
        builder = builder.class_prior(prior);
    }
    let study = builder.refute(RefuteSuite::None).bootstrap_replicates(0).build().unwrap();
    let result = study.run(&ExecutionContext::for_tests(seed)).unwrap();
    (study, result)
}

fn credible_interval_at(result: &StudyResult, level: f64) -> Option<(f64, f64)> {
    let post = result.posterior.as_ref()?;
    let draws = post.draws.column(post.effect_column()?).ok()?;
    quantile_interval(draws, level)
}

fn credible_interval(result: &StudyResult) -> Option<(f64, f64)> {
    credible_interval_at(result, LEVEL)
}

#[derive(Clone, Copy, Debug)]
enum Cell {
    Pulse,
    SingleSustained,
    MultiSustained,
}

impl Cell {
    fn query(self) -> TemporalEffectQuery {
        match self {
            Self::Pulse => pulse(),
            Self::SingleSustained => single_sustained(),
            Self::MultiSustained => multi_sustained(),
        }
    }

    const fn beta2(self) -> f64 {
        match self {
            Self::MultiSustained => BETA2,
            Self::Pulse | Self::SingleSustained => 0.0,
        }
    }

    /// True causal contrast of a unit (sustained) treatment change.
    const fn truth(self) -> f64 {
        BETA1 + self.beta2()
    }

    fn graph(self) -> TemporalDag {
        match self {
            Self::MultiSustained => lag12_dag(),
            Self::Pulse | Self::SingleSustained => lag1_dag(),
        }
    }
}

/// Gated at 90%; the runtime's reported 95% credible interval is scored on the
/// same replicates and recorded. `measured` names a grid point as a boundary.
fn coverage(test: &'static str, cell: Cell, regime: Regime, measured: [Option<f64>; 3]) {
    let regime = regime.at_grid();
    let key = RecordKey { test, dgp: "series_xy", interval: "posterior_quantile" };
    let mut tally = CoverageTally::for_record(key, LEVEL);
    let mut reported = CoverageTally::for_record(key, REPORTED_LEVEL).unasserted();
    let runs = map_replicates(n_sim(), |rep| {
        let data = series_xy(regime, rep, cell.beta2());
        run(data, cell.graph(), cell.query(), None, 7 + rep)
    });
    for (study, result) in &runs {
        bind_all(&mut [&mut tally, &mut reported], study, result);
        tally.record(credible_interval(result), cell.truth());
        reported.record(credible_interval_at(result, REPORTED_LEVEL), cell.truth());
    }
    tally.assert_boundary_at(measured);
    reported.emit();
}

