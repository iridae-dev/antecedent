//! Coverage of Bayesian temporal Pulse / Sustained credible intervals (R-9).
//!
//! Every replicate runs the staged `Study` path. The treatment and the outcome
//! residual are independent stationary processes of one noise family
//! ([`Noise`]): AR(1) (`common::calibration::ar1_noise`), AR(2)(0.3, 0.5), an
//! ARMA(1,1)(0.5, 0.4) and an MA(2)(0.6, 0.4) robustness design. The treatment's
//! persistence is latent (the temporal identifier certifies no autoregressive
//! treatment edge), and the residual autocorrelation is latent too, so every DGP
//! sits inside the stated identification assumptions. With a persistent
//! treatment the score `x̃_t e_t` inherits the residual autocorrelation — the
//! case an iid Normal–Inverse-Gamma likelihood understates. The iid-residual
//! regime keeps a persistent treatment, so it checks that the dependence
//! correction does not over-widen when the iid likelihood is right.
//!
//! Ignored tests run via `scripts/gate_calibration.sh`.
//!
//! SPDX-License-Identifier: MIT OR Apache-2.0

