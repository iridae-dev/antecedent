"""Retained black-box Ananke reference for the mixed-source external fixture.

Regenerates the three Ananke cases (OneLineGID, OneLineAID and OneLineID) of
`expected.json` through the package's public classes and checks the verdict and the
printed identifying functional against the frozen record.  The graphs, experiments and
queries are pinned below independently of the fixture, so a changed scenario is reported
rather than followed.  The four dosearch cases are regenerated by `reference.R`.

The script imports no Antecedent code and reads no Ananke source or test file; Ananke is
isolated locked tooling outside the product runtime and ordinary CI.

    uv run --frozen --script conformance/identify/mixed_source_external/reference.py --check
    uv run --frozen --script conformance/identify/mixed_source_external/reference.py --check --self-test

SPDX-License-Identifier: MIT OR Apache-2.0
"""

from __future__ import annotations

import argparse
import copy
import importlib.metadata
import json
import warnings
from pathlib import Path

warnings.filterwarnings("ignore")

from ananke.graphs import ADMG  # noqa: E402
from ananke.identification import OneLineAID, OneLineGID, OneLineID  # noqa: E402

HERE = Path(__file__).resolve().parent
PINS = {"ananke-causal": "0.5.0", "scipy": "1.11.4"}

NODES = ["X1", "X2", "W", "Y"]
DIRECTED = [["X1", "W"], ["W", "Y"], ["X2", "Y"]]
BIDIRECTED = [["X1", "X2"], ["X1", "W"], ["X2", "Y"]]
QUERY = {"outcomes": ["Y"], "treatments": ["X1", "X2"]}
# Pinned scenario coordinates for the cases this script owns.
SPECS = {
    "ananke_gid_two_experiments": {
        "oracle": "ananke_onelinegid",
        "inputs": [
            {"study": "exp-x1", "do": ["X1"], "measured": ["W", "X2", "Y"]},
            {"study": "exp-x2", "do": ["X2"], "measured": ["W", "X1", "Y"]},
        ],
    },
    "ananke_aid_ancestral_margin": {
        "oracle": "ananke_onelineaid",
        "inputs": [
            {"study": "exp-x1-ancestral", "do": ["X1"], "measured": ["W"]},
            {"study": "exp-x2", "do": ["X2"], "measured": ["W", "X1", "Y"]},
        ],
    },
    "ananke_observational_only": {
        "oracle": "ananke_onelineid",
        "inputs": [
            {"study": "obs", "do": [], "measured": ["X1", "X2", "W", "Y"]}
        ],
    },
}


def graph() -> ADMG:
    return ADMG(
        NODES,
        di_edges=[tuple(e) for e in DIRECTED],
        bi_edges=[tuple(e) for e in BIDIRECTED],
    )


def experiment(study: dict) -> ADMG:
    """The experiment's graph: treatments fixed, restricted to what it measures."""
    g = graph()
    g.fix(study["do"])
    kept = set(study["do"]) | set(study["measured"])
    return g if kept == set(NODES) else g.subgraph(sorted(kept))


def regenerate(name: str) -> dict:
    spec = SPECS[name]
    args = (graph(), QUERY["treatments"], QUERY["outcomes"])
    if spec["oracle"] == "ananke_onelineid":
        identified = bool(OneLineID(*args).id())
        return {"identified": identified}
    cls = OneLineGID if spec["oracle"] == "ananke_onelinegid" else OneLineAID
    runner = cls(*args)
    experiments = [experiment(s) for s in spec["inputs"]]
    identified = bool(runner.id(experiments))
    out = {"identified": identified}
    if identified:
        out["functional"] = runner.functional(experiments)
    return out


def check(document: dict, actual: dict) -> list[str]:
    problems = []
    oracle = document.get("oracle", {})
    if oracle.get("kind") != "external_package":
        problems.append("incorrect oracle origin")
    versions = {r.get("project"): r.get("version") for r in oracle.get("reference", [])}
    if versions.get("ananke-causal") != PINS["ananke-causal"]:
        problems.append("missing pinned ananke-causal comparator")
    cases = {c.get("id"): c for c in document.get("cases", [])}
    for name, spec in SPECS.items():
        case = cases.get(name)
        if case is None:
            problems.append(f"{name}: case missing")
            continue
        coordinates = (
            case.get("nodes"),
            case.get("directed"),
            case.get("bidirected"),
            case.get("query"),
            case.get("inputs"),
            case.get("oracle"),
        )
        pinned = (NODES, DIRECTED, BIDIRECTED, QUERY, spec["inputs"], spec["oracle"])
        if coordinates != pinned:
            problems.append(f"{name}: graph, query or experiments changed")
        verbatim = case.get("oracle_output_verbatim")
        if verbatim != actual[name]:
            problems.append(
                f"{name}: verbatim output differs: regenerated={actual[name]!r}, frozen={verbatim!r}"
            )
        verdict = "identified" if actual[name]["identified"] else "not_identified"
        if case.get("oracle_result") != verdict:
            problems.append(f"{name}: summary verdict differs from the oracle")
        if case.get("oracle_formula") != actual[name].get("functional"):
            if "functional" in actual[name] or "oracle_formula" in case:
                problems.append(f"{name}: oracle_formula differs")
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", required=True)
    parser.add_argument("--self-test", action="store_true")
    args = parser.parse_args()
    for package, version in PINS.items():
        if importlib.metadata.version(package) != version:
            raise AssertionError(f"incorrect {package} version")
    document = json.loads((HERE / "expected.json").read_text(encoding="utf-8"))
    actual = {name: regenerate(name) for name in SPECS}
    problems = check(document, actual)
    if args.self_test:

        def must_fail(label: str, wrong: dict) -> None:
            if not check(wrong, actual):
                problems.append(f"fault escaped: {label}")

        def case_of(doc: dict, name: str) -> dict:
            return next(c for c in doc["cases"] if c["id"] == name)

        for name in SPECS:
            wrong = copy.deepcopy(document)
            case_of(wrong, name)["oracle_output_verbatim"] = {"identified": True, "functional": "p(Y)"}
            must_fail(f"{name} altered output", wrong)
            wrong = copy.deepcopy(document)
            case_of(wrong, name)["oracle_result"] = (
                "not_identified" if case_of(wrong, name)["oracle_result"] == "identified" else "identified"
            )
            must_fail(f"{name} flipped verdict", wrong)
            wrong = copy.deepcopy(document)
            case_of(wrong, name)["bidirected"] = []
            must_fail(f"{name} changed graph", wrong)
            wrong = copy.deepcopy(document)
            wrong["cases"] = [c for c in wrong["cases"] if c["id"] != name]
            must_fail(f"{name} removed case", wrong)
        wrong = copy.deepcopy(document)
        wrong["oracle"]["kind"] = "closed_form"
        must_fail("false origin", wrong)
        wrong = copy.deepcopy(document)
        wrong["oracle"]["reference"][0]["version"] = "0.0.0"
        must_fail("wrong comparator pin", wrong)
    print("\n".join(problems) if problems else "Ananke mixed-source references and fault controls passed")
    return int(bool(problems))


if __name__ == "__main__":
    raise SystemExit(main())
